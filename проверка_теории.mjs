// ---- 3. Явный Эйлер против симплектического (Верле) ------------------------
console.log('\n3. ИНТЕГРИРОВАНИЕ ОСЦИЛЛЯТОРА: сохраняется ли энергия');
function энергия(метод, шагов, w){
  let x = 1, v = 0;
  const a = xx => -w*w*xx;
  for (let i = 0; i < шагов; i++){
    if (метод === 'эйлер'){ const ускор = a(x); v += ускор; x += v; }
    else { v += a(x)/2; x += v; v += a(x)/2; }
  }
  return (v*v + w*w*x*x) / (w*w);       // нормируем к начальной
}
for (const w of [.01, .05, .2]){
  const э = энергия('эйлер', 20000, w), в = энергия('верле', 20000, w);
  console.log(`   w=${w}: эйлер ×${э.toFixed(3)}  верле ×${в.toFixed(3)}  (идеал 1.000)`);
}

// ---- 4. Формула ухода частоты у мягкой пружины -----------------------------
console.log('\n4. ДУФФИНГ: ω(A) = ω₀·√(1 + 3βA²/4α) — совпадает ли');
function частота_дуффинга(w0, отн, A){
  const α = w0*w0, β = -α*отн;
  let x = A, v = 0, прошлый = -1, пер = [];
  for (let i = 0; i < 400000; i++){
    const ускор = -α*x - β*x*x*x;
    v += ускор/2; x += v; v += (-α*x - β*x*x*x)/2;
    if (v > 0 && x > 0 && x - v <= 0){ if (прошлый>=0) пер.push(i-прошлый); прошлый = i; }
  }
  пер.sort((a,b)=>a-b);
  const T = пер[пер.length>>1];
  return T ? 2*Math.PI/T : 0;
}
const w0 = .02;
for (const [отн, A] of [[.3,.5],[.3,1],[.6,.5],[.6,1]]){
  const изм = частота_дуффинга(w0, отн, A);
  const прогноз = w0*Math.sqrt(Math.max(.01, 1 - 3*отн*A*A/4));
  console.log(`   мягкость=${отн} A=${A}: измерено ${изм.toFixed(5)}  формула ${прогноз.toFixed(5)}  расх ${(Math.abs(изм-прогноз)/прогноз*100).toFixed(1)}%`);
}
