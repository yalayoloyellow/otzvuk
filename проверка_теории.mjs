// Проверка КАЖДОГО утверждения из РАЗБОР.md. Не «кажется верным», а счёт.
// Модель генератора здесь пишется с нуля, отдельно от движка: проверять
// теорию его же кодом — значит проверять код собой.

const ln = Math.log, exp = Math.exp;

// ---- 1. Период генератора против формулы даташита -------------------------
// V' = (Vвых − V)/RC, пороги Vp и Vn, выход {0, Vdd}
function период_модель(Vdd, Vp, Vn, RC, SR, секунд){
  let v = Vn, q = 1, t = 0, прошлый = -1, периоды = [];
  const dt = 1/SR, k = 1 - exp(-dt/RC);
  for (let i = 0; i < SR*секунд; i++){
    const цель = q ? Vdd : 0;
    v += (цель - v) * k;
    if (q && v > Vp){ q = 0; if (прошлый >= 0) периоды.push(t - прошлый); прошлый = t; }
    else if (!q && v < Vn) q = 1;
    t += dt;
  }
  периоды.sort((a,b)=>a-b);
  return периоды[периоды.length>>1] || 0;
}
function период_формула(Vdd, Vp, Vn, RC){
  return RC * ln( ((Vdd-Vn)*Vp) / ((Vdd-Vp)*Vn) );
}
console.log('1. ПЕРИОД ГЕНЕРАТОРА против формулы даташита');
for (const [RC, SR] of [[1e-3, 48000], [1e-4, 48000], [3e-5, 48000], [1e-5, 48000]]){
  const т = период_формула(1, 2/3, 1/3, RC);
  const м = период_модель(1, 2/3, 1/3, RC, SR, .6);
  const ош = Math.abs(м-т)/т*100;
  console.log(`   RC=${RC}  формула ${(1/т).toFixed(1)} Гц  модель ${(1/м).toFixed(1)} Гц  ошибка ${ош.toFixed(2)}%`);
}

