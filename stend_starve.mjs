// СТЕНД STARVE. Один вопрос: не окажется ли реостат в питании на слух дублем
// DRIVE. Так же проверялись RELEASE и GAIN — оба не прошли и были сняты.
//
// Меряем то, чем эти вещи ОБЯЗАНЫ различаться, если различаются вообще:
//
//   скз            громкость. Обе ручки её меняют, и по ней не отличишь
//   крест-фактор   пик к скз. DRIVE его СЖИМАЕТ: сначала громче, потом
//                  плотнее, потом стена. Голод должен, наоборот, рвать —
//                  срывы генерации дают всплески при упавшем среднем
//   центроид       куда уехал спектр. Пороги триггера заданы долями питания:
//                  просадка уводит частоту, чего с DRIVE не происходит вовсе
//   разброс скз    насколько неровно звучит по секундам. Голод модулирует
//                  прибор САМ СОБОЙ, и это должно быть видно
//   шина           сколько осталось от ЭДС
import {readFileSync} from 'fs';
globalThis.sampleRate = 48000;
let K = null;
globalThis.registerProcessor = (n, k) => K = k;
globalThis.AudioWorkletProcessor = class {
  constructor(){ this.port = { postMessage(){}, set onmessage(f){this._f=f},
                               get onmessage(){return this._f} }; }
};
new Function(readFileSync('./chaos.worklet.js', 'utf8'))();

const БАЗА = {sway:.55, tone:.5, depth:.75, pulse:.2, hit:.35, spread:.15,
              drift:0, range:.5, gryzn:0, golos:0, gen1:1, gen2:1, gen3:0,
              link:0, dirt:0, petlya:0, kuda:0, naruzhu:0,
              zhat:0, drive:.15, master:1, starve:0};

function progon(izm, sek = 6, seed = 1626943591){
  const c = new K();
  c.port.onmessage({data:{t:'seed', v:seed}});
  c.port.onmessage({data:{t:'p', v:{...БАЗА, ...izm}}});
  const n = 128, blokov = Math.round(48000 * sek / n);
  const L = new Float32Array(n), R = new Float32Array(n);
  const все = [];
  let пик = 0, кв = 0, cnt = 0, шина = 0, шн = 0;
  const посек = []; let скв = 0, сн = 0;
  for (let b = 0; b < blokov; b++){
    c.process([[]], [[L, R]]);
    if (b < blokov * .2) continue;                 // переходный процесс мимо
    for (let i = 0; i < n; i++){
      const a = Math.abs(L[i]); if (a > пик) пик = a;
      кв += L[i] * L[i]; cnt++; скв += L[i] * L[i]; сн++;
      все.push(L[i]);
    }
    // Окно в ДЕСЯТУЮ секунды, а не в секунду. Голод давит шину через
    // сглаживающую ёмкость: постоянная времени тут сотые-десятые доли, и
    // посекундное окно усредняло бы ровно то, что мы ищем.
    if (сн >= 4800){ посек.push(Math.sqrt(скв / сн)); скв = 0; сн = 0; }
    шина += c.pr ? c.pr.bat.Vl / c.pr.sb.EMF : 0; шн++;
  }
  const скз = Math.sqrt(кв / cnt);
  // Центроид по спектру. ПРОРЕЖИВАТЬ ЗДЕСЬ НЕЛЬЗЯ: первый заход брал каждый
  // восьмой отсчёт, всё выше трёх килогерц заворачивалось, и центроид выходил
  // ровно 12000 — серединой полосы — для любой настройки. Число, одинаковое
  // для всего, это не измерение, а его отсутствие.
  const N = Math.min(8192, все.length), x = все.slice(0, N);
  const полос = 60, шаг = 24000 / полос;
  let сум = 0, вес = 0;
  for (let p = 1; p <= полос; p++){
    const f = (p - .5) * шаг;
    let re = 0, im = 0;
    for (let i = 0; i < N; i++){
      const w = 2 * Math.PI * f * i / 48000;
      // Окно Ханна: без него края куска дают ложную высокочастотную сыпь.
      const ok = .5 - .5 * Math.cos(2 * Math.PI * i / (N - 1));
      re += x[i] * ok * Math.cos(w); im += x[i] * ok * Math.sin(w);
    }
    const e = (re * re + im * im) / (N * N);
    сум += e * f; вес += e;
  }
  const ср = посек.reduce((a, b) => a + b, 0) / (посек.length || 1);
  const разб = Math.sqrt(посек.reduce((a, b) => a + (b - ср) ** 2, 0) / (посек.length || 1)) / (ср || 1e-9);
  return {скз, крест: пик / (скз || 1e-9), центроид: вес ? сум / вес : 0,
          разброс: разб, шина: шина / (шн || 1)};
}

const строка = (имя, r) =>
  `${имя.padEnd(16)}${r.скз.toFixed(4).padStart(8)}${r.крест.toFixed(2).padStart(9)}` +
  `${Math.round(r.центроид).toString().padStart(11)}${(r.разброс * 100).toFixed(1).padStart(10)}` +
  `${(r.шина * 100).toFixed(1).padStart(9)}`;

// Два режима: тихий (два генератора) и жадный (три генератора, счётчик
// вмешивается). Голод обязан быть заметнее там, где схема жрёт больше — если
// он не зависит от тока, значит это не голод, а просто громкость.
// ГЛАВНЫЙ ВОПРОС ВТОРОГО ЗАХОДА: не душит ли сглаживающая ёмкость сам смысл
// голода. Реостат создаёт просадку, ЗАВИСЯЩУЮ ОТ ТОКА, — но между ним и
// логикой стоит конденсатор развязки, и если он всё сглаживает, то от голода
// остаётся одна громкость. Тумблер SAG этот конденсатор снимает. Значит и
// мерить надо парой: с развязкой и без.
const РЕЖИМЫ = [['развязка цела', {}], ['SAG снят', {dirt:1}],
                ['жадный, SAG снят', {gen3:1, gryzn:.7, hit:.8, depth:1, dirt:1}]];
for (const [имя, реж] of РЕЖИМЫ){
  console.log(`\n=== ${имя} ===`);
  console.log('                     скз    крест   центроид   разброс     шина');
  console.log('STARVE');
  for (const v of [0, .3, .5, .7, .85, 1])
    console.log(строка('  ' + v.toFixed(2), progon({...реж, starve: v})));
  console.log('DRIVE');
  for (const v of [.15, .5, .85, 1])
    console.log(строка('  ' + v.toFixed(2), progon({...реж, drive: v})));
}
