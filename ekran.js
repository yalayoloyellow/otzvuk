// ============================================================================
//  ЭКРАН — общий движок отрисовки светящегося поля.
//
//  Отсюда берут вид и фигура, и шкалы панели. Не «похоже так же», а буквально
//  один код: иначе половины экрана расходятся на первой же правке, что уже
//  трижды и случилось.
//
//  Устройство одно на всех:
//    · свет копится в трёх полях по цвету и гаснет между кадрами
//    · ступень знакоместа берётся ПО РАНГУ — доля от всех горящих
//    · знак растёт вместе со ступенью, цвет и ореол берутся из таблицы
//    · слой на каждую пару (цвет, ступень), в слое чистый текст
//
//  Ни одного элемента на знакоместо: цвет знака в тексте требует обернуть его
//  в отдельный элемент, и элемент заводится на каждую смену цвета вдоль
//  строки. Подробно раскрашенное поле упиралось в это намертво.
// ============================================================================

export const CVETOV = 3, STUPENEY = 5, SLOEV = CVETOV * STUPENEY;

// ЗНАКИ ВЫБРАНЫ ПО ЧЕРНИЛАМ — по доле закрашенной клетки, замеренной
// отрисовкой в том же шрифте. Видимая яркость знакоместа это доля, умноженная
// на яркость цвета; одного цвета мало.
//
//     ·  6.0     ◦ 10.9     ⁘ 20.2     ✷ 32.3     ※ 53.0     ● 67.0
//
// Ряд ВЫСТРОЕН, а не подобран: каждая ступень примерно вдвое жирнее
// предыдущей (×1.82 ×1.85 ×1.60 ×1.64), все знаки одной ширины и круглые —
// ни квадратов, ни горизонтальных черт, оба вида отвергнуты раньше.
//
// И это одна история, а не набор значков: пятно люминофора под лучом. Слабый
// луч даёт искру, сильнее — колечко, ещё сильнее — россыпь, потом пятно
// начинает разбрасывать лучи, и на пределе это полная вспышка.
//
// У АКЦЕНТОВ РЯД СВОЙ, ЖИРНЕЕ НА СТУПЕНЬ. Поправка на зрение: цветовое
// разрешение глаза втрое-вчетверо ниже яркостного, и мелкий цветной знак
// усредняется по клетке почти в чёрное. Замер среднего цвета клетки для
// #ff7a5c: точка · даёт rgb(15,7,6), плотная звезда ※ — rgb(135,65,49). Тот
// же самый цвет, разница вдевятеро.
export const ZNAKI = [' ·◦⁘✷※',    // схема
                      ' ◦⁘✷※●',    // пост
                      ' ◦⁘✷※●'];   // голос
export const KOD = ZNAKI.map(r => [...r].map(c => c.charCodeAt(0)));

// КАКАЯ СТУПЕНЬ КАКОМУ КЛАССУ. Зелёный берёт все пять — он фон, и глубину
// держит он. У акцентов цвет один на четыре нижние ступени, а ореол свой у
// каждой: затемнённый красный на мелком знаке читается бурым, а не тихим
// красным.
export const KLASS = [['z0','z1','z2','z3','z4'],
                      ['kg0','kg1','kg2','k3','k4'],
                      ['sg0','sg1','sg2','s3','s4']];

// ДОЛИ СВЕРХУ от всех горящих знакомест. Последняя — граница отрисовки: всё,
// что тусклее, не рисуется вовсе. Тусклая масса это пустая порода: там, где
// след прошёл один раз и давно погас, смотреть не на что.
export const DOLI = [.10, .20, .30, .38, .46];
// Ниже этого знакоместо считается погасшим.
export const POROG_GOR = .02;
// Ниже этой ступени акцент не показывается: тонкий знак теряет цветность.
export const NIZ_AKCENTA = 3;

const GIST = new Int32Array(64);

// ГРАНИЦЫ СТУПЕНЕЙ ПО РАНГУ. Считаются ОДИН раз по главному полю и потом
// раздаются всем: если бы каждая шкала считала ранг у себя, шкала на десяти
// процентах всё равно показала бы раскалённое ядро — ранг съедает уровень.
//
// Корзины по КОРНЮ, а не по яркости напрямую: одно знакоместо, куда сошлись
// несколько мазков, бывает на порядок ярче остальных, и при равномерных
// корзинах всё поле сваливалось в нулевую, пороги садились в ноль и
// рисовались ВСЕ знакоместа, включая пустые.
export function grani(polya, out) {
  const N = polya[0].length;
  let mx = 1e-4, gorit = 0;
  for (let i = 0; i < N; i++) {
    let v = 0;
    for (let c = 0; c < polya.length; c++) v += polya[c][i];
    if (v > mx) mx = v;
  }
  GIST.fill(0);
  const obr = 1 / mx;
  for (let i = 0; i < N; i++) {
    let v = 0;
    for (let c = 0; c < polya.length; c++) v += polya[c][i];
    if (v > POROG_GOR) { GIST[(Math.sqrt(v * obr) * 63.999) | 0]++; gorit++; }
  }
  let nakop = 0, g = 0;
  for (let k = 63; k >= 0 && g < 5; k--) {
    nakop += GIST[k];
    while (g < 5 && nakop >= Math.max(1, Math.round(gorit * DOLI[g]))) {
      const u = k / 63.999;
      // Порог НИКОГДА не опускается до нуля: иначе под него попадают пустые
      // знакоместа и заливается всё поле.
      out[g++] = Math.max(POROG_GOR, u * u * mx);
    }
  }
  for (; g < 5; g++) out[g] = POROG_GOR;
  return out;
}

// ЭКРАН. Держит свои слои и переводит поля в текст. Всё, что ему нужно
// снаружи, — размер, элемент-хозяин и готовые границы ступеней.
export class Ekran {
  constructor(el, Sh, V) {
    this.el = el; this.peresoberi(Sh, V);
  }
  peresoberi(Sh, V) {
    this.Sh = Sh; this.V = V;
    const dlina = (Sh + 1) * V;
    // В шаблоне пробелы и переводы строк: каждый кадр слой не заполняется
    // заново по знаку, а копируется целиком — это одно движение памяти.
    this.shablon = new Uint16Array(dlina); this.shablon.fill(32);
    for (let y = 0; y < V; y++) this.shablon[y * (Sh + 1) + Sh] = 10;
    this.el.textContent = '';
    this.sloi = []; this.pre = []; this.bylo = new Uint8Array(SLOEV);
    for (let c = 0; c < CVETOV; c++) for (let t = 0; t < STUPENEY; t++) {
      this.sloi.push(new Uint16Array(dlina));
      const e = document.createElement('pre');
      e.className = 'sl ' + KLASS[c][t];
      this.el.appendChild(e); this.pre.push(e);
    }
    this.est = new Uint8Array(SLOEV);
  }
  // polya — три поля по числу цветов, gr — границы из grani()
  risuy(polya, gr) {
    const {Sh, V, sloi, pre, est, bylo} = this;
    const [P0, P1, P2] = polya;
    const g4 = gr[0], g3 = gr[1], g2 = gr[2], g1 = gr[3];
    const gris = Math.max(POROG_GOR, gr[4]);
    est.fill(0);
    for (let k = 0; k < SLOEV; k++) sloi[k].set(this.shablon);
    for (let y = 0; y < V; y++) {
      const yb = y * Sh, ob = y * (Sh + 1);
      for (let x = 0; x < Sh; x++) {
        const i = yb + x;
        const a0 = P0[i], a1 = P1[i], a2 = P2[i];
        const v = a0 + a1 + a2;
        if (v < gris) continue;
        const st = v >= g4 ? 4 : v >= g3 ? 3 : v >= g2 ? 2 : v >= g1 ? 1 : 0;
        // Цвет знакоместа — у кого его больше. Смешивать нечего: точка либо
        // принадлежит прибору, либо её сдвинула обработка, либо это голос.
        let c = a1 > a0 ? (a2 > a1 ? 2 : 1) : (a2 > a0 ? 2 : 0);
        // У АКЦЕНТА НЕТ ТУСКЛЫХ СТУПЕНЕЙ. Он либо виден в полную силу, либо
        // не виден вовсе — слабое вмешательство просто не помечается.
        //
        // Замер среднего цвета клетки для одного и того же #ff7a5c:
        //     на ступени 3 (знак ✷)  rgb(117, 52, 35)  — насыщенный красный
        //     на ступени 1 (знак ◦)  rgb( 28, 13, 10)  — бурое пятнышко
        // Половина красного в картине сидела на нижних ступенях, где знак
        // тонкий, и клетка вчетверо темнее. Оттого красное в фигуре и
        // читалось «тупо другим», чем красное на ползунке, где оно всё
        // наверху: цвет, ореол и ступень совпадали, а средний цвет клетки —
        // нет. Оттенками это не лечится, лечится отказом от тусклых ступеней.
        if (c && st < NIZ_AKCENTA) c = 0;
        const k = c * STUPENEY + st;
        sloi[k][ob + x] = KOD[c][st + 1];
        est[k] = 1;
      }
    }
    // Пустой слой не переводим в строку вовсе, и очищаем его только когда он
    // ТОЛЬКО ЧТО опустел.
    for (let k = 0; k < SLOEV; k++) {
      if (est[k]) { pre[k].textContent = vStroku(sloi[k]); bylo[k] = 1; }
      else if (bylo[k]) { pre[k].textContent = ''; bylo[k] = 0; }
    }
  }
}

// Буфер знаков в строку. Через раскодировщик — одним нативным движением на
// весь буфер. Сборка по восемь тысяч доводов за вызов оказалась в семьдесят
// раз дороже.
const RASKOD = typeof TextDecoder !== 'undefined'
  && new Uint16Array(new Uint8Array([65, 0]).buffer)[0] === 65
  ? new TextDecoder('utf-16le') : null;
export function vStroku(buf) {
  if (RASKOD) return RASKOD.decode(buf);
  let s = '';
  for (let i = 0; i < buf.length; i += 8192)
    s += String.fromCharCode.apply(null, buf.subarray(i, Math.min(i + 8192, buf.length)));
  return s;
}
