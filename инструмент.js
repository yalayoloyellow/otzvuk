// ============================================================================
//  ИНСТРУМЕНТ — всё с клавиатуры, вид ретро-терминальный.
//
//  Ничего автоматического: система не решает за тебя. Клавиша слева от пары
//  убавляет, справа прибавляет; Shift — мелкий шаг, чтобы попадать в узкие
//  места. Верхний ряд цифр — сцены: запомнить (Shift+цифра) и вернуться.
//
//  Приборы показывают, ГДЕ ты в системе: показатель Ляпунова (мера хаоса),
//  число вращения (в какое ритмическое отношение захватились узлы), шина
//  питания (насколько просажена), уровень. Это и есть карта, по которой
//  «зная, что крутишь, попадаешь в нужную область».
// ============================================================================
const $ = s => document.querySelector(s);
const clamp = (v,a,b) => v<a?a:v>b?b:v;

let ctx=null, node=null, идёт=false;
let отчёт={пик:0,rms:0,ляп:0,вращение:0,шина:1,осц:new Float32Array(256),
           узлы:[0,0,0,0,0,0],шаг:0,рисунок:new Uint8Array(32),удар:0};

// Пары клавиш: убавить / прибавить. Раскладка по смыслу, а не по алфавиту:
// слева звук, в середине форма, справа ритм.
const РУЧКИ=[
  {к:'частота',    м:['q','w'], имя:'высота'},
  {к:'разброс',    м:['a','s'], имя:'разброс'},
  {к:'связь',      м:['z','x'], имя:'СВЯЗЬ'},
  {к:'питание',    м:['e','r'], имя:'ПРОСАДКА'},
  {к:'гистерезис', м:['d','f'], имя:'гистерез'},
  {к:'логика',     м:['c','v'], имя:'логика'},
  {к:'фильтр',     м:['t','y'], имя:'срез'},
  {к:'резонанс',   м:['g','h'], имя:'резонанс'},
  {к:'обратная',   м:['b','n'], имя:'обратная'},
  {к:'грязь',      м:['u','i'], имя:'грязь'},
  {к:'асимметрия', м:['j','k'], имя:'асиммет'},
  {к:'сворачивание',м:['m',','], имя:'СВОРАЧ'},
  {к:'пульс',      м:['o','p'], имя:'ПУЛЬС'},
  {к:'делёж',      м:['l',';'], имя:'делёж'},
  {к:'качели',     м:["'",'\\'], имя:'КАЧЕЛИ'},
  {к:'струна',     м:['7','8'], имя:'СТРУНА'},
  {к:'натяг',      м:['9','0'], имя:'натяг'},
  {к:'мягкость',   м:['5','6'], имя:'мягкость'},
  {к:'затух',      м:['3','4'], имя:'затух'}
];
const p={};
for(const r of РУЧКИ) p[r.к]=0;
Object.assign(p,{частота:.35,разброс:.5,связь:.3,питание:.25,гистерезис:.5,
  логика:.3,фильтр:.6,резонанс:.2,обратная:.15,грязь:.3,сворачивание:0,
  асимметрия:.5,пульс:.4,делёж:.35,качели:.5,
  струна:.3,натяг:.35,мягкость:.45,затух:.5});

const сцены={};
let последняя=null, вспышка=0;

function шли(){ node&&node.port.postMessage({t:'p',v:p}); }

// ---- запуск ---------------------------------------------------------------
window.дбг={состояние:'не запускался',ошибка:null};
async function пуск(){
  if(идёт) return;
  window.дбг.состояние='запускаю';
  try{
  ctx=new AudioContext({latencyHint:'interactive'});
  await ctx.audioWorklet.addModule('хаос.worklet.js?v='+Date.now());
  node=new AudioWorkletNode(ctx,'хаос',{numberOfInputs:0,numberOfOutputs:1,
    outputChannelCount:[2]});
  node.connect(ctx.destination);
  node.port.onmessage=e=>{ отчёт=e.data; window.дбг.отчётов=(window.дбг.отчётов||0)+1; window.дбг.о=отчёт; };
  await ctx.resume();
  идёт=true; шли();
  window.дбг.состояние='играет';
  }catch(e){ window.дбг.ошибка=''+e; window.дбг.состояние='упал'; }
}

// Щелчок тоже запускает: клавиша не дойдёт, пока окно без фокуса.
addEventListener('pointerdown',()=>{ пуск(); });

// ---- клавиатура -----------------------------------------------------------
addEventListener('keydown',async e=>{
  if(e.metaKey||e.ctrlKey||e.altKey) return;
  const k=e.key.toLowerCase();
  if(!идёт){ await пуск(); if(k===' ') { e.preventDefault(); return; } }
  const шаг=e.shiftKey?.008:.04;

  for(const r of РУЧКИ){
    if(k===r.м[0]){ p[r.к]=clamp(p[r.к]-шаг,0,1); последняя=r; вспышка=6; шли(); e.preventDefault(); return; }
    if(k===r.м[1]){ p[r.к]=clamp(p[r.к]+шаг,0,1); последняя=r; вспышка=6; шли(); e.preventDefault(); return; }
  }
  if(k===' '){ node&&node.port.postMessage({t:'толчок'}); e.preventDefault(); return; }
  if(k>='1'&&k<='2'){                       // сцены: Shift — запомнить
    if(e.shiftKey) сцены[k]={...p};
    else if(сцены[k]){ Object.assign(p,сцены[k]); шли(); }
    e.preventDefault();
  }
});

// ---- рисунок: фазовый портрет и осциллограмма в ASCII ---------------------
const Ш=96, В=17;
const ГРАД=' ·:-=+*#%@';
function рисуй(){
  const холст=[];
  for(let y=0;y<В;y++) холст.push(new Array(Ш).fill(' '));
  const о=отчёт.осц, n=о.length;
  // фазовый портрет: сигнал против себя же со сдвигом — форма аттрактора
  const сдвиг=7;
  const плотн=[];
  for(let y=0;y<В;y++) плотн.push(new Float32Array(Ш));
  for(let i=0;i<n-сдвиг;i++){
    const x=clamp(о[i],-1,1), y=clamp(о[i+сдвиг],-1,1);
    const cx=Math.round((x*.5+.5)*(Ш-1)), cy=Math.round((1-(y*.5+.5))*(В-1));
    плотн[cy][cx]+=1;
  }
  let макс=0;
  for(let y=0;y<В;y++) for(let x=0;x<Ш;x++) if(плотн[y][x]>макс) макс=плотн[y][x];
  for(let y=0;y<В;y++) for(let x=0;x<Ш;x++){
    const v=плотн[y][x]/(макс||1);
    if(v>0) холст[y][x]=ГРАД[clamp(Math.round(v*(ГРАД.length-1)),1,ГРАД.length-1)];
  }
  return холст.map(r=>r.join('')).join('\n');
}

function полоса(v,ш,симв){
  const n=clamp(Math.round(v*ш),0,ш);
  return (симв||'▮').repeat(n)+'·'.repeat(ш-n);
}

function приборы(){
  // Разброс интервалов между щелчками: 0 — жёсткий захват, растёт — распад.
  // Показатель Ляпунова по траектории здесь врал (см. ядро), поэтому мерим
  // то, что слышно: ровность самих щелчков.
  const л=отчёт.разброс||0;
  const где = л<.02?'ЖЁСТКИЙ ЗАХВАТ' : л<.10?'ровно' : л<.28?'дышит'
            : л<.55?'КРАЙ ХАОСА' : 'распад';
  const цвет = л<.10?'тускло' : л<.55?'ярко':'тревога';
  const в=отчёт.вращение||0;
  // Число вращения: близкое к простому отношению — захват в ритмическую фигуру
  const прост=[[1,1],[2,1],[3,1],[3,2],[4,1],[4,3],[5,2],[5,4],[6,1],[8,1]];
  let бл='—', лучш=9;
  for(const [a,b] of прост){ const d=Math.abs(в-a/b); if(d<лучш&&d<.06){ лучш=d; бл=a+':'+b; } }
  // Пульс не рисуется по счётчику — его нет. Показываем сами медленные узлы:
  // видно, как они захватываются друг за друга.
  const м=отчёт.медл||[0,0,0];
  const лента=м.map(v=>{
    const n=clamp(Math.round((v*.5+.5)*11),0,11);
    return '·'.repeat(n)+'●'+'·'.repeat(11-n);
  }).join(' ');
  const стр=clamp(Math.abs(отчёт.струна||0)/2,0,1);
  return [
`  разброс <span class="${цвет}">${полоса(clamp(л*1.6,0,1),28)}</span> ${где}  ${(л*100).toFixed(0)}%`,
`  пульс ${лента}   струна ${полоса(стр,10)}`,
`  захват ${бл==='—'?'<span class="совсем">плывёт</span>':'<span class="ярко">'+бл+'</span>'}    шина ${полоса(clamp(отчёт.шина,0,1),12)}  уровень ${полоса(clamp(отчёт.пик,0,1),12)}`
  ].join('\n');
}

function ручки(){
  const строки=[];
  for(let i=0;i<РУЧКИ.length;i+=3){
    строки.push(РУЧКИ.slice(i,i+3).map(r=>{
      const свой=r===последняя&&вспышка>0;
      const имя=(r.имя+'        ').slice(0,8);
      const кл=r.м[0]+r.м[1];
      const б=полоса(p[r.к],10);
      const s=`${имя} ${б} ${кл}`;
      return свой?`<span class="ярко">${s}</span>`:`<span class="тускло">${s}</span>`;
    }).join('   '));
  }
  return строки.join('\n');
}

function кадр(){
  try{ кадр_(); }catch(e){ window.дбг.кадр=''+e; }
  requestAnimationFrame(кадр);
}
function кадр_(){
  if(вспышка>0) вспышка--;
  $('#шапка').innerHTML = идёт
    ? `<span class="совсем">о т з в у к · инструмент</span>`
    : `<span class="ярко">о т з в у к · инструмент</span>\n\n  нажми любую клавишу`;
  if(идёт){
    $('#рисунок').textContent=рисуй();
    $('#приборы').innerHTML=приборы();
    $('#ручки').innerHTML=ручки();
    $('#строка').innerHTML=
      '  shift — мелкий шаг · пробел — толчок · 1–2 сцена, shift+цифра запомнить';
  }
}
кадр();
