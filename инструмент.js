// ---- запуск ---------------------------------------------------------------
window.дбг={состояние:'не запускался',ошибка:null};
async function пуск(){
  if(идёт) return;
  window.дбг.состояние='запускаю';
  try{
  ctx=new AudioContext({latencyHint:'interactive'});
  await ctx.audioWorklet.addModule('хаос.worklet.js?v='+Date.now());
  node=new AudioWorkletNode(ctx,'хаос',{numberOfInputs:0,numberOfOutputs:1,
    outputChannelCount:[2]});
  node.connect(ctx.destination);
  node.port.onmessage=e=>{ отчёт=e.data; window.дбг.отчётов=(window.дбг.отчётов||0)+1; window.дбг.о=отчёт; };
  await ctx.resume();
  идёт=true; шли();
  window.дбг.состояние='играет';
  }catch(e){ window.дбг.ошибка=''+e; window.дбг.состояние='упал'; }
}

// Щелчок тоже запускает: клавиша не дойдёт, пока окно без фокуса.
addEventListener('pointerdown',()=>{ пуск(); });

// ---- клавиатура -----------------------------------------------------------
addEventListener('keydown',async e=>{
  if(e.metaKey||e.ctrlKey||e.altKey) return;
  const c=e.code;
  if(!идёт){ await пуск(); if(c==='Space'){ e.preventDefault(); return; } }
  if(c==='Tab'){ e.preventDefault(); страница=(страница+1)%СТРАНИЦЫ.length;
                 РУЧКИ=СТРАНИЦЫ[страница].ручки; держим.clear(); return; }

  for(const r of РУЧКИ){
    const знак = c===r.м[0] ? -1 : c===r.м[1] ? 1 : 0;
    if(!знак) continue;
    e.preventDefault();
    const было=держим.get(c);
    if(было){ было.живо=performance.now(); return; }     // автоповтор — подтверждение
    {
      const t=performance.now();
      держим.set(c,{ключ:r.к,знак,ручка:r,начало:t,живо:t,мелко:e.shiftKey});
      p[r.к]=clamp(p[r.к]+знак*(e.shiftKey?.004:.012),0,1);   // короткое нажатие тоже работает
      последняя=r; вспышка=6; шли();
    }
    return;
  }
  if(c==='Space'){ node&&node.port.postMessage({t:'толчок'}); e.preventDefault(); return; }
  const цифра=c.startsWith('Digit') ? c.slice(5) : null;
  if(цифра && цифра>='1' && цифра<='6'){
    if(e.shiftKey){ сцены[цифра]={...p}; сохраниСцены(); }
    else { const с=сцены[цифра]||СЦЕНЫ_ВСТРОЕННЫЕ[цифра];
           if(с){ Object.assign(p,с); шли(); } }
    e.preventDefault();
  }
});

// ---- рисунок: фазовый портрет и осциллограмма в ASCII ---------------------
const Ш=96, В=17;
const ГРАД=' ·:-=+*#%@';
function рисуй(){
  const холст=[];
  for(let y=0;y<В;y++) холст.push(new Array(Ш).fill(' '));
  const о=отчёт.осц, n=о.length;
  // фазовый портрет: сигнал против себя же со сдвигом — форма аттрактора
  const сдвиг=7;
  const плотн=[];
  for(let y=0;y<В;y++) плотн.push(new Float32Array(Ш));
  for(let i=0;i<n-сдвиг;i++){
    const x=clamp(о[i],-1,1), y=clamp(о[i+сдвиг],-1,1);
    const cx=Math.round((x*.5+.5)*(Ш-1)), cy=Math.round((1-(y*.5+.5))*(В-1));
    плотн[cy][cx]+=1;
  }
  let макс=0;
  for(let y=0;y<В;y++) for(let x=0;x<Ш;x++) if(плотн[y][x]>макс) макс=плотн[y][x];
  for(let y=0;y<В;y++) for(let x=0;x<Ш;x++){
    const v=плотн[y][x]/(макс||1);
    if(v>0) холст[y][x]=ГРАД[clamp(Math.round(v*(ГРАД.length-1)),1,ГРАД.length-1)];
  }
  return холст.map(r=>r.join('')).join('\n');
}

function полоса(v,ш,симв){
  const n=clamp(Math.round(v*ш),0,ш);
  return (симв||'▮').repeat(n)+'·'.repeat(ш-n);
}

function приборы(){
  // Разброс интервалов между щелчками: 0 — жёсткий захват, растёт — распад.
  // Показатель Ляпунова по траектории здесь врал (см. ядро), поэтому мерим
  // то, что слышно: ровность самих щелчков.
  const л=отчёт.разброс||0;
  const где = л<.02?'ЖЁСТКИЙ ЗАХВАТ' : л<.10?'ровно' : л<.28?'дышит'
            : л<.55?'КРАЙ ХАОСА' : 'распад';
  const цвет = л<.10?'тускло' : л<.55?'ярко':'тревога';
  const в=отчёт.вращение||0;
  // Число вращения: близкое к простому отношению — захват в ритмическую фигуру
  const прост=[[1,1],[2,1],[3,1],[3,2],[4,1],[4,3],[5,2],[5,4],[6,1],[8,1]];
  let бл='—', лучш=9;
  for(const [a,b] of прост){ const d=Math.abs(в-a/b); if(d<лучш&&d<.06){ лучш=d; бл=a+':'+b; } }
  // Пульс не рисуется по счётчику — его нет. Показываем сами медленные узлы:
  // видно, как они захватываются друг за друга.
  const м=отчёт.медл||[0,0,0];
  const лента=м.map(v=>{
    const n=clamp(Math.round((v*.5+.5)*11),0,11);
    return '·'.repeat(n)+'●'+'·'.repeat(11-n);
  }).join(' ');
  const стр=clamp(Math.abs(отчёт.струна||0)/2,0,1);
  return [
`  разброс <span class="${цвет}">${полоса(clamp(л*1.6,0,1),28)}</span> ${где}  ${(л*100).toFixed(0)}%`,
`  пульс ${лента}   струна ${полоса(стр,10)}`,
`  захват ${бл==='—'?'<span class="совсем">плывёт</span>':'<span class="ярко">'+бл+'</span>'}    шина ${полоса(clamp(отчёт.шина,0,1),12)}  уровень ${полоса(clamp(отчёт.пик,0,1),12)}`
  ].join('\n');
}

function ручки(){
  const строки=[`  <span class="совсем">страница</span> <b>${СТРАНИЦЫ[страница].имя}</b>`+
                `  <span class="совсем">Tab — вторая</span>`, ''];
  for(let i=0;i<РУЧКИ.length;i+=3){
    строки.push(РУЧКИ.slice(i,i+3).map(r=>{
      const свой=r===последняя&&вспышка>0;
      const имя=(r.имя+'        ').slice(0,8);
      const кл=r.подпись;
      const б=полоса(p[r.к],10);
      const s=`${имя} ${б} ${кл}`;
      return свой?`<span class="ярко">${s}</span>`:`<span class="тускло">${s}</span>`;
    }).join('   '));
  }
  return строки.join('\n');
}

