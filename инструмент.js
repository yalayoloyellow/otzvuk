// ============================================================================
//  ИНСТРУМЕНТ — всё с клавиатуры, вид ретро-терминальный.
//
//  Ничего автоматического: система не решает за тебя. Клавиша слева от пары
//  убавляет, справа прибавляет; Shift — мелкий шаг, чтобы попадать в узкие
//  места. Верхний ряд цифр — сцены: запомнить (Shift+цифра) и вернуться.
//
//  Приборы показывают, ГДЕ ты в системе: показатель Ляпунова (мера хаоса),
//  число вращения (в какое ритмическое отношение захватились узлы), шина
//  питания (насколько просажена), уровень. Это и есть карта, по которой
//  «зная, что крутишь, попадаешь в нужную область».
// ============================================================================
const $ = s => document.querySelector(s);
const clamp = (v,a,b) => v<a?a:v>b?b:v;

let ctx=null, node=null, идёт=false;
let отчёт={пик:0,rms:0,ляп:0,вращение:0,шина:1,осц:new Float32Array(256),
           узлы:[0,0,0,0,0,0],шаг:0,рисунок:new Uint8Array(32),удар:0};

// ---- ПАНЕЛЬ ----------------------------------------------------------------
// На приборе Срапионова наружу выходило три-четыре ручки, остальное впаяно
// намертво: это номиналы деталей, а не органы управления. Я же вывел все
// внутренние параметры разом — тридцать штук, и найти нужное стало нельзя.
//
// Теперь наружу шесть МАКРО-ручек, каждая из которых ведёт целую группу
// связанных величин так, как их вело бы одно вращение на панели. Внутренности
// остались, но живут по своим законам и наружу не торчат.
//
// Первые три ручки — КАЧЕЛИ, тот самый механизм: медленный генератор ведёт
// током заряд звукового, тот ездит по пяти октавам и внизу проваливается в
// треск. Одна ручка задаёт период рисунка, вторая — высоту и грязь, третья —
// насколько глубоко качели проваливаются. Всё остальное вторично и стоит
// после них.
const МАКРО=[
  {к:'качание',   м:['KeyQ','KeyW'], имя:'КАЧАНИЕ'},
  {к:'характер',  м:['KeyE','KeyR'], имя:'ХАРАКТЕР'},
  {к:'размах',    м:['KeyT','KeyY'], имя:'РАЗМАХ'},
  {к:'скважность',м:['KeyU','KeyI'], имя:'ИМПУЛЬС'},
  {к:'дребезг',   м:['KeyO','KeyP'], имя:'ДРЕБЕЗГ'},
  {к:'удар',      м:['KeyA','KeyS'], имя:'УДАР'},
  {к:'гуляние',   м:['KeyZ','KeyX'], имя:'ГУЛЯНИЕ'}
];
// Второй страницы нет и быть не должно. Всё, чего нет на панели, — это
// номиналы деталей: конденсаторы, резисторы, пороги конкретной микросхемы,
// ёмкость монтажа. Ими не «управляют», они впаяны.
//
// Для исполнителя они выглядят случайностью, хотя физически детерминированы:
// случайность здесь — это ровно то, к чему у него НЕТ ДОСТУПА, но что звучит.
// Поэтому случайность живёт не в сигнале, а в ЭКЗЕМПЛЯРЕ прибора: собрал —
// получил свой набор номиналов, и он твой, пока не пересоберёшь.
for(const r of МАКРО) r.подпись=r.м.map(c=>c.replace('Key','').toLowerCase()).join('');
const РУЧКИ=МАКРО;

// ---- ЭКЗЕМПЛЯР ПРИБОРА -----------------------------------------------------
// Номиналы из семени: у каждой сборки свои. Разброс небольшой — детали всё же
// из одного ящика, — но именно он делает прибор «этим», а не «таким же».
let семя=(Math.random()*4294967295)>>>0;
function изСемени(с){
  let x=с>>>0;
  return ()=>{ x=(Math.imul(x,1664525)+1013904223)>>>0; return x/4294967296; };
}
function пересобери(новое){
  семя = новое!==undefined ? новое>>>0 : (Math.random()*4294967295)>>>0;
  const r=изСемени(семя), м=(a,b)=>a+r()*(b-a);
  // Номиналов немного, потому что и деталей немного: свежесть батарейки,
  // общий перекос частотозадающих цепей. Разброс самих генераторов сидит
  // внутри ядра — там у каждого свой допуск.
  экземпляр={
    батарея: м(.06,.2),
    перекос: м(-.12,.12)
  };
  Object.assign(p, экземпляр);
  // Семя уходит В ЯДРО: там из него выводятся допуски всех генераторов и
  // резонанс излучателя. Без этой строки Tab менял только подпись.
  node&&node.port.postMessage({t:'семя', v:семя});
  шли();
}
let экземпляр={};

// Разводка макро-ручек во внутренние величины. Здесь и живёт то, что в
// железке было впаяно: соотношения номиналов, подобранные так, чтобы прибор
// звучал в любом положении, а не только в удачном.
function разведи(){
  const м=макро, в={}, пк=(экземпляр.перекос||0);

  // КАЧАНИЕ — резистор медленного генератора. Ручка задаёт ПЕРИОД, поэтому
  // слева десятки герц: качание такое частое, что слышится тембром, а не
  // рисунком. Справа доли герца — одно движение на несколько секунд.
  в.пульс = clamp(м.качание, 0, 1);

  // ХАРАКТЕР — управляющее смещение качелей: верхняя точка и вместе с ней
  // перекос импульса. Нижняя держится в области треска на всём ходу.
  в.частота = clamp(м.характер + пк*.35, 0, 1);
  в.фильтр = .58 + м.характер*.34;

  // РАЗМАХ — глубина качелей. На нуле прибор играет ровный тон.
  в.размах = м.размах;

  // ---- начало цепи: то, из чего сделан сам сигнал --------------------------
  // СКВАЖНОСТЬ — подстроечный резистор смещения. Постоянный ток подгоняет
  // заряд и тормозит разряд: импульс из симметричного делается узким, тон
  // уходит от полого к резкому. Складывается с током качелей и упирается
  // в общий предел — за ним генератор запирается.
  в.скважность = м.скважность;
  // ДРЕБЕЗГ — тепловой шум в цепи заряда. Триггер сэмплирует его в момент
  // решения, и фронты начинают дрожать: хрип живёт в самом сигнале, а не
  // подмешан поверх. Низкие ноты хрипят заметнее — так и в железе.
  в.дребезг = м.дребезг;

  // УДАР — добротность излучателя. Динамик это масса на подвесе; каждый
  // фронт пинает его, и он отвечает низом. У вялого низа почти нет, у
  // звонкого каждый импульс становится ударом, а диффузор на большом
  // сигнале упирается в ход — отсюда грязный бас.
  в.удар = м.удар;

  // ГУЛЯНИЕ — генератор вдесятеро медленнее качает период качелей: рисунок
  // остаётся рисунком, но перестаёт повторяться в точности.
  в.гуляние = м.гуляние;

  в.батарея = .12;
  return в;
}

// макро — то, что на панели; p — то, что уходит в движок
const макро={качание:.55, характер:.5, размах:.75, скважность:.2, дребезг:.15, удар:.35, гуляние:0};
const p={};
пересобери(семя);

let последняя=null, вспышка=0;
// Ручка должна ехать, а не прыгать. Шаг 4% при диапазоне высоты в семь с
// половиной октав давал треть октавы за нажатие — отсюда «жёсткие пороги»
// и ощущение цифры вместо аналога. Теперь базовый шаг мелкий, а при
// удержании клавиши он разгоняется, как крутилка под пальцем.
const держим=new Map();
setInterval(()=>{
  const t=performance.now();
  for(const [k,с] of держим){
    // Страховка от залипания — но мягкая. Прежняя требовала автоповтора,
    // а браузер шлёт его ТОЛЬКО для последней нажатой клавиши: при попытке
    // крутить две ручки разом первая молча отваливалась. Теперь верим
    // отпусканию и потере фокуса, а таймаут — только на совсем зависшее.
    if(t - с.живо > 6000){ держим.delete(k); continue; }
    const держится=(t-с.начало)/1000;
    // Короткое нажатие = РОВНО один шаг, сделанный при нажатии. Разгон
    // включается только после паузы: иначе быстрый тык давал и шаг, и
    // разгон разом, и ручка прыгала на несколько делений.
    if(держится < .28) continue;
    const разгон=Math.min(держится-.28, 2.2);
    const скорость=(.12+разгон*.8)*(с.мелко?.25:1);
    const шаг=скорость/60;
    макро[с.ключ]=clamp((макро[с.ключ]||0)+с.знак*шаг,0,1);
    последняя=с.ручка; вспышка=4;
  }
  if(держим.size) шли();
},1000/60);

function шли(){
  Object.assign(p, разведи());
  node&&node.port.postMessage({t:'p',v:p});
}

// Сцены переживают перезагрузку: найденную точку обидно терять.
// Площадки: какие сейчас прижаты и насколько притёрся контакт.
// Объявление потерялось при удалении блока пресетов — площадки молча не
// работали, хотя обработчик клавиш срабатывал.
const площадки=new Map();
const проводимость=new Float32Array(9);

// Проводимость ведётся плавно: контакт не идеальный ключ, он притирается
// под пальцем и отпускает с задержкой.
setInterval(()=>{
  let менялось=false;
  for(let i=1;i<=8;i++){
    const с=площадки.get(i);
    const цель=с ? Math.min(1,.45+(performance.now()-с.нажата)/1400) : 0;
    const скор=с ? .16 : .07;
    const было=проводимость[i];
    проводимость[i]+=(цель-проводимость[i])*скор;
    if(Math.abs(проводимость[i]-было)>1e-4) менялось=true;
  }
  if(менялось&&node) node.port.postMessage({t:'площадки',v:Array.from(проводимость)});
},1000/60);

// ---- запуск ---------------------------------------------------------------
window.дбг={состояние:'не запускался',ошибка:null,
  get площадки(){return [...площадки.keys()]},
  get пров(){return Array.from(проводимость)}};
async function пуск(){
  if(идёт) return;
  window.дбг.состояние='запускаю';
  try{
  ctx=new AudioContext({latencyHint:'interactive'});
  await ctx.audioWorklet.addModule('хаос.worklet.js?v='+Date.now());
  node=new AudioWorkletNode(ctx,'хаос',{numberOfInputs:0,numberOfOutputs:1,
    outputChannelCount:[2]});
  node.connect(ctx.destination);
  node.port.onmessage=e=>{ отчёт=e.data; window.дбг.отчётов=(window.дбг.отчётов||0)+1; window.дбг.о=отчёт; };
  await ctx.resume();
  идёт=true; шли();
  window.дбг.состояние='играет';
  }catch(e){ window.дбг.ошибка=''+e; window.дбг.состояние='упал'; }
}

// Щелчок тоже запускает: клавиша не дойдёт, пока окно без фокуса.
addEventListener('pointerdown',()=>{ пуск(); });

// ---- клавиатура -----------------------------------------------------------
addEventListener('keydown',async e=>{
  if(e.metaKey||e.ctrlKey||e.altKey) return;
  const c=e.code;
  if(!идёт){ await пуск(); if(c==='Space'){ e.preventDefault(); return; } }
  // Пересборка прибора: новый экземпляр с другими номиналами. Ручки на
  // панели остаются где стояли — меняется сам прибор, а не настройка.
  if(c==='Tab'){ e.preventDefault(); пересобери(); return; }

  for(const r of РУЧКИ){
    const знак = c===r.м[0] ? -1 : c===r.м[1] ? 1 : 0;
    if(!знак) continue;
    e.preventDefault();
    const было=держим.get(c);
    if(было){ было.живо=performance.now(); return; }     // автоповтор — подтверждение
    {
      const t=performance.now();
      держим.set(c,{ключ:r.к,знак,ручка:r,начало:t,живо:t,мелко:e.shiftKey});
      // один щелчок ручки: сотая доля хода, у полосы это десятая часть деления
      макро[r.к]=clamp((макро[r.к]||0)+знак*(e.shiftKey?.005:.02),0,1);
      последняя=r; вспышка=6; шли();
    }
    return;
  }
  if(c==='Space'){ node&&node.port.postMessage({t:'толчок'}); e.preventDefault(); return; }
  // ---- ПЛОЩАДКИ -----------------------------------------------------------
  // Не пресеты. У Срапы были контактные площадки: палец замыкал участок цепи
  // через сопротивление своего тела, и звук менялся ровно пока ты держишь.
  // Прохождения тока через нас тут не будет, поэтому переосмысляем: цифра
  // замыкает СВОЙ участок схемы, и «сопротивление контакта» живое — оно
  // падает, пока держишь (контакт разогревается и притирается), и медленно
  // восстанавливается после. Держать можно сколько угодно площадок разом.
  const цифра=c.startsWith('Digit') ? +c.slice(5) : 0;
  if(цифра>=1 && цифра<=8){
    e.preventDefault();
    if(!площадки.has(цифра)) площадки.set(цифра,{нажата:performance.now()});
    return;
  }
});

// Отпускание клавиши, потеря фокуса, сворачивание вкладки. Все три
