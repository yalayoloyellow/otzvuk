// ---- КАРТИНА ---------------------------------------------------------------
// Не приборная панель, а портрет самой системы. Фазовое пространство: сигнал
// против себя же со сдвигом — у порядка это замкнутая петля, у хаоса облако,
// у захвата — узел с лепестками. То есть форма на экране И ЕСТЬ то, что
// слышно, а не иллюстрация к нему.
//
// Поверх — фосфор: след гаснет не сразу, как на осциллографе с длинным
// послесвечением. И зеркало по вертикали: живая динамика превращается в
// орнамент, который дышит вместе со звуком.
const Ш=112, В=40;
const ФОСФОР=' ·∙:∴*≋≡▒▓█';
const поле=new Float32Array(Ш*В);
let угол=0;

function картина(){
  const о=отчёт.осц||new Float32Array(256), n=о.length;
  const u=clamp(отчёт.качели??.5,0,1);            // положение качелей
  const г=clamp(отчёт.гуляние??.5,0,1);
  const ут=clamp(отчёт.утечка||0,0,1.4);          // пальцы на площадках

  // ПОСЛЕСВЕЧЕНИЕ. Внизу качелей звук трещит отдельными импульсами — там
  // след держится дольше и рисунок стоит в воздухе; наверху, на визге,
  // фигура гаснет быстро. Так качание видно даже боковым зрением.
  const спад=.87 + (1-u)*.09 + (1-clamp(отчёт.шина||1,0,1))*.03;
  for(let i=0;i<поле.length;i++) поле[i]*=спад;

  // Траектория в фазовом пространстве: сигнал против себя же, сдвинутого по
  // времени. Сдвиг должен идти за ВЫСОТОЙ — четверть периода волны, иначе
  // портрет вырождается в отрезок вместо кольца. Качели подгибают его сверх
  // того, и от этого фигура раскрывается и складывается на ходу.
  // В буфере всегда около двух периодов волны, поэтому четверть периода —
  // это просто четверть от его половины, независимо от высоты.
  const сдв=clamp(Math.round(32*(.8+u*.6)),4,60);
  const цx=(Ш-1)/2, цy=(В-1)/2;
  угол += .003 + u*.016;
  const ко=Math.cos(угол), си=Math.sin(угол);
  // ЗАКРУТКА. Чем ниже качели, тем сильнее внешние витки отстают от
  // внутренних — фигура сворачивается в вихрь; наверху распрямляется в
  // ровное кольцо. Это тот же самый ход, который слышно.
  const твист=(1-u)*2.6 - 1.1 + (г-.5)*1.4;
  // ДЫХАНИЕ: качели растягивают фигуру по вертикали и поджимают по
  // горизонтали, как меняется сама волна.
  const рx=.80+u*.42, рy=1.18-u*.44;
  // Точки траектории СОЕДИНЯЮТСЯ отрезками, а не сыплются россыпью: на
  // резком фронте соседние отсчёты разлетаются далеко, и между ними
  // протягивается длинный луч. Отсюда щупальца — они рисуют ровно то, где
  // сигнал рвётся, а плавные участки остаются плотным телом.
  const мазок=(x0,y0,x1,y1,сила)=>{
    const dx=Math.abs(x1-x0), dy=Math.abs(y1-y0);
    const шагов=Math.max(dx,dy);
    if(шагов>Ш) return;
    const яр=сила/Math.max(1,Math.pow(шагов,.45));
    for(let k=0;k<=шагов;k++){
      const t=шагов?k/шагов:0;
      const x=Math.round(x0+(x1-x0)*t), y=Math.round(y0+(y1-y0)*t);
      if(x>=0&&x<Ш&&y>=0&&y<В) поле[y*Ш+x]+=яр;
      const xм=Ш-1-x;
      if(xм>=0&&xм<Ш&&y>=0&&y<В) поле[y*Ш+xм]+=яр*.4;
    }
  };
  let пx=null, пy=null;
  for(let i=0;i<n-сдв;i++){
    const a=clamp(о[i],-1,1), b=clamp(о[i+сдв],-1,1);
    let rx=a*ко - b*си, ry=a*си + b*ко;
    const рад=Math.sqrt(rx*rx+ry*ry);
    const т=твист*рад*рад;
    const кт=Math.cos(т), ст=Math.sin(т);
    const wx=rx*кт - ry*ст, wy=rx*ст + ry*кт;
    // палец на площадке мутит саму фигуру, а не рисует поверх неё
    const муть=ут>.01 ? (Math.random()-.5)*ут*.18 : 0;
    const x=Math.round(цx + (wx+муть)*цx*.96*рx);
    const y=Math.round(цy - (wy+муть)*цy*.96*рy);
    if(пx!==null) мазок(пx,пy,x,y,.85); else if(x>=0&&x<Ш&&y>=0&&y<В) поле[y*Ш+x]+=.85;
    пx=x; пy=y;
  }

  let mx=.001;
  for(const v of поле) if(v>mx) mx=v;
  const строки=[];
  for(let y=0;y<В;y++){
    let s='';
    for(let x=0;x<Ш;x++){
      const v=поле[y*Ш+x]/mx;
      s+=ФОСФОР[clamp(Math.round(Math.pow(v,.55)*(ФОСФОР.length-1)),0,ФОСФОР.length-1)];
    }
    строки.push(s);
  }
  return строки.join('\n');
}

function полоса(v,ш,симв){
  const n=clamp(Math.round(v*ш),0,ш);
  return (симв||'▮').repeat(n)+'·'.repeat(ш-n);
}

// Частота раскачки: биения огибающей. Это и есть ритм, рождённый встречей
// двух приборов на границе захвата — то, ради чего вся инжекция.
const огиб=new Float32Array(180); let огибИ=0, ритмГц=0, ритмТик=0;
function ритмЗамер(){
  const о=отчёт.осц; if(!о) return;
  let s=0; for(let i=0;i<о.length;i++) s+=о[i]*о[i];
  огиб[огибИ=(огибИ+1)%огиб.length]=Math.sqrt(s/о.length);
  if(++ритмТик<12) return;
  ритмТик=0;
  const n=огиб.length; let m=0; for(const v of огиб) m+=v; m/=n;
  const d=new Float32Array(n); for(let i=0;i<n;i++) d[i]=огиб[(огибИ+1+i)%n]-m;
  let e0=0; for(const v of d) e0+=v*v;
  if(e0<1e-9){ ритмГц=0; return; }
  let лучш=0,лаг=0;
  for(let l=3;l<n-6;l++){
    let sc=0; for(let i=0;i+l<n;i++) sc+=d[i]*d[i+l];
    const c=sc/e0; if(c>лучш){лучш=c;лаг=l;}
  }
  ритмГц = (лучш>.2&&лаг) ? 30/лаг : 0;      // отчёты идут 30 раз в секунду
}

function приборы(){
  ритмЗамер();
  // Разброс интервалов между щелчками медленного узла: 0 — рисунок стоит
  // как вкопанный, растёт — гуляет.
  const л=отчёт.разброс||0;
  const где = л<.02?'РОВНО' : л<.10?'дышит' : л<.28?'гуляет'
            : л<.55?'КРАЙ' : 'распад';
  const цвет = л<.10?'тускло' : л<.55?'ярко':'тревога';
  const пер=отчёт.период||0;
  const выс=отчёт.высота||0, скв=отчёт.скважность||0;
  return [
`  период <b>${пер>.02&&пер<30?пер.toFixed(2)+' с':'—'}</b>   высота <b>${выс.toFixed(0)}</b> Гц` +
  `   импульс <b>${(скв*100).toFixed(0)}%</b>   <span class="${цвет}">${где}</span>`,
`  шина ${полоса(clamp(отчёт.шина,0,1),12)}  уровень ${полоса(clamp(отчёт.пик,0,1),12)}`
  ].join('\n');
}

function ручки(){
  const сб=отчёт.сборка||{};
  const строки=[`  <span class="совсем">прибор</span> <b>${сб.имя||'····'}</b>`+
                (сб.динамик?`  <span class="совсем">динамик ${сб.динамик.toFixed(0)} Гц ·`+
                 ` ${(сб.ёмкость*1e9).toFixed(1)} нФ · порог ${(сб.порог*100).toFixed(0)}% ·`+
                 ` ${сб.эдс.toFixed(1)} В</span>`:'')+
                `  <span class="совсем">Tab — пересобрать</span>`, ''];
  for(let i=0;i<РУЧКИ.length;i+=3){
    строки.push(РУЧКИ.slice(i,i+3).map(r=>{
      const свой=r===последняя&&вспышка>0;
      const имя=(r.имя+'        ').slice(0,8);
      const кл=r.подпись;
      const б=полоса(макро[r.к]||0,10);
      const s=`${имя} ${б} ${кл}`;
      return свой?`<span class="ярко">${s}</span>`:`<span class="тускло">${s}</span>`;
    }).join('   '));
  }
  return строки.join('\n');
}

