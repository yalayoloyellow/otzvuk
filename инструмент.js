// ---- КАРТИНА ---------------------------------------------------------------
// Не приборная панель, а портрет самой системы. Фазовое пространство: сигнал
// против себя же со сдвигом — у порядка это замкнутая петля, у хаоса облако,
// у захвата — узел с лепестками. То есть форма на экране И ЕСТЬ то, что
// слышно, а не иллюстрация к нему.
//
// Поверх — фосфор: след гаснет не сразу, как на осциллографе с длинным
// послесвечением. И зеркало по вертикали: живая динамика превращается в
// орнамент, который дышит вместе со звуком.
const Ш=100, В=26;
const ФОСФОР=' ·∙:∴*≋≡▒▓█';
const поле=new Float32Array(Ш*В);
let угол=0;

function картина(){
  const о=отчёт.осц||new Float32Array(256), n=о.length;
  // гаснем: чем сильнее просажена шина, тем дольше тлеет — прибор «устал»
  const спад=.86 + (1-clamp(отчёт.шина||1,0,1))*.10;
  for(let i=0;i<поле.length;i++) поле[i]*=спад;

  // Траектория в фазовом пространстве, но не плоская: фигура ВРАЩАЕТСЯ, и
  // угол ведёт медленный узел. Без вращения прямоугольные сигналы кладут
  // точки в две жёсткие горизонтали — вместо портрета получались полосы.
  const сдв=3+Math.round((отчёт.медл?.[0]||0)*6+4);
  const цx=(Ш-1)/2, цy=(В-1)/2;
  угол += .004 + (отчёт.медл?.[0]||0)*.02;
  const ко=Math.cos(угол), си=Math.sin(угол);
  // третья координата — струна: она выгибает фигуру в глубину
  const глуб=clamp((отчёт.струна||0)/3,-1,1);
  for(let i=0;i<n-сдв;i++){
    const a=clamp(о[i],-1,1), b=clamp(о[i+сдв],-1,1);
    const rx=a*ко - b*си, ry=a*си + b*ко;
    const п=1/(1.35 + глуб*.5*ry);              // перспектива от струны
    const x=Math.round(цx + rx*цx*.92*п*1.35);
    const y=Math.round(цy - ry*цy*.92*п*1.35);
    if(x>=0&&x<Ш&&y>=0&&y<В) поле[y*Ш+x]+=.5;
    const xм=Ш-1-x;                              // зеркало — орнамент
    if(xм>=0&&xм<Ш&&y>=0&&y<В) поле[y*Ш+xм]+=.22;
  }

  // площадки прожигают свои полосы — видно, что палец делает со схемой
  const пл=отчёт.пл||[];
  for(let i=1;i<=8;i++){
    const g=пл[i]||0;
    if(g<.02) continue;
    const y=Math.round((i-1)/7*(В-1));
    for(let x=0;x<Ш;x++){
      const волна=Math.sin(x*.19 + i*1.7 + (отчёт.гц||0)*.01);
      поле[y*Ш+x]+=g*.5*(.4+.6*волна*волна);
    }
  }

  let mx=.001;
  for(const v of поле) if(v>mx) mx=v;
  const строки=[];
  for(let y=0;y<В;y++){
    let s='';
    for(let x=0;x<Ш;x++){
      const v=поле[y*Ш+x]/mx;
      s+=ФОСФОР[clamp(Math.round(Math.pow(v,.55)*(ФОСФОР.length-1)),0,ФОСФОР.length-1)];
    }
    строки.push(s);
  }
  return строки.join('\n');
}

function полоса(v,ш,симв){
  const n=clamp(Math.round(v*ш),0,ш);
  return (симв||'▮').repeat(n)+'·'.repeat(ш-n);
}

// Частота раскачки: биения огибающей. Это и есть ритм, рождённый встречей
// двух приборов на границе захвата — то, ради чего вся инжекция.
const огиб=new Float32Array(180); let огибИ=0, ритмГц=0, ритмТик=0;
function ритмЗамер(){
  const о=отчёт.осц; if(!о) return;
  let s=0; for(let i=0;i<о.length;i++) s+=о[i]*о[i];
  огиб[огибИ=(огибИ+1)%огиб.length]=Math.sqrt(s/о.length);
  if(++ритмТик<12) return;
  ритмТик=0;
  const n=огиб.length; let m=0; for(const v of огиб) m+=v; m/=n;
  const d=new Float32Array(n); for(let i=0;i<n;i++) d[i]=огиб[(огибИ+1+i)%n]-m;
  let e0=0; for(const v of d) e0+=v*v;
  if(e0<1e-9){ ритмГц=0; return; }
  let лучш=0,лаг=0;
  for(let l=3;l<n-6;l++){
    let sc=0; for(let i=0;i+l<n;i++) sc+=d[i]*d[i+l];
    const c=sc/e0; if(c>лучш){лучш=c;лаг=l;}
  }
  ритмГц = (лучш>.2&&лаг) ? 30/лаг : 0;      // отчёты идут 30 раз в секунду
}

function приборы(){
  ритмЗамер();
  // Разброс интервалов между щелчками: 0 — жёсткий захват, растёт — распад.
  // Показатель Ляпунова по траектории здесь врал (см. ядро), поэтому мерим
  // то, что слышно: ровность самих щелчков.
  const л=отчёт.разброс||0;
  const где = л<.02?'ЖЁСТКИЙ ЗАХВАТ' : л<.10?'ровно' : л<.28?'дышит'
            : л<.55?'КРАЙ ХАОСА' : 'распад';
  const цвет = л<.10?'тускло' : л<.55?'ярко':'тревога';
  const в=отчёт.вращение||0;
  // Число вращения: близкое к простому отношению — захват в ритмическую фигуру
  const прост=[[1,1],[2,1],[3,1],[3,2],[4,1],[4,3],[5,2],[5,4],[6,1],[8,1]];
  let бл='—', лучш=9;
  for(const [a,b] of прост){ const d=Math.abs(в-a/b); if(d<лучш&&d<.06){ лучш=d; бл=a+':'+b; } }
  // Пульс не рисуется по счётчику — его нет. Показываем сами медленные узлы:
  // видно, как они захватываются друг за друга.
  const м=отчёт.медл||[0,0,0];
  const лента=м.map(v=>{
    const n=clamp(Math.round((v*.5+.5)*11),0,11);
    return '·'.repeat(n)+'●'+'·'.repeat(11-n);
  }).join(' ');
  const стр=clamp(Math.abs(отчёт.струна||0)/2,0,1);
  return [
`  разброс <span class="${цвет}">${полоса(clamp(л*1.6,0,1),28)}</span> ${где}  ${(л*100).toFixed(0)}%`,
`  пульс ${лента}   струна ${полоса(стр,10)}`,
`  раскачка ${ритмГц>.3&&ритмГц<12?'<span class="ярко">'+ритмГц.toFixed(1)+' Гц</span>':'<span class="совсем">нет</span>'}   захват ${бл==='—'?'<span class="совсем">плывёт</span>':'<span class="ярко">'+бл+'</span>'}    шина ${полоса(clamp(отчёт.шина,0,1),12)}  уровень ${полоса(clamp(отчёт.пик,0,1),12)}`
  ].join('\n');
}

function ручки(){
  const строки=[`  <span class="совсем">прибор</span> <b>${(семя>>>0).toString(36).slice(-4)}</b>`+
                `  <span class="совсем">Tab — пересобрать</span>`, ''];
  for(let i=0;i<РУЧКИ.length;i+=3){
    строки.push(РУЧКИ.slice(i,i+3).map(r=>{
      const свой=r===последняя&&вспышка>0;
      const имя=(r.имя+'        ').slice(0,8);
      const кл=r.подпись;
      const б=полоса(макро[r.к]||0,10);
      const s=`${имя} ${б} ${кл}`;
      return свой?`<span class="ярко">${s}</span>`:`<span class="тускло">${s}</span>`;
    }).join('   '));
  }
  return строки.join('\n');
}

