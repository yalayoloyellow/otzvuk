// ============================================================================
//  ГОВОРИЛКА — формантный синтезатор русской речи.
//
//  Не запись и не нейросеть: модель голосового тракта, как в SAM на Apple II
//  и в «Speak & Spell». Источник — импульсы голосовых связок или шум, дальше
//  три резонатора-форманты, которые и делают из жужжания гласный звук.
//  Отсюда её жестяной тембр: тракт грубый, переходы прямые.
//
//  Здесь только РАЗБОР ТЕКСТА — превращение букв в цепочку фонем с
//  длительностями. Сам синтез живёт в ядре, рядом со схемой прибора, потому
//  что его выход идёт в ту же точку, что микрофон.
// ============================================================================

// Форманты русских гласных, герцы. F1 отвечает за подъём языка, F2 — за ряд,
// F3 добавляет окраску. Числа взяты из речевой акустики, не подобраны на слух.
export const GLASNYE = {
  a: [700, 1080, 2600],
  o: [500,  850, 2500],
  u: [320,  640, 2200],
  y: [300, 1480, 2230],
  e: [440, 1800, 2550],
  i: [240, 2250, 3200],
};

// Согласные: тип источника и полоса шума либо форманты для сонорных.
//   g — с голосом (звонкий), sh — шум, vz — взрыв (смычка с выбросом)
export const SOGLASNYE = {
  m: {tip:'son', f:[250,  900, 2200], dl:.07},
  n: {tip:'son', f:[250, 1700, 2600], dl:.07},
  l: {tip:'son', f:[350, 1100, 2900], dl:.07},
  r: {tip:'drozh', f:[400, 1300, 2600], dl:.08},
  v: {tip:'sh', f:[ 900, 2200], gol:1, dl:.07},
  z: {tip:'sh', f:[4000, 6000], gol:1, dl:.08},
  zh:{tip:'sh', f:[1800, 3000], gol:1, dl:.09},
  f: {tip:'sh', f:[ 900, 2200], gol:0, dl:.08},
  s: {tip:'sh', f:[4500, 7000], gol:0, dl:.09},
  sh:{tip:'sh', f:[1800, 3200], gol:0, dl:.10},
  h: {tip:'sh', f:[1200, 2400], gol:0, dl:.09},
  sc:{tip:'sh', f:[2400, 4200], gol:0, dl:.12},
  b: {tip:'vz', f:[ 400, 1000], gol:1, dl:.055},
  p: {tip:'vz', f:[ 400, 1000], gol:0, dl:.055},
  d: {tip:'vz', f:[ 500, 1700], gol:1, dl:.05},
  t: {tip:'vz', f:[ 500, 1700], gol:0, dl:.05},
  g: {tip:'vz', f:[ 400, 1900], gol:1, dl:.055},
  k: {tip:'vz', f:[ 400, 1900], gol:0, dl:.055},
  c: {tip:'af', f:[4500, 7000], gol:0, dl:.10},
  ch:{tip:'af', f:[2000, 3400], gol:0, dl:.10},
  j: {tip:'son', f:[240, 2400, 3200], dl:.045},   // й
};

const ZVONKIE = {b:'p', v:'f', g:'k', d:'t', z:'s', zh:'sh'};
const YOT = {я:['j','a'], ё:['j','o'], ю:['j','u'], е:['j','e']};
const PROSTYE = {
  а:'a', о:'o', у:'u', ы:'y', э:'e', и:'i',
  б:'b', в:'v', г:'g', д:'d', ж:'zh', з:'z', й:'j', к:'k', л:'l', м:'m',
  н:'n', п:'p', р:'r', с:'s', т:'t', ф:'f', х:'h', ц:'c', ч:'ch',
  ш:'sh', щ:'sc',
};

// Разбор слова в фонемы. Правила упрощены до тех, что слышны:
//   · йотированные буквы после гласной, ь, ъ и в начале слова дают «й»,
//     после согласной — просто смягчают её и превращаются в свой гласный;
//   · звонкие оглушаются в конце слова и перед глухими;
//   · безударное «о» звучит как «а» — без этого речь сразу выдаёт машину.
export function vFonemy(tekst){
  const out = [];
  const slova = String(tekst).toLowerCase().split(/([^а-яё]+)/);
  for (const kusok of slova){
    if (!/[а-яё]/.test(kusok)){
      if (kusok.trim() === '' && kusok.length) out.push({f:'pauza', dl:.12});
      continue;
    }
    const bukvy = [...kusok];
    // ударение не размечено, поэтому считаем ударным последний гласный слова:
    // для нашей задачи важно не попасть в него редукцией, а не угадать точно
    let posl = -1;
    bukvy.forEach((b,i)=>{ if('аоуыэиеёюя'.includes(b)) posl=i; });
    for (let i = 0; i < bukvy.length; i++){
      const b = bukvy[i], sled = bukvy[i+1] || '', pred = bukvy[i-1] || '';
      if (b === 'ь' || b === 'ъ') continue;
      if (YOT[b]){
        const [j, gl] = YOT[b];
        const posleGlasnoy = !pred || 'аоуыэиеёюяьъ'.includes(pred);
        if (posleGlasnoy) out.push({f:j, dl:.045});
        else if (out.length && !['zh','sh','c'].includes(out[out.length-1].f))
          out[out.length-1].myagko = 1;   // ж, ш, ц не смягчаются никогда
        let zvuk = gl;
        if (i !== posl && gl === 'o') zvuk = 'a';       // редукция
        if (i !== posl && gl === 'e') zvuk = 'i';
        out.push({f:zvuk, dl: i===posl ? .16 : .10, gl:1});
        continue;
      }
      const f = PROSTYE[b];
      if (!f) continue;
      if (GLASNYE[f]){
        let zvuk = f;
        if (i !== posl && f === 'o') zvuk = 'a';
        out.push({f:zvuk, dl: i===posl ? .16 : .10, gl:1});
      } else {
        let zvuk = f;
        // оглушение: в конце слова и перед глухим согласным
        const sledF = PROSTYE[sled];
        const gluhoy = sledF && SOGLASNYE[sledF] && SOGLASNYE[sledF].gol === 0;
        if (ZVONKIE[zvuk] && (i === bukvy.length-1 || gluhoy)) zvuk = ZVONKIE[zvuk];
        const s = SOGLASNYE[zvuk];
        out.push({f:zvuk, dl:s ? s.dl : .07});
        // ПУСТАЯ строка входит в любую как подстрока — без проверки на длину
        // последняя согласная слова всегда выходила мягкой.
        // Ж, Ш и Ц в русском не смягчаются никогда, какая бы буква ни шла.
        if (sled && 'еёюяи'.includes(sled) && !['zh','sh','c'].includes(f))
          out[out.length-1].myagko = 1;
      }
    }
    out.push({f:'pauza', dl:.10});
  }
  // Две паузы подряд слышны как заминка — сливаем.
  return out.filter((x,i)=> !(x.f==='pauza' && out[i-1] && out[i-1].f==='pauza'));
}
