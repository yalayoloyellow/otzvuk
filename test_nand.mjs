// Сверка двух схем: триггер Шмитта (40106, что моделировался) против
// мультивибратора на двух элементах 2И-НЕ (К561ЛА7 — то, из чего делали
// на советской базе, а значит почти наверняка и Срапионов).
//
// Различия не косметические:
//  · у Шмитта пороги встроены и заданы долями питания;
//  · у 2И-НЕ порог один (примерно половина питания), а гистерезис создаётся
//    самой схемой — выход второго элемента через резистор возвращается на
//    вход, и напряжение там ВЫСКАКИВАЕТ ЗА ПРЕДЕЛЫ ПИТАНИЯ через конденсатор;
//  · выброс ограничивают защитные диоды входа — без них расчёт периода
//    неверен, и именно они дают несимметричную форму.
const exp = Math.exp;

// --- 40106: релаксационный на триггере Шмитта
function шмитт(RC, SR, сек, Vdd = 1){
  let v = Vdd/3, q = 1, n = 0, первый = -1, последний = -1;
  const dt = 1/SR, k = 1 - exp(-dt/RC);
  const Vp = Vdd*2/3, Vn = Vdd/3;
  for (let i = 0; i < SR*сек; i++){
    v += ((q ? Vdd : 0) - v) * k;
    if (q ? v > Vp : v < Vn){ if (q){ if (первый<0) первый=i; последний=i; n++; } q ^= 1; }
  }
  return n>1 ? (n-1)*SR/(последний-первый) : 0;
}

// --- К561ЛА7: два инвертора (2И-НЕ со связанными входами), R и C
// вход1 —— C —— выход1 —— вход2, R от выхода2 к входу1
// Ключевое: скачок выхода через C переносится на вход целиком, поэтому
// напряжение уходит за питание и садится на защитных диодах.
// Правильная петля мультивибратора на двух инверторах:
//   B → [инв1] → A → C → вход2 → [инв2] → B,  и R от B ко входу2.
// В прошлой версии связи были замкнуты так, что получалась положительная
// обратная связь без регенерации — схема залипала, и тест давал ноль.
function нанд(RC, SR, сек, Vdd = 1, диоды = true){
  let v2 = Vdd/2, B = Vdd, n = 0, первый = -1, последний = -1;
  const dt = 1/SR, k = 1 - exp(-dt/RC), Vt = Vdd/2;
  let A = (B > Vt) ? 0 : Vdd;
  for (let i = 0; i < SR*сек; i++){
    const новыйB = (v2 > Vt) ? 0 : Vdd;
    if (новыйB !== B){
      B = новыйB;
      const новыйA = (B > Vt) ? 0 : Vdd;
      // скачок выхода первого инвертора переносится через конденсатор целиком
      v2 += (новыйA - A);
      A = новыйA;
      if (B > Vt){ if (первый < 0) первый = i; последний = i; n++; }
    }
    // защитные диоды входа: дальше 0.6 В за шины напряжение не уходит.
    // Без них форма и период считаются неверно — это не мелочь, а то,
    // из-за чего у таких схем несимметричные полупериоды.
    // Падение на диоде — АБСОЛЮТНЫЕ 0.6 В, оно не масштабируется вместе с
    // питанием. Именно эта «неподвижная» величина на фоне садящейся батарейки
    // и делает частоту зависимой от питания: чем ниже Vdd, тем большую долю
    // размаха съедает диод. В прошлой версии диоды были заданы долями Vdd —
    // тогда всё пропорционально и зависимость исчезает, что и намерилось.
    if (диоды) v2 = Math.max(-.6, Math.min(Vdd + .6, v2));
    v2 += (B - v2) * k;                     // заряд через R к выходу второго
  }
  return n > 1 ? (n-1)*SR/(последний-первый) : 0;
}

console.log('СВЕРКА СХЕМ: частота при одинаковых R и C\n');
console.log('   RC      Шмитт(40106)   2И-НЕ(К561ЛА7)  отношение');
for (const RC of [1e-3, 3e-4, 1e-4, 3e-5]){
  const ш = шмитт(RC, 192000, .5), н = нанд(RC, 192000, .5);
  console.log(`  ${String(RC).padEnd(8)}  ${ш.toFixed(1).padStart(8)} Гц  ${н.toFixed(1).padStart(11)} Гц   ${(н/ш).toFixed(3)}`);
}

console.log('\nЗАВИСИМОСТЬ ОТ ПИТАНИЯ (главный вопрос: садится батарейка)\n');
console.log('  питание   Шмитт        2И-НЕ с диодами   2И-НЕ без диодов');
for (const Vdd of [9, 6, 4.5, 3]){
  const ш = шмитт(1e-4, 192000, .5, Vdd);
  const нд = нанд(1e-4, 192000, .5, Vdd, true);
  const нб = нанд(1e-4, 192000, .5, Vdd, false);
  console.log(`  ${Vdd.toFixed(1)} В ${ш.toFixed(1).padStart(8)} Гц  ${нд.toFixed(1).padStart(12)} Гц  ${нб.toFixed(1).padStart(14)} Гц`);
}
