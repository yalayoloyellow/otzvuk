// Сравнение ЧИСТОГО СТЕНДА и ПРИБОРА одной и той же меркой: сколько октав
// проходит высота и с каким периодом повторяется рисунок. Автокорреляция
// для периода не годится — она садится на кратные лаги; интервалы между
// всплесками огибающей честнее.
import {прогон} from './стенд_хаос.mjs';
const SR=48000;

// ---- ядро стенда (то, что yala опознал) -----------------------------------
function стенд(качание, характер, сек){
  const n=Math.round(SR*сек), L=new Float32Array(n);
  const F=.20*Math.pow(2,качание*6.8), RCм=1/(1.508*F), шагМ=1-Math.exp(-1/(SR*RCм));
  const fн=22*Math.pow(2,характер*1.2), fв=300*Math.pow(2,характер*4.0);
  const aм=.12+характер*.19;
  let vм=.4,qм=1,v=.4,q=1,дс=0;
  for(let s=0;s<n;s++){
    vм+=((qм?1:0)-vм)*шагМ;
    if(qм? vм>.68 : vм<.32) qм^=1;
    const u=Math.max(0,Math.min(1,(vм-.32)/.36));
    const f0=fн*Math.pow(fв/fн,u), a=aм*(1-u), RC=1/(1.508*f0);
    const ц=(q?1:0)+a, прошл=v;
    v+=(ц-v)*(1-Math.exp(-1/(SR*RC)));
    let вых=q?1:-1;
    if(q? v>.68 : v<.32){
      const порог=q?.68:.32;
      const доля=Math.max(0,Math.min(1,(порог-прошл)/(v-прошл)));
      const стар=вых; q^=1; вых=стар*доля+(q?1:-1)*(1-доля);
    }
    дс+=(вых-дс)*(12*6.283/SR);
    L[s]=(вых-дс)*.25;
  }
  return L;
}

function разведи(м){
  const в={};
  в.пульс=м.качание; в.делёж=.2+м.качание*.5;
  в.частота=м.характер; в.гистерезис=.32+(1-м.характер)*.42;
  в.качели=.3+м.характер*.45; в.фильтр=.60+м.характер*.30;
  в.размах=м.размах;
  в.каскад=м.второй*.9; в.вес=м.второй*.6; в.назад=м.второй*.45;
  в.куда=.35+м.второй*.4; в.расстройка=.08+м.второй*.84;
  в.разброс=м.хаос*.85; в.вПорог=м.хаос*.3; в.связь=м.хаос*.55;
  в.логика=м.хаос*.6; в.шум=м.хаос*.2;
  в.накачка=м.сила*.9; в.нагрузка=м.сила*.9; в.питание=.05+м.сила*.55;
  в.струна=0; в.съём=.42;
  в.гейт=0;в.рисунок=0;в.видРисунка=0;в.гейт2=0;в.холд=0;
  return в;
}

// ОДНА мерка для обоих: мгновенная высота по расстоянию между переходами
// через ноль. Окно фиксированной длины не годится — оно либо не ловит 26 Гц,
// либо усредняет килогерц; здесь каждый период меряется сам по себе.
// Возвращает пары [время, частота]. Раньше возвращались только частоты, и
// период рисунка считался в НОМЕРАХ периодов: внизу качелей их за секунду
// два десятка, наверху тысяча, поэтому «период» плыл от характера, хотя
// качание не менялось. Считать надо по секундам.
function высоты(L){
  // Считать простые переходы через ноль нельзя: узкий импульс после
  // выходного конденсатора даёт обратный выброс, и каждый период считался
  // дважды. Детектор со своим гистерезисом (как настоящий триггер) видит
  // только настоящие фронты.
  const out=[]; let пред=-1, вверху=false, ог=0;
  for(let s=1;s<L.length;s++){
    const a=Math.abs(L[s]); ог += (a-ог)*(a>ог?.02:.0005);
    const п=Math.max(.004, ог*.45);
    if(!вверху && L[s]>п){ вверху=true;
      if(пред>=0){ const T=(s-пред)/SR; if(T>1/6000&&T<1/12) out.push([s/SR,1/T]); }
      пред=s;
    } else if(вверху && L[s]<-п*.3) вверху=false;
  }
  return out;
}
// период рисунка по интервалам между подъёмами высоты выше медианы
function периодРисунка(в){
  const с=в.map(x=>x[1]).sort((a,b)=>a-b), мед=с[с.length>>1];
  const инт=[]; let послед=-1;
  for(let i=1;i<в.length;i++)
    if(в[i-1][1]<=мед && в[i][1]>мед){ if(послед>=0) инт.push(в[i][0]-послед); послед=в[i][0]; }
  if(инт.length<3) return {п:0,разб:0,n:инт.length};
  const ср=инт.reduce((a,b)=>a+b,0)/инт.length;
  let д=0; for(const t of инт) д+=(t-ср)*(t-ср);
  return {п:ср, разб:Math.sqrt(д/инт.length)/ср, n:инт.length};
}
function отчёт(имя,L){
  const в=высоты(L).slice(20);
  if(в.length<10) return `${имя}  тишина`;
  const с=в.map(x=>x[1]).sort((a,b)=>a-b);
  const низ=с[Math.floor(с.length*.03)], верх=с[Math.floor(с.length*.97)];
  const р=периодРисунка(в);
  return `${имя.padEnd(26)} период ${р.п.toFixed(2).padStart(5)} с  дрожь ${(р.разб*100).toFixed(0).padStart(3)}%  ` +
         `${низ.toFixed(0).padStart(5)}–${верх.toFixed(0).toString().padEnd(5)} Гц  ${(низ>0?Math.log2(верх/низ):0).toFixed(2)} окт`;
}
