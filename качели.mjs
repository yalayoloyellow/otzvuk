// Численная проверка ядра ДО звука: реально ли частота ходит в нужном
// размахе и с нужным периодом. Формулы те же, что пойдут в стенд.
const SR=48000;
function прогон(качание, характер, сек){
  // медленный узел
  const F = .20*Math.pow(2, качание*6.8);
  // звуковой узел
  // Низ держится в области треска всегда — там прямоугольник слышен
  // отдельными импульсами. Характер поднимает верх и усиливает перекос.
  const fн = 22*Math.pow(2, характер*1.2);
  const fв = 300*Math.pow(2, характер*4.0);
  const aмакс = .12 + характер*.19;
  const RCм = 1/(1.508*F);
  let vм=.4,qм=1, v=.4,q=1;
  let n=0, min=1e9, max=0, широт=[], тперекос=[];
  const N=Math.round(SR*сек);
  let послед=0, периодов=0, суммаПериод=0;
  for(let s=0;s<N;s++){
    // медленный
    const цм=qм?1:0;
    vм += (цм-vм)*(1-Math.exp(-1/(SR*RCм)));
    if(qм? vм>.68 : vм<.32){ qм^=1;
      if(qм){ if(послед){ суммаПериод += (s-послед)/SR; периодов++; } послед=s; } }
    const u=Math.max(0,Math.min(1,(vм-.32)/.36));
    // звуковой
    const f0 = fн*Math.pow(fв/fн, u);
    const a  = aмакс*(1-u);
    const RC = 1/(1.508*f0);
    const ц  = (q?1:0) + a;
    v += (ц-v)*(1-Math.exp(-1/(SR*RC)));
    if(q? v>.68 : v<.32){ q^=1; if(q) n++; }
    if(s%64===0){ if(f0<min)min=f0; if(f0>max)max=f0; }
  }
  return {F, период:периодов?суммаПериод/периодов:0, fн:min, fв:max,
          средняя:n/сек, размахОкт:Math.log2(max/min)};
}
