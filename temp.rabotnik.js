// СЧЁТЧИК ТЕМПА — ОТДЕЛЬНЫМ РАБОТНИКОМ.
//
// Считает он треть секунды. На главной нити это была бы вставшая картинка
// каждые двенадцать секунд, и человек видел бы рывок, не понимая, откуда.
// Здесь же он никому не мешает: посчитал — прислал число.
//
// Алгоритм чужой и взят нарочно. Свой, написанный руками, набрал ОДНО
// попадание из одиннадцати на настоящей музыке — при девятнадцати из
// двадцати одного на синтетических пищалках, которые я сам же и сочинил под
// него. Это и есть цена самодельного счёта: он умеет ровно тот материал, на
// котором его крутили.
//
// Beatroot (Simon Dixon, 2001) в изложении music-tempo, MIT: свёрстан на
// настоящей музыке и даёт восемь из одиннадцати на его же треках.
importScripts('./chuzhoe/music-tempo.min.js');

// ЧАСТОТА ДИСКРЕТИЗАЦИИ ЗАШИТА В БИБЛИОТЕКЕ НА 44100.
//
// Шаг окна у неё — 441 отсчёт, а время события считается как индекс × 0.01
// секунды. Совпадает это ровно на сорока четырёх с сотней. У нас на маке
// сорок восемь тысяч, и без поправки она врёт на восемь процентов: сто
// двадцать восемь показывает как сто семнадцать. Ошибка тихая — число
// правдоподобное, просто чужое.
onmessage = e => {
  const {pcm, sr, nomer} = e.data;
  try {
    const mt = new MusicTempo(pcm, {timeStep: 441 / sr});
    postMessage({
      nomer,
      bpm: +mt.tempo,
      shag: mt.beatInterval,               // секунд на долю
      doli: mt.beats.length,               // сколько долей уложил
      dlit: pcm.length / sr,
    });
  } catch (err) {
    // «Fail to find peaks» — тишина на входе. Это не поломка, это ответ.
    postMessage({nomer, bpm: 0, pochemu: String(err)});
  }
};
