// ---- ОГРАНИЧИТЕЛЬ (ПОСТ) ---------------------------------------------------
// Последняя черта, и единственный способ сделать её по-настоящему.
//
// Компрессор пики прибора не берёт, и это не вопрос настройки: у него атака
// четыре миллисекунды, а пики здесь — щелчки в несколько отсчётов. Замер
// показал ровно это: крест-фактор держится около 3.5 при любом пороге и любом
// отношении. Догонять его укорочением атаки нельзя — это съело бы треск, то
// есть весь характер прибора.
//
// Ограничитель работает иначе: он смотрит на две миллисекунды ВПЕРЁД (для
// чего сигнал на столько же задержан) и, увидев там пик выше потолка,
// успевает свести усиление ЗАРАНЕЕ и плавно. Обрубание режет уже пришедшее и
// потому слышно треском; этот — не слышен, пока не работает, а работает
// только на том, что иначе сломало бы цифру.
class Predel {
  constructor(){
    this.n = Math.max(8, Math.round(SR * .002));
    this.z = new Float32Array(this.n);      // задержанный сигнал
    this.i = 0; this.g = 1;
    this.otp = 1 - Math.exp(-1 / (SR * .05));
    this.rabota = 1;
    // ОЧЕРЕДЬ МИНИМУМОВ. Минимум по окну искался перебором всех девяноста
    // шести ячеек на каждом отсчёте. Здесь он берётся сразу: в очереди лежат
    // только те значения, которые ещё могут стать минимумом, — по убыванию
    // от головы. Число на выходе то же самое, до последнего разряда.
    this.oi = new Int32Array(this.n);      // когда записано
    this.ov = new Float32Array(this.n);    // и что
    this.gol = 0; this.hvost = 0; this.dl = 0; this.t = 0;
  }
  // ОТПУСКАНИЕ БЫЛО РУЧКОЙ И СНЯТО. Замер показал, что оно дублирует DRIVE,
  // только слабее: быстрое даёт громче и площе, медленное тише и живее — та
  // же ось, два децибела против десяти.
  //
  //   DRIVE 1.00:  отпускание 5 мс → скз 0.310, крест 2.58
  //                отпускание 300 мс → скз 0.250, крест 3.20
  //
  // Классической накачки от быстрого отпускания тут не возникает, и понятно
  // почему: накачке нужны редкие громкие события, а у этого материала треск
  // идёт сплошняком — ограничителю не об что качаться.
  //
  // Пятьдесят миллисекунд: быстрее усиление начинает шевелиться на звуковой
  // частоте и это слышно искажением, медленнее — заметно приседает.
  step(y, glub){
    const pot = POTOLOK * (glub === undefined ? 1 : glub);
    const star = this.z[this.i];
    this.z[this.i] = y;
    const a = y < 0 ? -y : y;
    this.i = (this.i + 1) % this.n;

    // МИНИМУМ ПО ВСЕМУ ОКНУ, а не догоняющая огибающая. Догоняющая — это
    // угадывание: она успевает убрать усиление, только если пик пришёл
    // ожидаемо, и течёт, как только отпускание оказывается короче
    // заглядывания. Замер это и поймал: при отпускании 5 мс выход доходил
    // до 0.977 при потолке 0.80. Минимум по окну не может ошибиться в
    // принципе — мы ЗНАЕМ будущее на эти две миллисекунды, гадать не о чем.
    const n = this.n, v = a > pot ? pot / a : 1, t = this.t++;
    // с головы уходит то, что вышло за окно
    while (this.dl && this.oi[this.gol] <= t - n){ this.gol = (this.gol + 1) % n; this.dl--; }
    // с хвоста уходит всё, что не меньше нового: минимумом ему уже не быть
    while (this.dl){
      const h = (this.hvost - 1 + n) % n;
      if (this.ov[h] < v) break;
      this.hvost = h; this.dl--;
    }
    this.ov[this.hvost] = v; this.oi[this.hvost] = t;
    this.hvost = (this.hvost + 1) % n; this.dl++;
    const cel = this.ov[this.gol];
    // Вниз мгновенно: будущее известно, ждать нечего. Вверх по отпусканию.
    this.g = cel < this.g ? cel : this.g + (cel - this.g) * this.otp;
    if (this.g < this.rabota) this.rabota = this.g;
    return star * this.g;
  }
}
const POTOLOK = .80;

// Мягкое колено. До 0.8 не трогает вовсе — наклон там ровно единичный, — а
// выше сводит к единице плавно. Это последняя черта, за которой цифра просто
// ломается.
function koleno(y){
  const b = y < 0 ? -y : y;
  if (b <= .8) return y;
  return (y < 0 ? -1 : 1) * (.8 + .2 * Math.tanh((b - .8) / .2));
}

// ---- ВЕДЕНИЕ НОМИНАЛОВ -----------------------------------------------------
// Как перейти от одного прибора к другому незаметно.
//
// Кроссфейдом — нельзя, и это не вопрос длины. Слух разбирает звук на потоки
// (анализ слуховой сцены), и главные признаки тут — общее начало и
// непрерывность тонкой структуры. У двух экземпляров прибора структура
// независимая: свои периоды, своё дрожание, свой хаос. Для слуха это заведомо
// ДВА источника, и он честно слышит, как один затихает, а другой появляется.
// Чем длиннее фейд, тем отчётливее: слуху дают больше времени на разбор.
//
// Поэтому смешивать не надо вовсе. Играет ОДИН прибор, а едут его НОМИНАЛЫ —
// из набора A в набор B. Разделять слуху нечего: поток один, тонкая структура
// нигде не рвётся, и заметить он может только «оно меняется».
//
// Почему это безопасно: каждый номинал берётся из своего диапазона, и любая
// точка между двумя выпавшими значениями лежит внутри того же диапазона.
// Значит все промежуточные состояния — законные приборы, а не мусор. Путь
// между двумя коробками целиком проходит по коробкам.
//
// Три решения по максимальной плавности:
//   · положительные величины ведутся по ЛОГАРИФМУ. Между 47 кОм и 4.1 МОм
//     середина это 440 кОм, а не 2 МОм: так устроены сопротивления, ёмкости
//     и частоты, и линейный ход по ним слышен как рывок в начале;
//   · каждая величина едет ВРАЗНОБОЙ — свой момент старта внутри общего
//     срока и свой темп, — поэтому ни в одну секунду не происходит события,
//     только дрейф, какой прибор и так даёт от нагрева;
//   · каждая величина трогается и останавливается с нулевой скоростью
//     (сглаженный ход), так что углов нет ни в начале, ни в конце.
const SROK = 12;

// Не всё, что число, — номинал. Сюда попадает то, у чего промежуточного
// значения не бывает вовсе, и ведение его портит:
//
//   РИСУНОК — целое, номер сочетания перемычек в диодной матрице. Дробный
//   код не совпадал ни с одной ветвью разбора, и рисунок молча становился
//   рисунком по умолчанию — причём на второй секунде пути, а не в конце.
// СЕМЯ здесь же и по той же причине: это не номинал, а НОМЕР прибора.
// Попав в интерполяцию, оно поехало числом — панель показывала «сборка
// 53705672.98» на середине пути.
const NE_VESTI = {risunok:1, semya:1};

function snimok(sb){
  const o = {};
  for (const k in sb){
    if (NE_VESTI[k]) continue;
    const v = sb[k];
    if (typeof v === 'number') o[k] = v;
    else if (Array.isArray(v)) o[k] = v.map(x =>
      typeof x === 'number' ? x : {vverh:x.vverh, vniz:x.vniz});
  }
  return o;
}
// Устойчивый разброс стартов: от имени величины, а не от случайности —
// иначе один и тот же переход каждый раз шёл бы иначе.
function razbros(imya){
  let h = 2166136261;
  for (let i = 0; i < imya.length; i++){ h ^= imya.charCodeAt(i); h = Math.imul(h, 16777619); }
  return ((h >>> 0) % 1000) / 1000;
}

class Vedenie {
  constructor(sb, cel){
    this.sb = sb;                 // живой набор прибора — его и правим
    this.a = snimok(sb);          // откуда
    this.b = snimok(cel);         // куда
    this.risunok = cel.risunok; this.imya = cel.imya; this.semya = cel.semya;
    this.t = 0; this.shag = 1 / (SR * SROK);
    this.sdvig = {};
    for (const k in this.b){
      // Окно этой величины внутри общего срока: трогается когда придётся, а
      // ВСТАЮТ все ровно к концу. Прежде конец считался от начала, и у
      // поздних величин уезжал за единицу — они не доезжали вовсе.
      const r = razbros(k);
      this.sdvig[k] = [r * .35, .65 + r * .35];
    }
  }
  hod(k){
    const [n, kon] = this.sdvig[k];
    const u = clamp((this.t - n) / (kon - n), 0, 1);
    return u * u * (3 - 2 * u);                   // трогается и встаёт плавно
  }
  static tochka(a, b, e){
    return (a > 0 && b > 0) ? a * Math.pow(b / a, e) : a + (b - a) * e;
  }
  step(n){
    this.t += this.shag * n;
    const sb = this.sb;
    for (const k in this.b){
      const e = this.hod(k);
      if (e <= 0) continue;
      const a = this.a[k], b = this.b[k];
      if (typeof b === 'number') sb[k] = Vedenie.tochka(a, b, e);
      else for (let i = 0; i < b.length; i++){
        if (typeof b[i] === 'number') sb[k][i] = Vedenie.tochka(a[i], b[i], e);
        else {
          sb[k][i].vverh = Vedenie.tochka(a[i].vverh, b[i].vverh, e);
          sb[k][i].vniz  = Vedenie.tochka(a[i].vniz,  b[i].vniz,  e);
        }
      }
    }
    // СВЕДЕНИЕ — не самостоятельный номинал, а ОТНОШЕНИЕ: собранный прибор
    // настраивают под его же конденсаторы. Если вести его отдельно от
    // ёмкостей, на середине пути прибор окажется сведён не под свои — таким
    // его никто бы не собрал. Пересчитываем, сохраняя разброс подбора.
    for (let i = 1; i < 3; i++){
      const otkl = sb.Ru[i] / (sb.Ru[0] * sb.sved[i]);
      sb.sved[i] = sb.C[0] / sb.C[i];
      sb.Ru[i] = sb.Ru[0] * sb.sved[i] * otkl;
    }
    if (this.t >= 1){
      // Рисунок сетки — перемычки в диодной матрице, целое число от нуля до
      // семи. Промежуточного рисунка не бывает, поэтому он переключается в
      // самом конце, когда всё остальное уже приехало и менять больше нечего.
      sb.risunok = this.risunok; sb.imya = this.imya; sb.semya = this.semya;
      return true;
    }
    return false;
  }
}

