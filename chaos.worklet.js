// ============================================================================
//  ХАОС — ядро инструмента. Физическая модель схемы, а не модель звука.
//
//  Здесь нет ни одной величины, придуманной для удобства: только омы, фарады,
//  вольты, генри, ньютоны и килограммы. Частота нигде не задаётся — она
//  ПОЛУЧАЕТСЯ из номиналов, как в железе. Ручки крутят сопротивления и
//  напряжения, а не параметры звука.
//
//      Сборка     номиналы этого экземпляра: R, C, L, пороги, динамик
//      Шум        тепловой (Джонсона) и фликкерный 1/f
//      Батарея    ЭДС, внутреннее сопротивление, развязка, разряд
//      Узел       конденсатор + триггер Шмитта + все ветви токов по Кирхгофу
//      Оптопара   лампочка и фоторезистор — управляемое сопротивление
//      Качели     два медленных узла: рисунок и его drift
//      Динамик    электромеханика: катушка, масса, подвес, противо-ЭДС
//      Прибор     провода между всем этим
//
//  Уравнение узла — первый закон Кирхгофа на конденсаторе:
//      C·dV/dt = (Vвых−V)/Rос + (Vупр−V)/Rу + (Vсосед−V)/Rсв − V/Rут + Iдиод
//  Линейная часть решается аналитически через эквивалентный источник, диоды
//  добавляются гладко по своей экспоненциальной ВАХ. При пересечении порога
//  ОСТАТОК ШАГА досчитывается с новым выходом — без этого период липнет к
//  сетке отсчётов и высота едет ступеньками (замерено: до 5% ошибки на
//  килогерцах, пилой).
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// Схема считается вчетверо чаще выхода: у прямоугольника с резким фронтом
// полоса шире слышимой, и без запаса его верхние гармоники заворачиваются
// вниз негармоничным звоном. В железе такого нет — там нет Найквиста.
const OVER = 4;
const FS = SR * OVER;
const dt = 1 / FS;

const kB = 1.380649e-23;      // постоянная Больцмана
const T0 = 300;               // комнатная температура, К
const nVt = .045;             // тепловое напряжение диода с коэффициентом идеальности

// Фильтр сведения: Баттерворт четвёртого порядка, два биквада каскадом.
class Decim {
  constructor(){
    this.z = [[0,0,0,0],[0,0,0,0]];
    const fc = SR * .43, K = Math.tan(Math.PI * fc / FS);
    this.b = [];
    for (const Q of [.5412, 1.3066]){
      const n = 1 / (1 + K/Q + K*K);
      this.b.push([K*K*n, 2*K*K*n, K*K*n, 2*(K*K-1)*n, (1 - K/Q + K*K)*n]);
    }
  }
  step(x){
    for (let i = 0; i < 2; i++){
      const [b0,b1,b2,a1,a2] = this.b[i], z = this.z[i];
      const y = b0*x + b1*z[0] + b2*z[1] - a1*z[2] - a2*z[3];
      z[1] = z[0]; z[0] = x; z[3] = z[2]; z[2] = y;
      x = y;
    }
    return x;
  }
}

// ---- ШУМ -------------------------------------------------------------------
// Тепловой шум резистора считается по формуле Джонсона: Vскз = √(4kTRΔf).
// Сверх него у углеродных резисторов есть избыточный токовый шум со спектром
// 1/f — он на порядки больше теплового и именно он даёт медленное «дыхание»
// частоты, по которому ухо отличает живую схему от расчёта.
class Noise {
  constructor(){ this.f = [0, 0, 0]; }
  teplovoy(R, T){ return Math.sqrt(4 * kB * T * R * FS / 2) * (Math.random() * 2 - 1) * 1.73; }
  flikker(){
    // три полюса с разнесёнными постоянными дают спектр, близкий к 1/f
    const b = Math.random() * 2 - 1;
    this.f[0] += (b - this.f[0]) * .00008;
    this.f[1] += (b - this.f[1]) * .0016;
    this.f[2] += (b - this.f[2]) * .032;
    return this.f[0] * 3.2 + this.f[1] * 1.1 + this.f[2] * .4;
  }
}

// ---- СБОРКА ----------------------------------------------------------------
// Номиналы этого экземпляра в реальных единицах. Разброс — не «tone», а
// допуски деталей: резисторы ±5%, керамика ±20%, микросхемы разных партий.
class Build {
  constructor(semya){
    let x = (semya >>> 0) || 1;
    const r = () => { x = (Math.imul(x, 1664525) + 1013904223) >>> 0; return x / 4294967296; };
    const m = (a, b) => a + r() * (b - a);
    this.r = r;

    // Диодная матрица рисунка ВПАЯНА в этот экземпляр — как поворот и свинг.
    // Переключателем она была зря: рисунок не настройка, а монтаж. Другой
    // рисунок — другой прибор, то есть Tab.
    this.risunok = Math.floor(m(0, 7.999));
    this.sbivka = m(0, .95);           // поворот рисунка — впаян, не ручка
    this.gruv   = m(.05, .55);         // насколько ленив счётчик на нечётных
    this.EMF   = m(8.2, 9.4);          // свежая крона, В
    this.Rvn   = m(2.5, 26);           // внутреннее сопротивление батареи, Ом
    this.Crazv = m(47e-6, 220e-6);     // ёмкость по батарее, Ф
    this.Rrazv = m(600, 2400);         // развязка питания логики, Ом
    this.Clog  = m(2.2e-6, 22e-6);     // конденсатор у микросхемы, Ф

    // Пороги триггера Шмитта. У реальной микросхемы они НЕ симметричны
    // относительно половины питания — отсюда скважность, отличная от ровных
    // 50%, ещё до всякого смещения.
    // Пороги задаются партией: у этого КОРПУСА они такие. Элементы внутри
    // сидят на одном кристалле и согласованы в пределах процентов — врозь
    // они разбрасывались бы в два с лишним раза по постоянной времени, и
    // никакого унисона не получалось бы в принципе.
    const vverhc = m(.55, .62), vnizc = m(.36, .44);
    this.vt = [];
    for (let i = 0; i < 3; i++)
      this.vt.push({ vverh: vverhc * m(.985, 1.015), vniz: vnizc * m(.985, 1.015) });
    this.Rvyh = m(150, 420);           // сопротивление открытого канала, Ом
    this.Rut  = m(80e6, 400e6);        // утечка конденсатора, Ом

    // Звуковые узлы: керамика с разбросом ±20% и свои цепи
    this.C   = [m(8.2e-9, 12e-9), m(8.2e-9, 12e-9), m(8.2e-9, 12e-9)];
    // Управляющий резистор должен быть СОПОСТАВИМ с цепью заряда, иначе он
    // не смещает конденсатор, а привязывает его к управляющему напряжению —
    // и генератор запирается наглухо. Здесь единицы мегаом, как в схеме.
    this.Ru  = [m(1.8e6, 3.2e6), m(2.0e6, 3.6e6), m(2.4e6, 4.2e6)];
    // Паразитная link между узлами ЁМКОСТНАЯ: дорожки на плате лежат рядом,
    // это единицы пикофарад. Она перебрасывает заряд на фронтах соседа и
    // ничего не тянет постоянно — резистивная link такого номинала просто
    // не дала бы конденсатору дойти до порога.
    this.Csv = m(.6e-12, 4.5e-12);
    // Резистор кросс-связи сопоставим с цепями заряда — иначе link только
    // называется связью, а генераторы её не чувствуют.
    this.Rsvyazi = m(180e3, 620e3);
    this.razv = [1, m(1.5, 2.6), m(5.5, 11)];    // куда разводят подстроечники
    this.ves  = [1, m(.75, .95), m(.6, .9)];      // доли в суммирующей цепи

    // Оптопара в цепи заряда: лампочка и фоторезистор. Сопротивление
    // фоторезистора падает по степенному закону от освещённости.
    // Фоторезистор: в темноте он держит генератор в области треска, на свету
    // отпускает под три килогерца. Отношение задаёт depth качелей.
    this.Rtemn = m(4.0e6, 5.4e6);
    this.Rsvet = m(40e3, 60e3);
    // Утечка платы: флюс, влага, сам монтаж. Она стоит параллельно
    // частотозадающей цепи и ограничивает эквивалентное сопротивление
    // сверху — то есть держит НИЖНЮЮ границу частоты. Благодаря ей общий
    // подстроечник может увести прибор вниз, а треск внизу качелей никуда
    // не денется: цепь просто упрётся в утечку.
    this.Rpl = m(4.5e6, 9e6);
    this.gamma = m(.72, .95);          // показатель фоторезистора
    this.inerc = m(.004, .012);        // послесвечение слоя, с
    this.nagrev = m(.008, .020);       // разогрев нити, с
    this.ostyv  = m(.030, .075);       // остывание нити, с — оно всегда дольше

    // Медленные узлы: электролит, поэтому разброс больше
    this.Cm  = m(1.8e-6, 2.7e-6);
    this.Cg  = m(3.9e-6, 6.8e-6);

    // Динамик: маленький бумажный
    // Высокоомный капсюль: восьмиомный динамик крона просто не потянет —
    // он сажает её насмерть. В таких приборах ставили телефонный капсюль на
    // полсотни ом и выше, и ток получался в единицы миллиампер.
    this.Rkat = m(48, 110);            // Ом
    this.L    = m(.22e-3, .55e-3);     // Гн
    this.Bl   = m(1.4, 2.8);           // Тл·м
    // Телефонный капсюль — не динамик: мембрана лёгкая, подвес жёсткий,
    // резонанс высоко. Низа он не отдаёт физически, зато звенит и трещит.
    // Прежние 72–190 Гц — это басовик, оттого прибор и гудел мотором.
    this.mms  = m(.04e-3, .13e-3);     // кг
    this.f0   = m(420, 1150);          // Гц, резонанс мембраны
    this.Qms  = m(1.5, 3.6);           // добротность — звонкость
    this.xmax = m(.05e-3, .16e-3);     // м, ход до жёсткого подвеса
    this.Rus  = m(6, 26);              // выходное сопротивление каскада, Ом
    // КОРПУС. Капсюль сидит не в воздухе, а в коробке, и она переизлучает
    // низ на своём резонансе. Отсюда бас, которого у самой мембраны нет и
    // быть не может: она для этого слишком лёгкая.
    this.fKorp = m(74, 165);           // Гц, резонанс коробки
    this.Qkorp = m(1.1, 2.8);          // насколько гулкая
    this.vkladk = m(.55, 1.5);         // как плотно капсюль связан с корпусом

    this.Cvyh = m(4.7e-6, 22e-6);      // разделительный конденсатор
    this.Cpar = m(120e-12, 900e-12);   // паразитная ёмкость монтажа
    this.αR   = m(1.4e-4, 6e-4);       // ТКС резистора, 1/К
    this.αC   = m(-1.6e-3, -4e-4);     // ТКЕ керамики, 1/К
    this.shumR = m(2, 40);              // избыточный токовый шум: угольные шумят
    // ИМЯ СБОРКИ. Не первые знаки самого числа: у близких семян они
    // совпадают — 1626943591, 1626943592 и 1626943600 давали одно и то же
    // «qwn1», — а имя, которое не меняется при смене прибора, хуже, чем
    // никакого. Число сперва перемешивается, поэтому любая правка семени
    // меняет все четыре знака сразу.
    this.semya = semya >>> 0;
    let h = this.semya ^ 0x9e3779b9;
    h = Math.imul(h ^ (h >>> 16), 0x21f0aaad);
    h = Math.imul(h ^ (h >>> 15), 0x735a2d97);
    h = (h ^ (h >>> 15)) >>> 0;
    this.imya = ('0000' + (h % 1679616).toString(36)).slice(-4);

    // СВЕДЕНИЕ. Собранный прибор настраивают: под каждый конденсатор
    // подбирают резисторы так, чтобы постоянные времени совпали. Тогда при
    // сведённых подстроечниках генераторы идут в унисон, и РАЗВОДУ есть что
    // разводить. Подбор идёт по отношению ёмкостей, поэтому совпадение
    // держится при любом положении ручек, а не в одной точке диапазона.
    this.sved = [1, this.C[0]/this.C[1], this.C[0]/this.C[2]];
    for (let i = 1; i < 3; i++) this.Ru[i] = this.Ru[0] * this.sved[i] * m(.97, 1.03);
    // Остаётся разброс порогов микросхемы — он и даёт биения в унисоне.
    // Его не подстроить: это разные экземпляры элементов в одном корпусе.

    // ВНИМАНИЕ: всё новое дописывается ТОЛЬКО СЮДА, в конец. Номиналы идут
    // из семени по порядку, и вставка нового вызова в середину сдвигает всю
    // последовательность — тот же seed стал бы другим прибором, а все
    // сохранённые пресеты зазвучали бы чужими. Порядок здесь — договор.
    // СУММИРУЮЩАЯ ЦЕПЬ — пассивная: три резистора сходятся на базу одного
    // транзистора, и оттого ветви СЛЫШАТ ДРУГ ДРУГА. Приходит третий
    // генератор — общая проводимость узла растёт, и первые два приседают.
    // На операционнике этого бы не было, но операционника на плате нет, и
    // именно эта просадка читается ухом как «включилось в живую схему», а
    // не «подмешалось вторым файлом».
    this.Rsum0 = m(47e3, 120e3);
    this.Rbaza = m(68e3, 180e3);
    // КЛЮЧ-ОПТОПАРА. Тумблер генератора коммутирует не сигнал, а ЛАМПОЧКУ
    // напротив фоторезистора в его ветви. Сигнал с постоянной составляющей
    // рвать контактом нельзя — будет щелчок в полшкалы, поэтому в технике
    // той же эпохи для беззвучной коммутации ставили ровно это. Лампочка
    // разогревается за сотые доли секунды, а остывает в разы дольше: отсюда
    // несимметричный переход, который ухо и слышит как аналоговый.
    this.RklTemn  = m(6e6, 14e6);
    this.RklSvet  = m(14e3, 30e3);
    this.klNagrev = m(.025, .055);
    this.klOstyv  = m(.16, .40);

    // МЁРТВЫЕ НОМИНАЛЫ. Здесь стоял ударный контур — двойное Т из драм-машины.
    // Он выкинут: этому прибору неоткуда взять ни такой узел, ни триггер для
    // него, и звучал он чужеродно. Но три вызова остаются на месте НАВСЕГДА:
    // порядок номиналов — договор с сохранёнными пресетами, и убрать их
    // значит сдвинуть всё, что идёт следом, и сломать каждый пресет.
    m(.72, .95); m(46, 88); m(.28, .52);

    // МОДЫ СТЕНКИ. У прямоугольной панели не одна частота, а гребёнка — и
    // именно её смесь делает звук деревянным. Одной моды хватало, пока
    // корпус только ОКРАШИВАЛ излучение; когда по нему стали бить, стало
    // слышно, что там синусоида, а не коробка.
    //
    // Высшие моды затухают быстрее (потери растут с частотой) и почти не
    // слышат капсюль: его отдача сосредоточена в точке крепления и
    // низкочастотна, она гонит основную. Ладонь же бьёт широко и заводит все.
    this.modY = [1, m(2.2, 2.9), m(3.9, 5.4)];
    this.modQ = [1, m(.55, .75), m(.35, .55)];   // доли добротности основной
    this.modK = [1, m(.012, .024), m(.004, .010)]; // насколько их слышит капсюль
    this.modU = [1, m(.65, .85), m(.45, .70)];   // насколько их заводит ладонь
    // Касание кожи о дерево — широкополосный треск, и опознаётся удар
    // в основном по нему, а не по звону.
    this.shlepF = m(1400, 3200);       // где звенит само касание
    this.shlepA = m(.10, .22);
  }
}

// ---- БАТАРЕЯ ---------------------------------------------------------------
// Не источник напряжения, а ЭДС с внутренним сопротивлением и развязывающим
// конденсатором. Импульсы жрут ток, шина проседает — и все узлы, сидящие на
// ней, слышат друг друга. Развязки нет намеренно: она убила бы живость.
class Battery {
  constructor(sb){ this.sb = sb; this.V = sb.EMF; this.Vl = sb.EMF; this.iznos = 1; }
  // Общая шина: батарейка со своим внутренним сопротивлением и ёмкостью.
  // Ток капсюля качает её на сотни милливольт — так и есть в железе.
  //
  // ПИТАНИЕ ЛОГИКИ берётся от шины через развязывающую цепочку: резистор и
  // конденсатор рядом с микросхемой. Это стандарт монтажа, и именно его
  // качество решает, услышит ли логика, как дёргается капсюль. Ручка ДРЕБЕЗГ
  // убирает этот конденсатор — тогда пульсация доходит до порогов триггеров
  // и прибор начинает модулировать сам себя. Вот откуда хрип в самоделках;
  // тепловой шум резистора тут ни при чём, он даёт микровольты.
  step(I, razvyazka){
    const τ = Math.max(1e-9, this.sb.Crazv * this.sb.Rvn);
    // ЭДС берётся из ЖИВОГО набора, а не из копии, снятой при сборке: когда
    // номиналы ведутся при переходе, копия осталась бы от прежнего прибора.
    const Vravn = this.sb.EMF * this.iznos - I * this.sb.Rvn;
    this.V += (Vravn - this.V) * (1 - Math.exp(-dt / τ));
    if (this.V < 1) this.V = 1;
    const Cl = this.sb.Clog * Math.pow(.0009, 1 - clamp(razvyazka, 0, 1));
    const τl = Math.max(1e-9, Cl * this.sb.Rrazv);
    this.Vl += (this.V - this.Vl) * (1 - Math.exp(-dt / τl));
    if (this.Vl < 1) this.Vl = 1;
    return this.Vl;
  }
  // Крона отдаёт свои полтора ампер-часа примерно за десять часов работы.
  sadis(){ this.iznos = Math.max(.55, this.iznos - 6.5e-11); }
}

// ---- ОПТОПАРА --------------------------------------------------------------
// Лампочка накаливания напротив фоторезистора — так в этих схемах и делали
// управляемое сопротивление. У фоторезистора степенная характеристика и
// заметная инерция слоя: он не успевает за быстрым сигналом, и от этого
// управление само по себе получается мягким.
class Opto {
  constructor(sb){ this.sb = sb; this.nit = .5; this.svet = .5; }
  // Нить накаливания разогревается быстро, а остывает МЕДЛЕННО — теплоёмкость
  // одна, а мощность подводится только при разогреве. Отсюда несимметричная
  // огибающая: качели взлетают резко и сползают вниз долго, и внизу, в
  // области треска, прибор проводит больше времени, чем наверху.
  //
  step(upr){
    const cel = clamp(upr, 0, 1);
    const τ = cel > this.nit ? this.sb.nagrev : this.sb.ostyv;
    this.nit += (cel - this.nit) * (1 - Math.exp(-dt / τ));
    // Инерция самого фоторезисторного слоя — она у него своя и небольшая.
    this.svet += (this.nit - this.svet) * (1 - Math.exp(-dt / this.sb.inerc));
    const s = Math.max(1e-4, this.svet);
    return this.sb.Rtemn * Math.pow(this.sb.Rsvet / this.sb.Rtemn, Math.pow(s, this.sb.gamma));
  }
}

// ---- КЛЮЧ ------------------------------------------------------------------
// Оптопара как беззвучный коммутатор. Тумблер включает лампочку, а в цепь
// сигнала смотрит фоторезистор: пока нить разогревается, сопротивление
// сползает с мегаом до килоом, и ветвь ВЪЕЗЖАЕТ в суммирующий узел, а не
// впрыгивает. Ход туда и обратно разный по природе — нить греется подводимой
// мощностью, а остывает сама, — поэтому включение резче выключения, и ничем
// другим этого не подделать.
class Klyuch {
  constructor(sb){ this.sb = sb; this.nit = 0; this.svet = 0; }
  step(vkl){
    const sb = this.sb;
    const cel = vkl ? 1 : 0;
    const t = cel > this.nit ? sb.klNagrev : sb.klOstyv;
    this.nit += (cel - this.nit) * (1 - Math.exp(-dt / t));
    this.svet += (this.nit - this.svet) * (1 - Math.exp(-dt / sb.inerc));
    const s = Math.max(1e-4, this.svet);
    return sb.RklTemn * Math.pow(sb.RklSvet / sb.RklTemn, Math.pow(s, sb.gamma));
  }
}

// ---- УЗЕЛ ------------------------------------------------------------------
// Конденсатор, триггер Шмитта, резистор обратной связи. Всё остальное —
// ветви, которые в него втекают.
class Cell {
  constructor(sb, C, vt, shum){
    this.sb = sb; this.C = C; this.vt = vt; this.shum = shum;
    this.V = sb.EMF * .3; this.q = 1;
    this.vyh = 0; this.sgl = 0;
    this.tzar = 0; this.trazr = 0;
    this.f = 0; this.skv = .5; this.schelchok = 0; this.I = 0;
  }

  // Rос   — резистор обратной связи (обычно фоторезистор оптопары)
  // Vупр  — управляющее напряжение и его резистор
  // dVсос — насколько за этот шаг сдвинулся выход соседа: через паразитную
  //         ёмкость это переносит в конденсатор заряд Cсв·dVсос
  // Vdd   — живое питание
  // темп  — превышение температуры над комнатной, К
  // шумК  — множитель избыточного токового шума (ручка ДРЕБЕЗГ)
  step(Ros, Vupr, Ru, dVsos, Vsos, Rsv, Vdd, temp, Vvh, Rvh){
    const sb = this.sb;
    // Температура ведёт номиналы: медь и углерод греются, керамика плывёт.
    const Rt = 1 + sb.αR * temp, Ct = 1 + sb.αC * temp;
    const C = this.C * Ct;
    const Rf = Ros * Rt + sb.Rvyh;      // канал выхода последователен с цепью
    const porogv = Vdd * this.vt.vverh, porogn = Vdd * this.vt.vniz;

    // Шум в цепи заряда: тепловой предел плюс избыточный токовый шум
    // углеродного резистора, у которого спектр 1/f.
    // Тепловой шум по Джонсону плюс избыточный токовый шум углерода со
    // спектром 1/f. Оба честные по величине — на слух они почти не слышны,
    // но именно они не дают двум периодам совпасть в точности.
    const Vt = this.shum.teplovoy(Ros, T0 + temp);
    const Vsh = Vt + this.shum.flikker() * Vt * sb.shumR;

    this.schelchok = 0;
    let ostatok = dt, vitkov = 0;
    while (ostatok > 1e-12 && vitkov < 4){
      vitkov++;
      const Vvyh = this.q ? Vdd : 0;
      // первый закон Кирхгофа: суммируем проводимости и токи ветвей
      const Gvh = Rvh ? 1/Rvh : 0;
      const G = 1/Rf + 1/Ru + 1/sb.Rut + 1/Rsv + Gvh;
      const Ve = (Vvyh/Rf + (Vupr + Vsh)/Ru + Vsos/Rsv + (Vvh||0) * Gvh) / G;
      const τ = C / G;
      const prev = this.V;
      const porog = this.q ? porogv : porogn;
      // Триггер реагирует на УРОВЕНЬ, а не на пересечение: если напряжение
      // уже за порогом — он переключён, и точка. Прежде код ждал момента
      // пересечения и, проскочив его на старте, зависал навсегда.
      if (this.q ? prev > porog : prev < porog){
        this.q ^= 1;
        this.schelchok = this.q ? 1 : -1;
        if (this.q){
          const T = this.tzar + this.trazr;
          if (T > 1e-9){ this.f = 1 / T; this.skv = this.tzar / T; }
          this.tzar = 0; this.trazr = 0;
        }
        continue;
      }
      // Сколько времени осталось до порога — из точного решения экспоненты.
      // Если асимптота его не достигает, переключения в этом шаге не будет.
      let τdo = Infinity;
      const d0 = prev - Ve, d1 = porog - Ve;
      if (d0 !== 0 && d1 / d0 > 0 && Math.abs(d1) < Math.abs(d0)) τdo = -Math.log(d1 / d0) * τ;

      if (τdo <= ostatok){
        // доводим ровно до порога, переключаем и ДОСЧИТЫВАЕМ ОСТАТОК ШАГА
        this.V = porog;
        this.q ^= 1;
        this.schelchok = this.q ? 1 : -1;
        this.perekl = (dt - ostatok + τdo) / dt;    // где внутри шага
        if (this.q){
          const T = this.tzar + this.trazr;
          if (T > 1e-9){ this.f = 1 / T; this.skv = this.tzar / T; }
          this.tzar = 0; this.trazr = 0;
        }
        if (this.q) this.tzar += τdo; else this.trazr += τdo;
        ostatok -= τdo;
      } else {
        this.V += (Ve - this.V) * (1 - Math.exp(-ostatok / τ));
        if (this.q) this.tzar += ostatok; else this.trazr += ostatok;
        ostatok = 0;
      }
      this.I = Math.abs(Vvyh - this.V) / Rf;
    }
    // Заряд, переброшенный через паразитную ёмкость фронтом соседа.
    if (dVsos) this.V += sb.Csv * dVsos / C;

    // ЗАЩИТНЫЕ ДИОДЫ. Ток через диод растёт экспоненциально, поэтому
    // напряжение за шиной растёт логарифмически — ограничение мягкое, а не
    // обрубленное. Это единственная величина в схеме, не пропорциональная
    // питанию, и только благодаря ей просадка вообще слышна.
    if (this.V > Vdd) this.V = Vdd + nVt * Math.log1p((this.V - Vdd) / nVt);
    else if (this.V < 0) this.V = -nVt * Math.log1p(-this.V / nVt);

    // Выход элемента заряжает паразитную ёмкость монтажа через свой канал —
    // отсюда конечная скорость фронта. Ступенька за один отсчёт даёт полосу
    // шире слышимой; в железе её ограничивает именно эта RC.
    const Vcel = this.q ? Vdd : 0;
    // Фронт ограничен зарядом паразитной ёмкости через открытый канал.
    // Множитель прежде был впятеро больше — фронты сглаживались до
    // неразличимости, и щелчки превращались в гудение.
    const τf = sb.Rvyh * sb.Cpar * 45;
    this.sgl += (Vcel - this.sgl) * (1 - Math.exp(-dt / τf));
    this.vyh = this.sgl;
    // Ток потребления: заряд конденсатора плюс сквозной бросок при
    // переключении. Бросок длится десятки наносекунд, поэтому в средний ток
    // за шаг он входит своим ЗАРЯДОМ, а не полной амплитудой — иначе
    // батарейка садилась бы вдвое на ровном месте.
    this.Ipit = this.I + (this.schelchok ? 2.2e-3 * 8e-8 / dt : 0);
    return this.vyh;
  }

  upr(Vdd){ return clamp((this.V/Vdd - this.vt.vniz) / (this.vt.vverh - this.vt.vniz), 0, 1); }
}

// ---- КАЧЕЛИ ----------------------------------------------------------------
// Два медленных узла: первый ведёт рисунок, второй качает период первого.
// Ручка КАЧАНИЕ — это подстроечник в цепи первого, и она задаёт ПЕРИОД:
// слева сопротивление мало и sway сливается в тембр, справа велико и
// прибор дышит одним движением на несколько секунд.
class Swing {
  constructor(sb, shum){
    this.sb = sb;
    this.medl = new Cell(sb, sb.Cm, sb.vt[1], shum);
    this.gul  = new Cell(sb, sb.Cg, sb.vt[2], shum);
    this.u = .5; this.g = .5; this.period = 0;
  }
  // hit — подстроечник смещения в цепи медленного узла. Постоянный ток
  // помогает заряду и мешает разряду, поэтому конденсатор скатывается вниз
  // медленно, а взлетает быстро: прибор проводит в нижней половине качелей —
  // в области треска — куда больше времени, чем наверху. Это и есть тот
  // самый долгий «тррррр» с коротким выкриком на верхушке.
  step(sway, drift, hit, Vdd, temp){
    // Ёмкости берутся из живого набора каждый шаг — как и у звуковых узлов.
    // Захваченные в конструкторе, они не доезжали при ведении номиналов, и
    // качели оставались от прежнего прибора, хотя отчёт показывал новый
    // период: он-то считался по свежему номиналу.
    this.medl.C = this.sb.Cm; this.gul.C = this.sb.Cg;
    const vt = this.sb.vt[1];
    // Постоянная схемы: сколько RC укладывается в период при этих порогах.
    const K = Math.log((1 - vt.vniz) / (1 - vt.vverh)) + Math.log(vt.vverh / vt.vniz);
    // Подстроечник: 12 кОм … 3.9 МОм
    let R = 12e3 * Math.pow(3.9e6 / 12e3, sway);
    if (drift > .002){
      const Rg = R * 11;
      this.gul.step(Rg, 0, 1e12, 0, 0, 1e12, Vdd, temp);
      this.g = this.gul.upr(Vdd);
      R *= Math.pow(2, (this.g - .5) * drift * 3.4);
    } else this.g = .5;
    // Смещение снимается с ОТВОДА того же подстроечника, поэтому его доля
    // держится при любом положении ручки КАЧАНИЕ. Чем ближе точка покоя
    // разряда подходит к нижнему порогу, тем медленнее конденсатор к нему
    // подползает — и тем дольше прибор сидит в нижней половине качелей.
    // Вплотную подойти нельзя: за порогом генератор просто запрётся.
    // Шкала растянута к правому краю: там, где точка покоя подходит к порогу
    // вплотную, каждый процент хода ручки стоит вдвое дороже предыдущего.
    const k = 20 * Math.pow(1.9 / 20, Math.pow(clamp(hit, 0, 1), .55));
    this.medl.step(R, Vdd, R * k, 0, 0, 1e12, Vdd, temp);
    this.u = this.medl.upr(Vdd);
    this.period = K * R * this.sb.Cm;
    return this.u;
  }
}

// ---- ДИНАМИК ---------------------------------------------------------------
// Электромеханика целиком: ток в катушке, сила Ампера, масса на подвесе,
// противо-ЭДС обратно в цепь. Излучает он УСКОРЕНИЕМ — звуковое давление
// пропорционально именно ему, поэтому выше резонанса отдача плоская.
// Сколько длится касание ладони и с какой силой. Три миллисекунды — обычное
// время контакта руки с деревянной стенкой. Сила выведена замером: удар
// выходит втрое-вчетверо громче того, что прибор играет сам, и не бьётся в
// потолок ограничителя.
const UDAR_DL = .003;
const UDAR_SILA = .08;

class Speaker {
  constructor(sb){
    this.sb = sb;
    this.I = 0; this.v = 0; this.x = 0; this.a = 0;
    this.k = sb.mms * Math.pow(2 * Math.PI * sb.f0, 2);
    this.c0 = sb.mms * 2 * Math.PI * sb.f0 / sb.Qms;
    // стенка корпуса: своя масса на своей упругости
    // Три моды стенки вместо одной.
    this.mv = [0,0,0]; this.mx = [0,0,0];
    this.udT = 0; this.udS = 0; this.shlep = 0; this.shlepZ = 0;
    this.kv = 0; this.kx = 0;
    this.ωk = 2 * Math.PI * sb.fKorp;
    this.zatk = 1 / sb.Qkorp;
  }
  // Пружина, демпфер и корпус выведены из номиналов, а не хранятся отдельно.
  // Когда номиналы едут, их надо пересчитать — иначе динамик остался бы от
  // прежнего прибора.
  perechitay(){
    const sb = this.sb;
    this.k = sb.mms * Math.pow(2 * Math.PI * sb.f0, 2);
    this.c0 = sb.mms * 2 * Math.PI * sb.f0 / sb.Qms;
    this.ωk = 2 * Math.PI * sb.fKorp;
    this.zatk = 1 / sb.Qkorp;
  }

  // УДАР ЛАДОНЬЮ ПО КОРПУСУ. Рука передаёт стенке импульс напрямую, и та
  // отзванивает своим низом — тем самым, на котором держится весь бас
  // прибора. Это единственное, что человек делает с шумовой коробкой руками
  // и что в модели до сих пор не было представлено ничем.
  udar(sila){
    this.udT = UDAR_DL; this.udS = sila;
    this.shlep = 1;
    // Удар трясёт и сам капсюль: мембрана по инерции идёт относительно рамы.
    // Это верх удара — без него он глухой, будто бьёшь по пустому месту.
    this.v += sila * .08;
  }

  // U — напряжение каскада; демпф — палец на корпусе.
  //
  // Демпфирует диффузор не столько подвес, сколько САМА КАТУШКА: двигаясь в
  // поле, она наводит ток, а тот тормозит движение. Сила этого торможения
  // равна Bl²/R и при обычных номиналах вдвое больше механической — вот
  // почему динамик звучит одинаково собранно почти при любом подвесе.
  step(U, dempf){
    const sb = this.sb;
    const R = sb.Rkat + sb.Rus;
    // L·dI/dt = U − I·R − Bl·v   (противо-ЭДС)
    const Iravn = (U - sb.Bl * this.v) / R;
    const τL = sb.L / R;
    this.I += (Iravn - this.I) * (1 - Math.exp(-dt / τL));
    // Подвес нелинейный: чем дальше ушёл диффузор, тем жёстче тянет назад.
    // Это не защита от перегруза, а устройство подвеса — отсюда грязный низ.
    const otn = this.x / sb.xmax;
    const k = this.k * (1 + 1.8 * otn * otn);
    // Q ведёт демпфирование: ручка УДАР ослабляет подвес, палец добавляет
    const c = this.c0 * (1 + dempf * 2.2);
    const F = sb.Bl * this.I - k * this.x - c * this.v;
    this.a = F / sb.mms;
    this.v += this.a * dt;
    this.x += this.v * dt;
    if (!(this.x === this.x)){ this.x = 0; this.v = 0; this.I = 0; this.a = 0; }

    // КОРПУС. Капсюль привинчен к коробке, и по третьему закону толкает её с
    // той же силой, с какой сам движется. Коробка тяжёлая и вялая, за
    // щелчками не успевает — но каждый щелчок её пинает, и она отзванивает
    // своим низом. Это и есть бас прибора: у самой мембраны его нет и быть
    // не может, она для этого слишком лёгкая.
    // Стенка корпуса НЕЛИНЕЙНА: на большом ходу упирается, и низ грязнеет.
    // Та же прогрессивная жёсткость, что у подвеса динамика, только у массы
    // побольше — отсюда рычание вместо ровного гула.
    // Ладонь касается корпуса миллисекунды, а не мгновение: сила нарастает и
    // спадает полусинусом. Мгновенный скачок скорости дал бы щелчок вместо
    // удара — щелчок это разрыв, а рука так не умеет.
    let ruka = 0;
    if (this.udT > 0){
      ruka = this.udS * Math.sin(Math.PI * (1 - this.udT / UDAR_DL));
      this.udT -= dt;
    }
    // Ладонь бьёт ШИРОКО и заводит все моды стенки; отдача капсюля
    // сосредоточена в точке крепления и низкочастотна — она гонит основную и
    // почти не слышна высшим. Оттого обычный звук от появления мод почти не
    // изменился, а удар стал деревянным вместо синусоидального.
    let stenka = 0;
    for (let i = 0; i < 3; i++){
      const ω = this.ωk * sb.modY[i];
      const zat = this.zatk / sb.modQ[i];
      const zhK = 1 + 3.4 * this.mx[i] * this.mx[i];
      this.mv[i] += ω * dt * (ruka * sb.modU[i]
                              + this.a * sb.vkladk * sb.modK[i] * 2.6e-4
                              - this.mx[i] * ω * zhK - this.mv[i] * zat);
      this.mx[i] += this.mv[i] * dt;
      if (!(this.mx[i] === this.mx[i])){ this.mx[i] = 0; this.mv[i] = 0; }
      stenka += this.mx[i] * ω;
    }
    this.kx = this.mx[0]; this.kv = this.mv[0];

    // САМО КАСАНИЕ. Хлопок кожи о дерево — широкополосный треск, и опознаётся
    // удар в основном по нему, а не по звону. Держится он миллисекунды.
    if (this.shlep > 0){
      this.shlep -= dt / .004;
      const sh = (Math.random() * 2 - 1) * this.shlep * this.shlep;
      const k = 1 - Math.exp(-2 * Math.PI * sb.shlepF / (1 / dt));
      this.shlepZ += (sh - this.shlepZ) * k;
    } else this.shlepZ *= .995;

    // Наружу идёт сумма: звон мембраны и тело коробки.
    // Корпус отзывается на удары заметно: это его резонанс и есть тело
    // звука. У капсюля низа нет физически, весь бас идёт отсюда.
    // Корпус отдаёт СМЕЩЕНИЕМ стенки, а не её скоростью: скорость шире по
    // спектру и тащит наверх то, что низом не является. Весь бас прибора —
    // отсюда, у капсюля его нет физически.
    return this.a + stenka * 2.4e6 + this.shlepZ * sb.shlepA * 3e5;
  }
}

// ---- СЕТКА -----------------------------------------------------------------
// РИТМ-СЕКЦИЯ, собранная из той же логики, что и прибор. Никаких семплов и
// никаких приклеенных слоёв: счётчик делит частоту тактового генератора на
// шестнадцать шагов, а логика на каждом шаге КОММУТИРУЕТ НОМИНАЛЫ самого
// прибора — освещённость оптопары и питание. Звучит при этом всё тот же
// прибор, просто его дёргают по рисунку.
//
// Рисунок — евклидов (алгоритм Бьорклунда): k ударов расставляются по n
// шагам максимально ровно. Это не выдумка для красоты: именно такие сетки
// дают ритмы, которые слышатся как музыка, а не как метроном, и в старом
// отзвуке они уже были отлажены на перкуссии.
//
// ГРУВ сдвигает нечётные доли назад по времени — то самое «не по линейке»,
// снятое с живых барабанщиков.
class Setka {
  constructor(){ this.faza = 0; this.shag = 0; this.risunok = []; this.kod = -1;
                 this.zhdet = undefined;
                 this.udar = 0; this.sila = 0; this.ogib = 0; this.novy = 0; }

  // РИСУНОК СОБИРАЕТСЯ ЛОГИКОЙ НА ОТВОДАХ ДЕЛИТЕЛЯ — так его и делали в
  // железе. Счётчик даёт отводы ÷2, ÷4, ÷8, ÷16, а диодная матрица решает,
  // какое их сочетание замыкает ключ. Оттуда берутся узнаваемые фигуры:
  // ровная четверть, восьмые, синкопа на «и», рваная группа.
  //
  // Евклидова сетка раскладывает удары РОВНО — это рейв. Хип-хоп живёт на
  // неровности: удары садятся на сильные доли, между ними дыры, а нечётные
  // шаги запаздывают.
  static sobrat(kod){
    const N = 16, r = new Array(N).fill(0);
    for (let i = 0; i < N; i++){
      const b1 = (i >> 0) & 1, b2 = (i >> 1) & 1, b4 = (i >> 2) & 1, b8 = (i >> 3) & 1;
      let v;
      switch (kod){
        case 0: v = !b1 && !b2; break;                            // четверти
        case 1: v = (!b1 && !b2) || (b1 && b2 && !b4); break;      // четверть с синкопой
        case 2: v = (!b1 && !b2 && !b4) || (b1 && b2); break;      // редко и криво
        case 3: v = !b1; break;                                   // восьмые
        case 4: v = (b2 ^ b4) && !b1; break;                      // качель на восьмых
        case 5: v = (!b1 && !b2) || (b1 && !b2 && b8); break;      // четверть с добивкой
        case 6: v = ((i * 5) % 16) < 6; break;                    // сдвинутая группа
        case 7: v = 1; break;                                     // все шестнадцатые
        default: v = !b1 && !b2;
      }
      r[i] = v ? 1 : 0;
    }
    return r;
  }

  // period — длительность такта; kod — какое сочетание отводов замкнуто;
  // sbivka — поворот рисунка; gruv — насколько запаздывают нечётные шаги
  step(period, kod, sbivka, gruv){
    const N = 16;
    // ПЕРЕМЫЧКИ В МАТРИЦЕ не меняют посреди такта. Новый код запоминается, а
    // подхватывается на НАЧАЛЕ такта, где смена фигуры и без того ожидаема
    // ухом. Иначе рисунок переключался в произвольной точке — и это было
    // единственное настоящее событие во всём переходе между приборами.
    if (kod !== this.kod){
      if (this.kod === -1){ this.risunok = Setka.sobrat(kod); this.kod = kod; }
      else this.zhdet = kod;
    }
    const shagT = Math.max(1e-4, period) / N;
    this.faza += dt / shagT;
    // СВИНГ: на нечётных шагах счётчик ленивее, и доля запаздывает.
    const zaderzhka = (this.shag & 1) ? gruv * .42 : 0;
    if (this.faza >= 1 + zaderzhka){
      this.faza = 0;
      this.shag = (this.shag + 1) % N;
      if (this.shag === 0 && this.zhdet !== undefined && this.zhdet !== this.kod){
        this.risunok = Setka.sobrat(this.zhdet); this.kod = this.zhdet;
        this.zhdet = undefined;
      }
      const i = (this.shag + Math.round(sbivka * (N - 1))) % N;
      this.udar = this.risunok[i] ? 1 : 0;
      // Сила удара: у первого отвода делителя ключ замыкается плотнее, чем у
      // последующих, поэтому сильные доли выходят жирнее сами собой.
      this.sila = this.udar ? (((this.shag & 3) === 0) ? 1 : ((this.shag & 1) ? .55 : .78)) : 0;
      this.novy = 1; this.fronT = 0;
    } else this.novy = 0;
    this.fronT = (this.fronT || 0) + dt;
    if (this.fronT < .004) this.novy = 1;   // ключ держится замкнутым миг
    // Ключ не мгновенный: на затворе висит конденсатор, и напряжение спадает
    // по RC — быстрая атака, долгий выдох. Прежняя огибающая падала степенью
    // и была привязана к длине шага: удар выстреливал щелчком, а доля не
    // успевала прозвучать. Постоянные времени тут от самой цепи, а не от
    // темпа, поэтому на медленном темпе удары отчётливы, на быстром сливаются.
    const cel = (this.novy && this.udar) ? this.sila : 0;
    if (cel > this.ogib) this.ogib += (cel - this.ogib) * (1 - Math.exp(-dt / .0035));
    else this.ogib += (0 - this.ogib) * (1 - Math.exp(-dt / .045));
    return this.ogib;
  }
}

// ---- ПРИБОР ----------------------------------------------------------------
class Device {
  constructor(semya){
    this.sb = new Build(semya);
    this.shum = new Noise();
    this.bat = new Battery(this.sb);
    this.swing = new Swing(this.sb, this.shum);
    this.opto = [];
    this.cells = [];
    this.klyuch = [];
    for (let i = 0; i < 3; i++){
      this.cells.push(new Cell(this.sb, this.sb.C[i], this.sb.vt[i], this.shum));
      this.opto.push(new Opto(this.sb));
      this.klyuch.push(new Klyuch(this.sb));
    }
    this.osn = this.cells[0];
    this.din = new Speaker(this.sb);
    this.setka = new Setka();

    this.Cvyh = 0; this.holodny = 1; this.scDC = 0; this.temp = 0; this.moschn = 0;
    this.vyh = 0;
    this.int = new Float32Array(32); this.inti = 0; this.intN = 0; this.ssch = 0;
    this.razbr = 0; this.gc = 0;
  }

  step(p, utechka, navodka, kontakt, gls, ogib, petl){
    const sb = this.sb;
    let Vdd = this.bat.Vl * (kontakt === undefined ? 1 : kontakt);
    // Точка ввода внешнего сигнала. Номер положения переключателя.
    // КУДА — не выбор одной точки из двух, а положение переключателя между
    // ними: на середине сигнал входит в обе разом. Мгновенный выбор был
    // ступенькой ровно там, где её быть не должно.
    const tochka = clamp(p.kuda, 0, 1);
    const gl = p.golos || 0;
    if (gl > .002 && tochka > .002)
      Vdd *= 1 + clamp(gls || 0, -.9, .9) * .85 * gl * tochka;

    const u = this.swing.step(p.sway, p.drift, p.hit, Vdd, this.temp);

    // ХАРАКТЕР — подстроечник, задающий, в каких пределах ходит фоторезистор.
    // Нижняя точка держится в области треска на всём ходу: иначе рисунок
    // пропадает и остаётся вой.
    const har = clamp(p.tone, 0, 1);
    // ПИТЧ — подстроечник, включённый ПОСЛЕДОВАТЕЛЬНО с фоторезистором.
    // В тёмной фазе фоторезистор держит мегаомы, и добавка в сотни килоом на
    // его фоне не значит ничего — низ качелей стоит на месте. На свету он
    // падает до полусотни килоом, и там та же добавка решает всё: верхняя
    // точка опускается в разы. Поэтому низкие остаются при любом питче —
    // это соотношение номиналов, а не подгонка.
    // ДИАПАЗОН — большой общий подстроечник во всех трёх цепях разом. Он
    // включён и последовательно, и как масштаб: на одном краю прибор рокочет,
    // на другом пищит, и между ними проходит непрерывно. Тумблером это было
    // бы тремя ступенями, а на приборе крутилось плавно.
    const d = clamp(p.range, 0, 1);
    const massht = Math.pow(3.2, 1 - 2 * d);
    const Rposl = 1.1e6 * Math.pow(.0009, d);
    // РАЗМАХ — насколько глубоко лампочка отрабатывает качели. Раскрытие идёт
    // от середины, поэтому ноль — ровный тон, а не гул на самом низу.
    const rzm = clamp(p.depth, 0, 1);
    // Лампочка светит тем ярче, чем выше качели. Нижняя точка накала
    // фиксирована — она держит генератор в области треска на всём ходу
    // ХАРАКТЕРА; верхняя растёт с ручкой. Раскрытие идёт от середины, поэтому
    // нулевой depth даёт ровный тон, а не гул на самом низу.
    const svmin = .05, svmaks = .34 + har * .62;
    let yarkost = svmin + (svmaks - svmin) * clamp(.5 + (u - .5) * rzm, 0, 1);
    // НАКАЛ: огибающая источника ведёт лампочку — прибор говорит его ритмом.
    if (gl > .002 && tochka < .998){
      const dolya = gl * .95 * (1 - tochka);
      yarkost = clamp(yarkost * (1 - dolya) + clamp((ogib || 0) * 1.8, 0, 1) * dolya, 0, 1);
    }

    // СЕТКА. Ключи по фронтам счётчика коммутируют те же номиналы, что и
    // ручки: на ударном шаге лампочка гаснет, фоторезистор уходит в темноту
    // и прибор проваливается в треск, а между ударами возвращается. Питание
    // при этом на миг подсаживается, как от любого ключа на плате. Звучит
    // всё тот же прибор — просто его дёргают по рисунку.
    // Такт берётся от ТОГО ЖЕ медленного генератора, что качает прибор: в
    // железе счётчик делит его фронты, отдельного тактового не ставят. Такт
    // равен ОДНОМУ качанию: шестнадцать шагов укладываются внутрь качели.
    // Когда такт был вчетверо длиннее, качели давали свой всплеск на каждой
    // четверти и перебивали рисунок — читалась не сетка, а они.
    const ritm = this.setka.step(this.swing.period, this.sb.risunok,
                                 this.sb.sbivka, this.sb.gruv);
    // Сетка НЕ выключает прибор — это была бы драм-машина, где в паузах
    // тишина. Ключи коммутируют номиналы, от которых меняется ИСКАЖЕНИЕ:
    // звук идёт непрерывно, но на ударных шагах рвётся его тембр.
    //
    //   · смещение подскакивает — импульс сжимается в иглу, звук грязнеет;
    //   · параллельно цепи заряда подключается конденсатор — высота ныряет
    //     и возвращается;
    //   · замыкается связь между узлами — они срываются в захват.
    // БАРАБАННОСТЬ. На ударе прибор ныряет глубоко вниз и там перегружается:
    // накал падает почти до нуля (низ и треск), смещение подскакивает (игла),
    // связь замыкается, ток растёт — шина проседает, каскад упирается в
    // питание. Это и даёт рычащий бас вместо аккуратного щелчка.
    let ritmSm = 0, ritmSv = 0, ritmGr = 0;
    if (p.gryzn > .002){
      const g = p.gryzn;
      ritmSm = ritm * .19 * g;
      ritmSv = ritm * g;
      ritmGr = ritm * g;
      yarkost = yarkost * (1 - ritm * .95 * g) + svmin * ritm * .95 * g;
      // Между ударами ключ приоткрыт, а не разомкнут: звук не пропадает, но
      // доля слышна акцентом. Полный разрыв делал драм-машину, полное
      // отсутствие акцента — кашу, в которой рисунок не читается.
      Vdd *= 1 - g * .45 * (1 - ritm);
    }

    // ИМПУЛЬС — постоянное смещение через управляющий резистор: подгоняет
    // заряд и тормозит разряд, симметричный прямоугольник делается узким.
    // ИМПУЛЬС — отвод того же подстроечника, что задаёт частоту. Постоянный
    // ток подгоняет заряд и тормозит разряд, и точка покоя разряда подходит
    // к нижнему порогу: конденсатор к нему подползает всё медленнее, время
    // разряда растёт, а pulse сжимается в иглу. Отсюда треск при чистом
    // звуке — не шум, а короткие щелчки с чистыми паузами между ними.
    //
    // Отвод, а не отдельный резистор: доля должна держаться при любой
    // частоте. С отдельным резистором смещение работало только на низах, где
    // цепь заряда с ним сопоставима, и скважность не падала ниже половины.
    const ki = 20 * Math.pow(1.30 / 20, Math.pow(clamp(p.pulse + ritmSm * 2.6, 0, 1), .7));

    // ТУМБЛЕРЫ ГЕНЕРАТОРОВ. Каждый снимает питание со своего элемента: тот
    // перестаёт и звучать, и потреблять ток из шины. Первый выключить нельзя —
    // это ведущий, на нём держится вся схема.
    // Первый генератор снимается тем же тумблером, что и прочие: ведущим он
    // был только по привычке, а питание у него такое же.
    const vkl = [p.gen1 > .5 ? 1 : 0, p.gen2 > .5 ? 1 : 0, p.gen3 > .5 ? 1 : 0];
    // ТУМБЛЕР СВЯЗИ. Замыкает между генераторами настоящий резистор — не
    // паразитную ёмкость монтажа, которая передаёт только фронты, а
    // постоянную link. Тогда они перестают идти каждый сам по себе и
    // ЗАХВАТЫВАЮТСЯ в целые отношения: 2:1, 3:2, 5:4. Это язык Арнольда, и
    // слышно его как ритмическую фигуру вместо расстроенного гула.
    // Связь замыкается ручкой или ударом сетки — это один и тот же провод.
    // Замкнута связь или нет — величина непрерывная: наполовину замкнутая
    // связь это вдвое больший резистор, и генераторы захватываются слабее.
    // Удар сетки замыкает её по-прежнему резко: там это ключ, а не ручка.
    const zamk = Math.max(clamp(p.link, 0, 1), ritmSv > .12 ? 1 : 0);
    const Rsv = zamk > 1e-4 ? sb.Rsvyazi / (zamk * (1 + ritmSv * 2)) : 1e12;
    // Суммирующий узел: ток каждой ветви втекает в базу через свой резистор,
    // а базовый резистор тянет узел к нулю. Отсюда и общий уровень, и то,
    // что ветви приседают друг под друга.
    let Isum = 0, tok = 0, Gsum = 1 / sb.Rbaza;
    for (let i = 0; i < 3; i++){
      const uzel = this.cells[i];
      // Свет на фоторезистор: яркость от качелей, положение — от ХАРАКТЕРА.
      const sv = clamp(yarkost, 0, 1);
      // ТУМБЛЕР ДИАПАЗОНА переключает конденсаторы: маленькие ставят прибор в
      // писк, большие — в рокот. Плавной ручкой этого не сделать: там меняют
      // номинал, а не крутят.
      uzel.C = sb.C[i];
      let R = (this.opto[i].step(sv) * massht + Rposl) * sb.sved[i];
      // ПИТЧ — общий подстроечник во всех трёх цепях разом. Вверх он тянет
      // всё, вниз — упирается в утечку платы, и низ остаётся на месте.
      R = 1 / (1/R + 1/sb.Rpl);
      // РАЗВОД — подстроечники расходятся: первый на месте, второй рядом
      // (биения), третий уходит далеко вверх (шипение).
      R /= (1 + p.spread * (sb.razv[i] - 1));
      // палец на площадке подключает своё сопротивление параллельно цепи
      if (utechka > .001) R = 1 / (1/R + utechka / 2.6e6);
      const sosed = this.cells[(i + 1) % 3];
      const dVs = sosed.vyh - (sosed.prosh || 0);
      // Ветвь до базы: свой резистор сведения последовательно с фоторезистором
      // ключа. Тумблер сюда не включён — он держит лампочку, и всё, что
      // слышно при переключении, происходит вот в этом сопротивлении.
      const Gv = 1 / (sb.Rsum0 / sb.ves[i] + this.klyuch[i].step(vkl[i]));
      // Предел отвода считается по порогу ИМЕННО ЭТОГО элемента: точка покоя
      // разряда обязана остаться ниже него, иначе генератор запрётся. Пороги
      // у трёх элементов немного разные, и общее число на всех запирало те
      // сборки, где нижний порог оказался выше.
      const kmin = 1 / uzel.vt.vniz - 1 + .09;
      // ВХОД ОТ ПРЕДЫДУЩЕГО ПРИБОРА. Сигнал приходит не в микшер, а ТОКОМ
      // в конденсаторы: генератор бросает свой ход и захватывается — начинает
      // делить частоту входа на 2, 3, 5. Крутишь первый прибор — второй
      // перескакивает по делениям. Это и есть «один синт вошёл в другой».
      // ТОК: сигнал втекает в конденсатор через свой резистор — отсюда
      // захват и деление частоты.
      const Rvh = 0, Vvh = 0;
      Isum += uzel.step(R, Vdd * (1 + utechka * .1), R * Math.max(ki, kmin),
                        dVs, sosed.V, Rsv, Vdd, this.temp, Vvh, Rvh) * Gv;
      Gsum += Gv;
      tok += uzel.Ipit;
    }
    // МИКРОФОННЫЙ ВХОД — такая же ветвь суммирующего узла, как генератор:
    // свой резистор на ту же базу, и ручка ПЕТЛЯ этим резистором и работает.
    // Отсюда всё остальное следует само: петля не может перекричать прибор,
    // потому что нагружает с ним один узел и делит его; вой садится на
    // резонансы капсюля и корпуса, потому что идёт через них; а порог
    // самовозбуждения проходится плавно, потому что это проводимость, а не
    // ключ. Ко входу КАСКАДА её ставить было нельзя: прибор вгоняет каскад
    // в ограничение вчетверо, и там петлю просто съедает.
    const pl = clamp(p.petlya, 0, 1);
    if (pl > .002){
      const Gm = pl / (sb.Rsum0 * .8);
      Isum += (petl || 0) * Gm;
      Gsum += Gm;
    }
    for (const u of this.cells) u.prosh = u.vyh;
    // Генераторы больше не выключаются из расчёта: секция запитана всегда,
    // тумблер держит только лампочку своего ключа. Поэтому выключенный
    // генератор продолжает идти, тянуть свой ток из шины и толкать соседей
    // через ёмкость монтажа — и, вернувшись, приходит не с начала, а с той
    // фазы, до которой дошёл сам.
    let x = Isum / Gsum;

    // ТУМБЛЕР ГРЯЗИ снимает конденсатор развязки питания логики.
    this.bat.step(tok + (this.tokdin || 0), 1 - clamp(p.dirt, 0, 1));
    this.bat.sadis();

    // Разделительный конденсатор: перекошенный pulse несёт постоянную
    // составляющую, и без него диффузор просто уехал бы в упор.
    // Tab — это ДРУГОЙ прибор, а не включение питания: он стоит на столе и
    // уже работает, значит и разделительный конденсатор на нём давно заряжен,
    // а не пуст. (Проверено: бросок уровня при Tab, ×4.5, идёт НЕ отсюда —
    // после этой правки он остался прежним. Источник не найден, записан
    // в долги.)
    if (this.holodny){ this.Cvyh = x; this.holodny = 0; }
    const τv = sb.Cvyh * (sb.Rkat + sb.Rus) * 1400;
    this.Cvyh += (x - this.Cvyh) * (1 - Math.exp(-dt / τv));
    // Усиление каскада подобрано под ЭТУ суммирующую цепь: пассивный
    // смеситель с базовым резистором отдаёт на базу заметно меньше, чем
    // отдавало прежнее усреднение, и без пересчёта каскад перестал бы
    // перегружаться — а вместе с перегрузом ушёл бы весь верх.
    let U = (x - this.Cvyh) * 3.06 + navodka;
    // Каскад питается от той же батарейки и больше неё выдать не может.
    // Упирается он мягко, как настоящий транзистор, а не обрубается.
    const pred = Vdd * .5;
    U = pred * Math.tanh(U / pred);

    const a = this.din.step(U, utechka);
    // Ток катушки берётся из той же батарейки, что и логика. Десятки
    // миллиампер против микроампер генераторов — качает шину именно он.
    // Через плохую развязку эта пульсация возвращается в пороги триггеров,
    // и прибор начинает модулировать сам себя. Отсюда хрип и завод, которыми
    // славятся самоделки; тепловой шум резистора тут ни при чём.
    this.tokdin = Math.abs(this.din.I);

    // Нагрев: рассеиваемая мощность греет плату, номиналы плывут за ней.
    // За минуты игры прибор уходит по высоте — как всякая живая схема.
    this.moschn += (Vdd * tok - this.moschn) * .0002;
    this.temp += (this.moschn * 620 - this.temp) * 3e-6;

    // мера беспорядка: разброс интервалов между щелчками медленного узла
    this.ssch += dt;
    if (this.swing.medl.schelchok > 0){
      if (this.ssch > 1e-4 && this.ssch < 8){
        this.int[this.inti = (this.inti + 1) % this.int.length] = this.ssch;
        if (this.intN < this.int.length) this.intN++;
      }
      this.ssch = 0;
    }
    // Давление у микрофона пропорционально ускорению диффузора и его площади.
    // Долбёж не должен звучать тише: питание в паузах просажено, но на
    // ударах каскад работает с перегрузом — и общий уровень выравнивается.
    this.vyh = a * 6e-6 * (1 + p.gryzn * .75);
    return this.vyh;
  }

  mera(){
    if (this.intN > 4){
      let sum = 0;
      for (let i = 0; i < this.intN; i++) sum += this.int[i];
      const sr = sum / this.intN;
      let d = 0;
      for (let i = 0; i < this.intN; i++){ const t = this.int[i] - sr; d += t * t; }
      this.razbr = sr > 0 ? Math.sqrt(d / this.intN) / sr : 0;
      this.gc = sr > 0 ? 1 / sr : 0;
    }
  }

  bey(sila){ this.din.udar(sila); }

  zhivoy(){
    for (const g of [...this.cells, this.swing.medl, this.swing.gul])
      if (!(g.V === g.V)){ g.V = this.sb.EMF * .4; g.q = 1; g.sgl = 0; }
    if (!(this.bat.V === this.bat.V)) this.bat.V = this.sb.EMF;
    if (!(this.Cvyh === this.Cvyh)) this.Cvyh = 0;
    this.din.x = 0; this.din.v = 0; this.din.I = 0;
  }
}

// ---- КОНТАКТЫ --------------------------------------------------------------
// То, что происходит в момент, когда рука трогает прибор.
//
// Тумблер не переключается мгновенно: пружина хлопает, и контакты несколько
// раз размыкаются за первые миллисекунды. Питание на этот момент рвётся, и
// схема отзывается щелчком — не потому, что так задумано, а потому что иначе
// не бывает.
//
// У подстроечника движок скребёт по резистивному слою. Слой неоднороден,
// пятно контакта прыгает, и сопротивление скачет тем сильнее, чем быстрее
// крутишь. Это тот самый шорох, по которому ухо и опознаёт живую ручку.
class Contacts {
  constructor(){ this.dreb = 0; this.faza = 0; this.shoroh = 0; }
  schelkni(){ this.dreb = 1; this.faza = 0; }
  // множитель питания: во время дребезга оно рвётся
  step(){
    if (this.dreb > 0){
      this.faza += 1 / SR;
      const t = this.faza / .007;      // пружина успокаивается за семь миллисекунд
      if (t >= 1){ this.dreb = 0; return 1; }
      return Math.random() < (1 - t) * .35 ? .04 + Math.random() * .2 : 1;
    }
    return 1;
  }
  kruti(skorost){ this.shoroh = Math.min(1, this.shoroh + skorost * 26); }
  trenie(){
    this.shoroh *= .9992;
    return this.shoroh > .002 ? (Math.random() - .5) * this.shoroh : 0;
  }
}

// ---- ПРОЦЕССОР -------------------------------------------------------------
// ---- ГОЛОС -----------------------------------------------------------------
// Внешний сигнал — микрофон, петля, потом говорилка — входит в схему не
// микшером, а в конкретную ТОЧКУ ЦЕПИ. От выбора точки зависит всё:
//
//   0 НАКАЛ    выпрямленная огибающая ведёт лампочку оптопары. Прибор
//              говорит ритмом источника: слышны слоги, ударения, дыхание —
//              и ни одного слова. Связь высоты с речью 0.42.
//   1 ПИТАНИЕ  шина ходит вместе с сигналом: тон плывёт, громкость приседает
//              на громких местах. Связь высоты 0.78, громкости −0.75 — самая
//              сильная из всех.
//
// Пробовались ещё две точки, обе оказались мертвы при нынешних номиналах и
// потому убраны, а не оставлены для вида:
//   · ТОК в конденсатор — для захвата нужен резистор ПОРЯДКА цепи заряда, а
//     при таком он уже не втекает, а задаёт частоту сам, подменяя прибор.
//   · СМЕЩЕНИЕ — своё смещение уже стоит у предела запирания, и добавка
//     голоса либо не меняет ничего, либо глушит генератор совсем.
class Golos {
  constructor(){ this.dc = 0; this.ogib = 0; }
  step(vh, glub){
    if (!glub) { this.ogib = 0; return 0; }
    // Постоянку и рокот стола в схему не пускаем.
    this.dc += (vh - this.dc) * (22 * 2 * Math.PI / FS);
    this.syro = (vh - this.dc) * glub * 6;
    // Огибающая — выпрямитель и конденсатор, как в железе: быстрый заряд,
    // медленный разряд.
    const a = Math.abs(this.syro);
    if (a > this.ogib) this.ogib += (a - this.ogib) * (1 - Math.exp(-1 / (FS * .003)));
    else this.ogib += (0 - this.ogib) * (1 - Math.exp(-1 / (FS * .045)));
    return this.syro;
  }
}

// ---- ГОВОРИЛКА -------------------------------------------------------------
// Голосовой тракт целиком: связки, три резонанса полости рта, турбулентность
// в сужениях и излучение с губ. Та же схема, что в SAM на Apple II и в
// «Говорящей книге», — оттуда и жестяной тембр: тракт огрублён до трёх
// формант, и ухо слышит человека, но собранного из железа.
//
// Она ИСТОЧНИК, а не эффект: её выход воткнут в то же гнездо, что микрофон,
// и дальше идёт по схеме прибора наравне с ним. Разбор текста в фонемы и
// цели артикуляции живут в govor.js — здесь только физика, и про русский
// язык этот код не знает ничего.
class Rez {
  constructor(){ this.y1 = 0; this.y2 = 0; this.A = 1; this.B = 0; this.C = 0; }
  // Двухполюсный резонатор Клатта: полюс задаётся частотой и ПОЛОСОЙ, а не
  // добротностью — так их и меряют у живого тракта.
  nastroy(F, BW){
    const C = -Math.exp(-2 * Math.PI * BW / SR);
    const B = 2 * Math.exp(-Math.PI * BW / SR) * Math.cos(2 * Math.PI * F / SR);
    this.A = 1 - B - C; this.B = B; this.C = C;
  }
  step(x){
    const y = this.A * x + this.B * this.y1 + this.C * this.y2;
    this.y2 = this.y1; this.y1 = y;
    return y;
  }
}

const RECH_DT = 1 / SR;
// Через сколько тактов повторять фразу. Дроби нужны для коротких выкриков,
// целые — для фраз: так повтор ложится и в долю, и в такт.
// ТЕМП — не скорость произношения, а РАЗМЕР ПАУЗЫ между произнесениями, в
// тактах прибора. Пять жёстких ступеней и ничего между ними.
const TEMPY = [.25, .5, 1, 2, 3];
// Скорость самого произношения ручкой не задаётся: она привязана к качелям
// намертво. Ускорились качели — ускорилась и говорилка, слоги остаются на
// долях. Опора выведена из прежней свободной скорости: при такте 0.6 с речь
// идёт ровно с тем темпом, что была по умолчанию до привязки.
const OPORA = 1.55 * .6;
// Полюс спада турбулентности: девятьсот герц даёт −6 дБ/окт выше него, то
// есть ровно то, что прибавляет излучение с губ. Множитель возвращает
// потерянный на фильтре размах.
const SHUM_K = 1 - Math.exp(-2 * Math.PI * 900 / SR);
// Сила турбулентности относительно связок. Выведена замером: в живой речи
// шумные согласные ТИШЕ гласных, а не громче — здесь они выходят примерно
// вполовину, как и должно быть.
const SHUM_SILA = .15;
const TIHO = {tip:'pauza', F:[500,1500,2500], B:[140,180,240],
              gol:0, shum:0, ampl:0, smychka:0, dl:.2};

class Govorilka {
  constructor(){
    this.q = []; this.i = 0; this.t = 0; this.hvost = 0;
    this.F = [500,1500,2500]; this.B = [140,180,240];
    this.rez = [new Rez(), new Rez(), new Rez()];
    this.faza = 0; this.jit = 0; this.shim = 1;
    this.amp = 0; this.gol = 0; this.shum = 0; this.drozh = 0;
    this.yp = 0; this.tik = 0; this.shp = 0;
    this.zhdu = 0; this.zapas = null; this.dlit = 0;
  }
  govori(celi){
    this.q = celi || []; this.i = 0; this.t = 0; this.hvost = 0; this.zhdu = 0;
    this.zapas = this.q.length ? this.q : null;
    // Полная длительность фразы в «своём» времени — из неё считается, через
    // сколько тактов её повторять.
    this.dlit = this.q.reduce((a, b) => a + b.dl, 0);
  }
  molchi(){ this.q = []; this.i = 0; this.hvost = .08; this.zhdu = 0; this.zapas = null; }

  // trakt — ДЛИНА ГОЛОСОВОГО ТРАКТА, и ничто другое не отличает мужской голос
  //   от женского так надёжно. Форманты обратно пропорциональны длине: тракт
  //   короче — все три уезжают вверх разом. Высота связок при этом отдельный
  //   орган и живёт на своей ручке, поэтому низкий женский и высокий мужской
  //   голос тут возможны, как и в жизни.
  // temp — РАЗМЕР ПАУЗЫ между произнесениями, в тактах прибора. Такт берётся
  //   от качелей, поэтому повтор садится в ритм сам, а не плывёт рядом.
  step(ton, temp, povtor, trakt, period){
    // ПОВТОР, включённый после того, как фраза договорила, обязан её поднять:
    // очередь к тому моменту пуста, и без этого тумблер молчал бы до
    // следующего Enter. Фраза лежит в запасе с момента, как её сказали.
    if (povtor && !this.q.length && this.zhdu <= 0 && this.hvost <= 0 && this.zapas){
      this.q = this.zapas; this.i = 0; this.t = 0;
    }
    if (!this.q.length && this.hvost <= 0 && this.amp < 1e-5 && this.zhdu <= 0) return 0;
    const takt = Math.max(.05, period || .5);
    const skor = clamp(OPORA / takt, .15, 8);
    if (this.zhdu > 0){
      this.zhdu -= RECH_DT;
      if (this.zhdu <= 0 && this.zapas){ this.q = this.zapas; this.i = 0; this.t = 0; }
    }
    else if (this.q.length){
      this.t += RECH_DT * skor;
      while (this.q.length && this.t >= this.q[this.i].dl){
        this.t -= this.q[this.i].dl;
        this.i++;
        if (this.i >= this.q.length){
          if (povtor){
            // Пауза ДОБАВЛЯЕТСЯ к фразе, а не заменяет её длину: иначе для
            // фразы длиннее выбранного числа тактов ручка не делала бы
            // ничего. Сама фраза при этом округляется вверх до целого такта —
            // от этого повтор и садится на долю, какой бы длины ни была фраза.
            const svoya = this.dlit / skor;
            const kratno = TEMPY[clamp(Math.round(temp * (TEMPY.length - 1)),
                                       0, TEMPY.length - 1)];
            const cikl = (Math.ceil(svoya / takt) + kratno) * takt;
            const tishina = cikl - svoya;
            if (tishina > .01){
              this.zapas = this.q; this.q = []; this.i = 0;
              this.zhdu = tishina; this.hvost = .10;
            } else this.i = 0;
          }
          else { this.q = []; this.i = 0; this.hvost = .10; }
          break;
        }
      }
    } else this.hvost -= RECH_DT;
    const c = this.q.length ? this.q[this.i] : TIHO;
    // Множитель тракта: короче тракт — выше все форманты и шире их полосы.
    const dl = .86 * Math.pow(1.45, clamp(trakt, 0, 1));

    // Внутри фонемы. Взрывной согласный устроен так: тракт ПЕРЕКРЫТ (тишина,
    // у звонких за смычкой гудят связки), потом давление срывает преграду —
    // выброс шума, — и следом придыхание, пока связки не вернулись. Без этого
    // «т» и «с» звучали бы одинаково.
    let cel = c.ampl, shcel = c.shum, gcel = c.gol;
    if (c.smychka > 0){
      const d = this.t / c.dl;
      if (d < c.smychka){ cel = c.gol ? .07 : 0; shcel = 0; }
      else if (d < c.smychka + .16){ cel = c.ampl * 1.7; shcel = 1; gcel = 0; }
      else { cel = c.ampl * .55; shcel = c.gol ? .35 : .85; }
    }
    if (c.tip === 'drozh'){
      // «Р» — кончик языка бьёт по нёбу двадцать шесть раз в секунду. Это не
      // модуляция для красоты: перекрытие тракта то есть, то нет.
      this.drozh += RECH_DT * 26;
      const m = .5 + .5 * Math.cos(2 * Math.PI * this.drozh);
      cel *= .12 + .88 * m * m;
    }

    // Язык и губы имеют массу: форманты не прыгают, а ПЕРЕЕЗЖАЮТ. Без этого
    // речь рассыпается на отдельные писки — переходы её и склеивают, и
    // мягкость соседней согласной сама тянет за собой гласный, правил для
    // этого не нужно.
    const tau = (c.tip === 'vz' || c.tip === 'af') ? .012 : .028;
    const kf = 1 - Math.exp(-RECH_DT / tau);
    for (let j = 0; j < 3; j++){
      this.F[j] += (c.F[j] * dl - this.F[j]) * kf;
      this.B[j] += (c.B[j] * dl - this.B[j]) * kf;
    }
    // Связки открываются быстрее, чем закрываются, и тракт после них звенит.
    const ka = 1 - Math.exp(-RECH_DT / (cel > this.amp ? .004 : .012));
    this.amp += (cel - this.amp) * ka;
    const kg = 1 - Math.exp(-RECH_DT / .006);
    this.gol += (gcel - this.gol) * kg;
    this.shum += (shcel - this.shum) * kg;

    // ВЫСОТА. К концу фразы голос садится — это не украшение, а дыхание:
    // давление в лёгких падает, и связки идут медленнее.
    const f0baz = 62 * Math.pow(2, clamp(ton, 0, 1) * 2.4);
    const proydeno = this.q.length ? this.i / this.q.length : 1;
    const f0 = f0baz * (1 - proydeno * .17) * (1 + this.jit);
    this.faza += f0 * RECH_DT;
    if (this.faza >= 1){
      this.faza -= 1;
      // Связки не метроном: период и сила гуляют от цикла к циклу. Без этого
      // выходит пила из генератора, а не голос.
      this.jit = (Math.random() - .5) * .014;
      this.shim = 1 + (Math.random() - .5) * .07;
    }
    // Импульс Розенберга: поток открывается плавно, закрывается резко.
    const oq = .62, tp = oq * .68, ph = this.faza;
    const g = ph < tp ? .5 * (1 - Math.cos(Math.PI * ph / tp))
            : ph < oq ? Math.cos(Math.PI * (ph - tp) / (2 * (oq - tp)))
            : 0;
    // Турбулентность не белая. Воздух срывается в вихри у сужения, и спектр
    // этого срыва падает — примерно шесть децибел на октаву. Если этого не
    // учесть, излучение с губ (а оно даёт РОВНО ПЛЮС шесть на октаву) задерёт
    // шум тем сильнее, чем выше свистит фонема: замер дал «ф» вшестеро
    // громче гласного, «ш» в четырнадцать, «с» в пятьдесят шесть. Спад
    // источника гасит подъём излучения, и остаётся то, что задано таблицей.
    this.shp += (Math.random() * 2 - 1 - this.shp) * SHUM_K;
    const sh = this.shp * SHUM_SILA;
    // Турбулентность у звонких пульсирует вместе со связками: воздух идёт
    // толчками, шум идёт за ним.
    const shv = sh * (this.gol > .5 ? .5 + .5 * g : 1);
    const gv = this.gol * g * this.shim * this.amp;
    const nv = this.shum * shv * this.amp;

    // Резонаторы перестраиваются не каждый отсчёт: форманты едут за
    // десятки миллисекунд, а косинус с экспонентой стоят дороже самого хода.
    if ((this.tik++ & 15) === 0)
      for (let j = 0; j < 3; j++) this.rez[j].nastroy(this.F[j], this.B[j]);

    // Параллельный банк со знакочередованием — иначе соседние форманты
    // гасят друг друга в промежутке и спектр проваливается.
    const y = this.rez[0].step(gv * 1.0 + nv * .10)
            - this.rez[1].step(gv * .50 + nv * .90)
            + this.rez[2].step(gv * .22 + nv * .70);
    // Излучение с губ: наружу выходит не сам поток, а его ПРОИЗВОДНАЯ —
    // отсюда наклон спектра, из-за которого речь звучит речью.
    // Уровень выставлен замером по десятку фраз на всех высотах: худший пик
    // ложится около 0.6, то есть говорилка приходит на вход схемы с тем же
    // запасом, с каким туда приходит микрофон.
    const out = (y - this.yp) * 4.4;
    this.yp = y;
    return clamp(out, -1, 1);
  }
}

// ---- ПЕТЛЯ -----------------------------------------------------------------
// Микрофон слышит динамик — круг замыкает сама комната. Усиление в петле
// решает всё: до единицы это окраска (помещение подкрашивает звук), за
// единицей — самовозбуждение, и частота садится туда, где петля сильнее
// всего, то есть на резонанс капсюля с корпусом.
//
// Ограничитель стоит ДО усилителя и по природе тот же, что вся схема:
// каскад упирается в питание. Это не защита от ошибки — так ведёт себя
// реальный усилитель, и потому фидбек в железе не разносит колонки, а
// входит в устойчивое самовозбуждение.
class Petlya {
  constructor(){ this.dc = 0; }
  // Отдаёт НАПРЯЖЕНИЕ на вход каскада, а не готовый звук. Своего
  // ограничителя у неё больше нет и быть не должно: в комнате усилитель
  // один на всех, и петля упирается в то же питание, что и прибор. Прежде
  // она складывалась с выходом уже ПОСЛЕ прибора — то есть имела свой
  // усилитель и свой динамик параллельно приборному, и потому глушила его
  // втрое по пику и в восемь раз по средней громкости.
  // usil приходит снаружи и считается от ИЗМЕРЕННОГО возврата комнаты.
  // Числом его задать нельзя: замер передачи «вольт на входе → выход» дал
  // 0.038 на резонансе корпуса и 0.036 на резонансе капсюля, то есть для
  // единичной петли нужно около двадцати шести, — но это до комнаты. А
  // комната возвращает то ли сотую долю, то ли полторы, смотря где стоит
  // микрофон и как выкручена громкость, и любое число годилось бы ровно для
  // одной из них.
  step(vh, usil){
    if (!usil) return 0;
    // микрофон отдаёт и постоянку, и рокот стола — их в петлю пускать нельзя
    this.dc += (vh - this.dc) * (18 * 2 * Math.PI / FS);
    return (vh - this.dc) * usil;
  }
}

