      // промаха, `db → (цель − измеренное)`. Но измеренное само зависит от
      // db, и такая петля сходится ровно на ПОЛОВИНЕ нужного усиления —
      // замер показал недобор в семь децибел на всех сборках сразу.
      // Правильно — интегратор: пока промах не ноль, усиление продолжает
      // ехать, и останавливается только когда цель достигнута.
      // Работа ограничителя в промах НЕ входит. Пробовал — он тогда дерётся
      // с ручкой отпускания: медленное отпускание давит сильнее, петля видит
      // это как «слишком громко» и убавляет, и до цели дело не доходит вовсе
