// ---- ПОСТ ------------------------------------------------------------------
// Всё, что здесь, — заведомо программное и к прибору отношения не имеет.
//
// Автовыравнивание сборок отсюда УБРАНО. Замер показывал между ними 18 дБ, и
// я собрался их подтянуть — но разница эта аутентична: коробки правда разные,
// и подгонка под общую громкость убивает как раз то, чем они отличаются.
// Осталось мягкое колено — оно не выравнивает, а только не даёт цифре
// сломаться на самом верху.
class Zhmi {
  // ПАРАЛЛЕЛЬНЫЙ КОМПРЕССОР. Обычный на этом материале не работает, и это
  // измерено: разброс громкости внутри фразы всего полтора децибела — качели
  // модулируют высоту и тембр, а не уровень, и выравнивать нечего. При любых
  // постоянных времени он выравнивал ноль целых три десятых.
  //
  // Зато крест-фактор здесь 4.3: сигнал колючий, вся энергия в иглах треска.
  // Для такого работает другой приём — сжатую до плоского копию подмешивают
  // к сухой. Иглы остаются на месте, а всё, что между ними, поднимается.
  // Звук густеет, не теряя атаки. Ручка ведёт долю подмеса.
  constructor(){ this.og = 0; this.g = 1; this.effekt = 1; }
  step(y, sila){
    if (sila < .002){ this.effekt = 1; return y; }
    const a = y < 0 ? -y : y;
    // Атака полмиллисекунды: иглы надо ЗАСТАТЬ, иначе давить нечего.
    this.og += (a - this.og) * (a > this.og ? this.atk : this.otp);
    const nad = 20 * Math.log10(this.og + 1e-9) - TDB;
    // Отношение около десяти к одному: копия должна стать плоской, иначе
    // подмешивать нечего — выйдет просто громче.
    const cel = nad > 0 ? Math.pow(10, -nad * .9 / 20) : 1;
    this.g += (cel - this.g) * this.sgl;
    const mokro = y * this.g * DOBOR;
    this.effekt = 1 + sila * (this.g * DOBOR - 1);
    return y + (mokro - y) * sila;
  }
}
const TDB = -30;      // порог: копия давится почти всегда
const DOBOR = 12;     // добор сжатой копии до сопоставимого уровня
Zhmi.prototype.atk = 1 - Math.exp(-1 / (SR * .0005));
Zhmi.prototype.otp = 1 - Math.exp(-1 / (SR * .08));
Zhmi.prototype.sgl = 1 - Math.exp(-1 / (SR * .0008));

// ---- ГРОМКОСТЬ (ПОСТ) ------------------------------------------------------
// Петля громкости по BS.1770 — тому самому стандарту, по которому меряют
// вещание и по которому приводят звук все стриминги. Цель −14 LUFS: с ней
// запись не сдвинется при нормализации, потому что двигать будет нечего.
//
// Почему в реальном времени, а не над готовым файлом: на приборе играют и
// выступают. Звук должен быть готов СРАЗУ, в колонках, а не после обработки.
//
// Почему это НЕ то автовыравнивание, которое мы днём выкинули. То имело окно
// в полсекунды и успевало ходить ВНУТРИ фразы, приседая под каждым всплеском,
// — это компрессия под видом уровня, и динамику она правда ест. Здесь окно
// две секунды и движение за секунды: внутри фразы усиление стоит намертво,
// то есть на всю фразу приходится ОДИН множитель. Форма волны не меняется.
class Gromkost {
  constructor(){
    // K-взвешивание: полочный подъём верха и срез инфраниза. Считаются по
    // формулам, а не таблицей коэффициентов, — тогда они верны на любой
    // частоте дискретизации, а не только на сорока восьми килогерцах.
    this.sh = biquadShelf(1681.974450, 3.999843, .7071752);
    this.hp = biquadHP(38.135457, .5003271);
    this.z = new Float64Array(8);
    this.ms = 1e-4; this.msFast = 1e-4;
    this.lufs = -70; this.videl = 0;
    this.db = 0; this.g = 1;
    this.kMs = 1 / (SR * 2.0);       // окно измерения, две секунды
    this.kFast = 1 / (SR * .4);      // мгновенное окно, четыреста миллисекунд
    this.kBystro = 1 / (SR * .3);    // окно на время резкого скачка
  }
  merit(y){
    const z = this.z;
    const y1 = this.sh.b0*y + this.sh.b1*z[0] + this.sh.b2*z[1]
             - this.sh.a1*z[2] - this.sh.a2*z[3];
    z[1]=z[0]; z[0]=y; z[3]=z[2]; z[2]=y1;
    const y2 = this.hp.b0*y1 + this.hp.b1*z[4] + this.hp.b2*z[5]
             - this.hp.a1*z[6] - this.hp.a2*z[7];
    z[5]=z[4]; z[4]=y1; z[7]=z[6]; z[6]=y2;

    const kv = y2 * y2;
    this.msFast += (kv - this.msFast) * this.kFast;
    // ВОРОТА по стандарту: куски тише текущей громкости на десять децибел в
    // счёт не идут. Без них паузы разреженного материала тянут измерение
    // вниз, усиление задирается, и разные настройки расходятся по громкости
    // на десяток децибел.
    const mig = this.msFast > 1e-12 ? -.691 + 10 * Math.log10(this.msFast) : -99;
    if (mig > Math.max(-60, this.lufs - 10)){
      // Окно измерения обычно две секунды — от него и медленность. Но когда
      // мгновенная громкость резко разошлась с ней (Tab на другую сборку),
      // ждать две секунды незачем: окно на это время сужается до трёхсот
      // миллисекунд. Замер без этого показал тринадцать секунд выхода на
      // громкость после Tab — и упиралось оно в измерение, а не в движение.
      const skachok = (mig - this.lufs) > 6 || (this.lufs - mig) > 6;
      this.ms += (kv - this.ms) * (skachok ? this.kBystro : this.kMs);
      this.videl = 1;
    }
    if (this.videl && this.ms > 1e-9) this.lufs = -.691 + 10 * Math.log10(this.ms);
  }
}
