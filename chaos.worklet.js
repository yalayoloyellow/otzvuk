// То, что происходит в момент, когда рука трогает прибор.
//
// Тумблер не переключается мгновенно: пружина хлопает, и контакты несколько
// раз размыкаются за первые миллисекунды. Питание на этот момент рвётся, и
// схема отзывается щелчком — не потому, что так задумано, а потому что иначе
// не бывает.
//
// У подстроечника движок скребёт по резистивному слою. Слой неоднороден,
// пятно контакта прыгает, и сопротивление скачет тем сильнее, чем быстрее
// крутишь. Это тот самый шорох, по которому ухо и опознаёт живую ручку.
class Contacts {
  constructor(){ this.dreb = 0; this.faza = 0; this.dl = .007; this.shoroh = 0; }
  schelkni(){ this.dreb = 1; this.faza = 0; this.dl = .007; }
  // множитель питания: во время дребезга оно рвётся
  step(){
    if (this.dreb > 0){
      this.faza += 1 / SR;
      const t = this.faza / this.dl;
      if (t >= 1){ this.dreb = 0; return 1; }
      return Math.random() < (1 - t) * .35 ? .04 + Math.random() * .2 : 1;
    }
    return 1;
  }
  // Переходное сопротивление контакта В ОМАХ, а не в разах.
  //
  // В разах было ошибкой: внутреннее сопротивление кроны единицы ом, и даже
  // одиннадцать раз от него — крохи, замер дал всего минус два децибела.
  // Настоящий перекошенный контакт это СОТНИ ОМ: пятно уменьшилось, окисел
  // мешает, ток идёт через точку. Такое сопротивление уже сравнимо с тем, что
  // ставит ручка напряжения, и прибор от него правда захлёбывается.
  // Две тысячи двести ом на полном расшатывании — подобрано замером, и края
  // видны: при девятистах прибор почти не замечает (минус четыре децибела, 1%
  // провалов), при четырёх тысячах умирает насмерть (минус шестьдесят восемь,
  // 70% провалов). Нужно между: чтобы трещал и захлёбывался, но жил.
  // ПОСТОЯННОЙ ПРОСАДКИ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ ПО ЗАМЕРУ.
  //
  // Сперва расшатанный контакт держал сопротивление в две тысячи ом, плавно
  // спадавшее к нулю за шесть секунд. Прибор от этого проседал и качался — и
  // звучало это комично: медленное «уаа-уаа» сдувающегося шарика.
  //
  // Замер разложил след удара на две полосы и назвал виновного:
  //
  //     вариант                    качание 0.3–3Гц  треск 20–150Гц  отношение
  //     просадка 2200 Ом                1.93            0.91           0.47
  //     без просадки, обрывы чаще       1.35            1.51           1.12
  //
  // Качание делает ГЛАДКАЯ ПРОСАДКА, а не обрывы. Убрана целиком: остались
  // только короткие частые потери контакта. Ухо слышит их как электрический
  // треск, то есть как неисправность, — а не как больного зверя. Провал при
  // этом даже глубже: минус пять и восемь против минус пяти и семи.
  soprot(){ return 0; }
  kruti(skorost){ this.shoroh = Math.min(1, this.shoroh + skorost * 26); }
  trenie(){
    this.shoroh *= .9992;
    return this.shoroh > .002 ? (Math.random() - .5) * this.shoroh : 0;
  }
}

