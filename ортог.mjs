// Проверка ощутимости: для каждой ручки смотрим, ЧТО она меняет.
// Если все ручки двигают одно и то же — инструмент вырожден, сколько бы
// параметров в нём ни было. Именно это yala и услышал.
import {прогон} from './стенд_хаос.mjs';

const БАЗА={каскад:.4,куда:.5,вПорог:.35,назад:.15,съём:.4,расстройка:.35,связь:.45,накачка:.2,шум:.25,питание:.3,пульс:.4,делёж:.42,качели:.55,
  частота:.35,разброс:.5,струна:.45,натяг:.33,мягкость:.55,затух:.5,
  фильтр:.55,логика:.35,гистерезис:.5};

function черты(L,пр){
  const n=L.length;
  let пик=0,сум=0,нулей=0;
  for(let i=0;i<n;i++){const a=Math.abs(L[i]); if(a>пик)пик=a; сум+=L[i]*L[i];
    if(i&&(L[i]>0)!==(L[i-1]>0)) нулей++;}
  const rms=Math.sqrt(сум/n);
  // грубый центроид: доля высоких через разностный фильтр
  let вч=0,общ=0,lp=0;
  for(let i=0;i<n;i++){lp+=(L[i]-lp)*.08; вч+=(L[i]-lp)**2; общ+=L[i]*L[i];}
  // высота низа: считаем переходы через ноль в нижней полосе — иначе ручки,
  // меняющие ЧАСТОТУ баса, а не его уровень, выглядят бесполезными
  let lp2=0, нулиНиз=0, знак=false;
  for(let i=0;i<n;i++){ lp2+=(L[i]-lp2)*.01;
    const з=lp2>0; if(i&&з!==знак) нулиНиз++; знак=з; }
  return {ур:rms, ярк:общ>1e-9?вч/общ:0, нули:нулей/(n/48000), низГц:нулиНиз/2/(n/48000),
          низ:Math.abs(пр.А?.низУр||0)+Math.abs(пр.Б?.низУр||0),
          сер:Math.abs(пр.Б?.серУр||0), верх:Math.abs(пр.Б?.верхУр||0),
          разбр:(пр.А?.разбр||0)+(пр.Б?.разбр||0), гц:(пр.А?.гц||0)};
}

const {L:L0,пр:пр0}=прогон(БАЗА,4);
const б=черты(L0,пр0);
const ключи=['каскад','куда','вПорог','назад','съём','расстройка','связь','пульс',
  'делёж','качели','частота','разброс','накачка','струна','натяг','мягкость','затух',
  'фильтр','логика','гистерезис','питание','шум'];
const строки=[];
for(const k of ключи){
  const p={...БАЗА, [k]: БАЗА[k]>.5 ? БАЗА[k]-.35 : БАЗА[k]+.35};
  const {L,пр}=прогон(p,4);
  const ч=черты(L,пр);
  const отн=(a,b)=>Math.abs(a-b)/(Math.abs(b)+1e-6);
  строки.push({ручка:k,
    гром:+отн(ч.ур,б.ур).toFixed(2), ярк:+отн(ч.ярк,б.ярк).toFixed(2),
    низ:+отн(ч.низ,б.низ).toFixed(2), сер:+отн(ч.сер,б.сер).toFixed(2),
    верх:+отн(ч.верх,б.верх).toFixed(2), темп:+отн(ч.гц,б.гц).toFixed(2),
    низГц:+отн(ч.низГц,б.низГц).toFixed(2),
    беспор:+отн(ч.разбр,б.разбр).toFixed(2)});
}
console.log('ручка'.padEnd(14),'гром ярк  низ  сер  верх темп беспор  → что меняет');
for(const r of строки){
  const пары=[['громкость',r.гром],['яркость',r.ярк],['низ',r.низ],['середину',r.сер],
              ['верх',r.верх],['темп',r.темп],['беспорядок',r.беспор],['высоту низа',r.низГц]];
  пары.sort((a,b)=>b[1]-a[1]);
  const главное=пары.filter(x=>x[1]>.12).slice(0,2).map(x=>x[0]).join('+')||'НИЧЕГО';
  console.log(r.ручка.padEnd(14),
    String(r.гром).padEnd(5),String(r.ярк).padEnd(4),String(r.низ).padEnd(4),
    String(r.сер).padEnd(4),String(r.верх).padEnd(4),String(r.темп).padEnd(4),
    String(r.беспор).padEnd(6),'→',главное);
}
