#!/usr/bin/env python3
"""Значок прибора. Тот же язык, что у картины: россыпь точек люминофора,
собранная в горизонтальный овал два к одному.

Держим ГЕНЕРАТОРОМ, а не картинкой: иначе через полгода никто не скажет, из
чего значок сделан и как его поправить. Запускать при смене палитры:

    python3 znachok.py
"""
import os
import struct
import zlib

ФОН = (0x06, 0x08, 0x0a)
# Ступени зелёного из палитры панели: z1 z2 z3 z4.
СТУПЕНИ = [(0x5a, 0x80, 0x4d), (0x82, 0xb9, 0x6f),
           (0xa8, 0xf0, 0x90), (0xd8, 0xff, 0xc0)]
ОВАЛ = 2.0           # вдвое шире, чем выше


def клеток(размер):
    """Сколько знакомест по ширине. На мелких значках сетку приходится
    грубить: при двадцати двух клетках знакоместо на шестнадцати точках
    меньше пикселя, и от россыпи не остаётся ничего."""
    return 22 if размер >= 256 else 18 if размер >= 128 else \
           14 if размер >= 64 else 10 if размер >= 32 else 7


def ступень(gx, gy, КЛЕТОК):
    """Какой ступенью горит знакоместо — и горит ли вообще.

    Плотность падает от середины к краю овала, а рябь внутри берётся из
    самих координат: случайность здесь не нужна, нужен неповторяющийся узор.
    """
    cx = cy = (КЛЕТОК - 1) / 2
    dx = (gx - cx) / (КЛЕТОК / 2)
    dy = (gy - cy) / (КЛЕТОК / 2) * ОВАЛ
    r = (dx * dx + dy * dy) ** .5
    if r > 1:
        return None
    ш = ((gx * 7 + gy * 13) * (gx * 3 + 5) ^ (gy * 11)) % 97 / 97
    сила = (1 - r) * (.45 + .55 * ш)
    if сила < .12:
        return None
    return min(3, int(сила * 4.6))


def значок(размер):
    КЛЕТОК = клеток(размер)
    клетка = размер / КЛЕТОК
    пиксели = bytearray(ФОН * (размер * размер))
    for gy in range(КЛЕТОК):
        for gx in range(КЛЕТОК):
            ст = ступень(gx, gy, КЛЕТОК)
            if ст is None:
                continue
            цвет = СТУПЕНИ[ст]
            # Пятно растёт со ступенью: слабое — искра, сильное — заливка.
            # Полпикселя снизу: иначе слабые ступени на мелком значке
            # не рисуются вовсе и овал распадается.
            радиус = max(.55, клетка * (.13 + .09 * ст))
            ox, oy = (gx + .5) * клетка, (gy + .5) * клетка
            for y in range(max(0, int(oy - радиус)), min(размер, int(oy + радиус) + 1)):
                for x in range(max(0, int(ox - радиус)), min(размер, int(ox + радиус) + 1)):
                    if (x + .5 - ox) ** 2 + (y + .5 - oy) ** 2 <= радиус * радиус:
                        i = (y * размер + x) * 3
                        пиксели[i:i + 3] = bytes(цвет)
    return bytes(пиксели)


def png(путь, размер, пиксели):
    строки = b''.join(b'\x00' + пиксели[y * размер * 3:(y + 1) * размер * 3]
                      for y in range(размер))

    def кусок(имя, данные):
        тело = имя + данные
        return (struct.pack('>I', len(данные)) + тело
                + struct.pack('>I', zlib.crc32(тело) & 0xffffffff))

    with open(путь, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n'
                + кусок(b'IHDR', struct.pack('>IIBBBBB', размер, размер, 8, 2, 0, 0, 0))
                + кусок(b'IDAT', zlib.compress(строки, 9))
                + кусок(b'IEND', b''))


ICNS = 'otzvuk.app/Contents/Resources/otzvuk.icns'
НАБОР = [(16, 'icon_16x16'), (32, 'icon_16x16@2x'), (32, 'icon_32x32'),
         (64, 'icon_32x32@2x'), (128, 'icon_128x128'), (256, 'icon_128x128@2x'),
         (256, 'icon_256x256'), (512, 'icon_256x256@2x'),
         (512, 'icon_512x512'), (1024, 'icon_512x512@2x')]


def icns():
    import shutil
    import subprocess
    import tempfile
    if not shutil.which('iconutil'):
        print('iconutil не нашёлся — значок приложения не собран')
        return
    with tempfile.TemporaryDirectory() as врем:
        набор = os.path.join(врем, 'otzvuk.iconset')
        os.makedirs(набор)
        готовые = {}
        for размер, имя in НАБОР:
            if размер not in готовые:
                готовые[размер] = значок(размер)
            png(os.path.join(набор, имя + '.png'), размер, готовые[размер])
        os.makedirs(os.path.dirname(ICNS), exist_ok=True)
        subprocess.run(['iconutil', '-c', 'icns', набор, '-o', ICNS], check=True)
    print(ICNS)


if __name__ == '__main__':
    icns()
