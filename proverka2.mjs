const exp = Math.exp;

// Генератор с точным экспоненциальным шагом; переключение либо по границе
// сэмпла (как у меня сейчас), либо с субсэмпловым моментом.
function ген(RC, SR, N, суб){
  const out = new Float32Array(N);
  let v = .33, q = 1;
  const dt = 1/SR;
  for (let i = 0; i < N; i++){
    const цель = q ? 1 : 0, k = 1 - exp(-dt/RC);
    const было = v;
    v += (цель - v) * k;
    let вых = q ? 1 : -1;
    const порог = q ? 2/3 : 1/3;
    const пересёк = q ? (v > порог) : (v < порог);
    if (пересёк){
      if (суб){
        // доля шага до пересечения: аналитически
        const τ = -Math.log((порог - цель) / (было - цель)) * RC;
        const доля = Math.max(0, Math.min(1, τ / dt));
        вых = вых * (2*доля - 1) + (-вых) * (1 - доля) * 0;  // линейная ступенька
        вых = вых * доля + (-(q?1:-1)) * (1 - доля);
      }
      q = q ? 0 : 1;
    }
    out[i] = вых;
  }
  return out;
}

// грубый спектр через ДПФ на подвыборке
function спектр(x, SR, точек){
  const N = 4096, S = new Float32Array(точек);
  for (let k = 0; k < точек; k++){
    const f = (k+1) * SR/2 / точек;
    let re = 0, im = 0;
    for (let n = 0; n < N; n++){
      const w = .5 - .5*Math.cos(2*Math.PI*n/N);
      const a = 2*Math.PI*f*n/SR;
      re += x[n]*w*Math.cos(a); im += x[n]*w*Math.sin(a);
    }
    S[k] = Math.sqrt(re*re + im*im)/N;
  }
  return S;
}

