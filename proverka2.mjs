// два генератора, второй расстроен; считаем отношение числа переключений
function пара(тип, K, отн, SR=48000, сек=2){
  const RC1 = 1/(1.2*300), RC2 = RC1/отн;
  let v1=.4,q1=1,v2=.6,q2=0,c1=0,c2=0;
  const dt=1/SR;
  for (let i=0;i<SR*сек;i++){
    const ц1 = q1?1:0, ц2 = q2?1:0;
    let k1 = 1-exp(-dt/RC1), k2 = 1-exp(-dt/RC2);
    if (тип==='частотная'){                 // модуляция скорости заряда
      k1 = 1-exp(-dt/RC1*(1+K*(q2?1:-1)));
      k2 = 1-exp(-dt/RC2*(1+K*(q1?1:-1)));
      v1 += (ц1-v1)*k1; v2 += (ц2-v2)*k2;
    } else if (тип==='диффузионная'){        // притяжение к напряжению соседа
      v1 += (ц1-v1)*k1 + (v2-v1)*K*k1;
      v2 += (ц2-v2)*k2 + (v1-v2)*K*k2;
    } else {                                  // вынуждающая: выход соседа через резистор
      const вых2 = q2?1:0, вых1 = q1?1:0;
      v1 += (ц1-v1)*k1 + (вых2-v1)*K*k1;
      v2 += (ц2-v2)*k2 + (вых1-v2)*K*k2;
    }
    if (q1 && v1>2/3){q1=0;c1++;} else if(!q1 && v1<1/3) q1=1;
    if (q2 && v2>2/3){q2=0;c2++;} else if(!q2 && v2<1/3) q2=1;
  }
  return c2/(c1||1);
}
