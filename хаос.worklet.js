// ============================================================================
//  ХАОС — ядро инструмента.
//
//  Устройство списано с шумовых синтезаторов на КМОП-логике (40106): шесть
//  генераторов на триггерах Шмитта, связанных перекрёстно и сидящих на общей
//  просаженной шине питания. Характер там рождается не в генераторах, а в их
//  взаимном влиянии: каждый импульс сажает питание, от этого плывут все
//  остальные. Развязки нет НАМЕРЕННО — она бы убила всю живость.
//
//  Математически это сеть связанных нелинейных осцилляторов. Её поведение
//  описывает отображение окружности: сила связи ведёт от захвата в жёсткие
//  ритмические отношения (языки Арнольда) через квазипериодичность к хаосу,
//  а расстройка выбирает, какое именно отношение. Поэтому две ручки дают
//  осмысленную карту, а не лотерею.
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// Шкала, растянутая возле критической точки. Без неё край хаоса — щель
// шириной в пару процентов хода, и ручка работает как выключатель:
// только что был ровный ритм, и сразу каша, а интересное проскочило.
function растяни(x, крит) {
  const t = clamp(x, 0, 1) - крит;
  return крит + Math.sign(t) * Math.pow(Math.abs(t) / Math.max(крит, 1 - крит), 1.8)
         * Math.max(крит, 1 - крит);
}

class Узел {
  constructor(i) {
    this.i = i;
    this.v = Math.sin(i * 1.7) * .3;   // заряд конденсатора
    this.q = i & 1 ? 1 : -1;           // состояние триггера
    this.f = 40 * Math.pow(2, i * .7); // своя частота
    this.фаза = 0;
    this.вых = 0;
    this.сгл = 0;
  }
  // Триггер Шмитта на RC. Конденсатор заряжается к текущему состоянию, на
  // порогах состояние опрокидывается; гистерезис — то, что отличает живой
  // генератор от идеального компаратора.
  //
  // Асимметрия — это РАЗНЫЕ сопротивления заряда и разряда. В такой цепи
  // полупериоды неравны, и получается свинг: не нарисованный формулой, а
  // вытекающий из схемы, как у настоящей железки с диодом в цепи.
  шаг(ток, сдвигПорога, гист, асим) {
    const вверх = ток * (1 + асим) / SR;
    const вниз  = ток * (1 - асим) / SR;
    const скорость = this.q > 0 ? вверх : вниз;
    this.v += (this.q - this.v) * clamp(скорость, 0, .8);
    // Порог обязан лежать НИЖЕ напряжения, к которому идёт заряд, иначе он
    // недостижим и генератор залипает навсегда. В настоящем 40106 пороги —
    // доли питания (примерно треть и две трети), а не абсолютные величины.
    // Соседний генератор через резистор смещает точку срабатывания — так в
    // настоящей схеме и рождается чувствительность к мелочам: одинаковые с
    // точностью до микровольта состояния перещёлкиваются в разные моменты.
    // Пока связь влияла только на скорость заряда, система оставалась
    // устойчивой при любой её силе, и хаоса не возникало вовсе.
    const вх = clamp(.15 + gист_плюс(гист) * .7 + сдвигПорога, .06, .95);
    let перещёлк = 0;
    if (this.q > 0 && this.v > вх) { this.q = -1; перещёлк = 1; }
    else if (this.q < 0 && this.v < -вх) { this.q = 1; перещёлк = -1; }
    this.вых = this.q;
    this.сгл += (this.v - this.сгл) * .25;
    this.щелчок = перещёлк;          // фронт: им возбуждается резонатор
    return this.v;
  }
}
function gист_плюс(г) { return clamp(г, .05, .95); }

// ---- ЧЕСТНАЯ ФИЗИКА ------------------------------------------------------
// Здесь нет ни счётчика шагов, ни евклидова рисунка, ни огибающих по
// расписанию — всё это было бы часами извне, наложенными на живую систему.
// Ритм рождается ИЗ схемы: связанные релаксационные генераторы сами
// захватываются в целые отношения частот (языки Арнольда), медленные
// сажают питание и тем самым дают пульс, а свинг вытекает из асимметрии
// цепи заряда и разряда — как в настоящем триггере Шмитта.
class Хаос extends AudioWorkletProcessor {
  constructor() {
    super();
    this.N = 6;
    this.узлы = [];
    for (let i = 0; i < this.N; i++) this.узлы.push(new Узел(i));

    // Параметры — то, что крутится с клавиатуры. Все в 0…1, наружу
    // разворачиваются нелинейно, чтобы интересное занимало весь ход.
    this.p = {
      частота: .35,     // общая высота
      разброс: .5,      // расстройка узлов друг относительно друга
      связь: .3,        // сила кросс-модуляции: главная ручка хаоса
      питание: .25,     // насколько сильно узлы сажают общую шину
      гистерезис: .5,   // ширина петли триггера
      логика: .3,       // доля логического смешения против аналогового
      фильтр: .6,       // срез выходного фильтра
      резонанс: .2,
      обратная: .15,    // возврат выхода на вход сети
      грязь: .3,        // насыщение и перегруз
      // ---- медленная часть: пульс рождается захватом, а не счётчиком ----
      пульс: .4,        // частота медленных узлов, доли герца … единицы
      делёж: .35,       // расстройка медленных: во что они захватятся (2:1, 3:1…)
      качели: .5,       // асимметрия RC — физическая причина свинга
      просадка: .45,    // насколько медленные сажают питание быстрых = ворота
      // ---- резонатор вместо подмешанного баса ----
      струна: .3,       // сколько его в звуке
      натяг: .35,       // частота покоя
      мягкость: .45,    // нелинейность Дуффинга: высота едет с амплитудой
      затух: .5,        // добротность
      // ---- нелинейности тракта ----
      сворачивание: 0,  // диодный фолдер: спектр не режется, а складывается
      асимметрия: .5    // смещение перед насыщением: чётные гармоники, тепло
    };
    // медленные узлы: те же триггеры Шмитта, но на инфранизких частотах
    this.М = 3;
    this.медл = [];
    for (let i = 0; i < this.М; i++) this.медл.push(new Узел(i + 11));
    // резонатор Дуффинга: нелинейная пружина. Мягкая характеристика —
    // чем сильнее раскачана, тем ниже частота; при затухании высота сама
    // ползёт вверх. Это физическая причина того, что в 808 рисуют экспонентой.
    this.rx = 0; this.rv = 0;

    this.шина = 1;      // напряжение общей шины
    this.lp = 0; this.bp = 0;
    this.fb = 0;
    this.dcx = 0; this.dcy = 0;

    // Второй экземпляр сети с крошечным сдвигом: по расхождению копий
    // считается показатель Ляпунова — численная мера того, насколько
    // система сейчас хаотична. Это индикатор «где я на карте».
    this.тень = [];
    for (let i = 0; i < this.N; i++) { const u = new Узел(i); u.v += 1e-6; this.тень.push(u); }
    this.тень_шина = 1;
    this.ляп = 0; this.ляп_сгл = 0;
    this.разошлось = 1e-6;
    // Мера беспорядка по РАЗБРОСУ ИНТЕРВАЛОВ между щелчками. Показатель
    // Ляпунова по непрерывной траектории здесь врёт: у релаксационного
    // генератора между переключениями система всегда сжимается, и он
    // показывает порядок при любой связи. Вся суть — в моментах щелчков,
    // поэтому и мерить надо их: ровные интервалы — захват, разбросанные —
    // распад. Это ровно то, что слышно.
    this.инт = new Float32Array(48); this.интИ = 0; this.интN = 0;
    this.сЩелчка = 0; this.разбр = 0;

    // Число вращения: отношение частот двух первых узлов. Рациональное —
    // значит захват в ритмическую фигуру, иррациональное — плывёт.
    this.переходы = [0, 0];
    this.прошлое = [0, 0];
    this.окно = 0;
    this.вращение = 0;

    this.пик = 0; this.rms = 0;
    this.отчёт = 0;
    this.осц = new Float32Array(256);
    this.осцИ = 0;
    this.спектр = new Float32Array(24);
    this.гон = 0;

    this.port.onmessage = e => {
      const d = e.data;
      if (d.t === 'p') { for (const k in d.v) if (k in this.p) this.p[k] = clamp(d.v[k], 0, 1); }
      else if (d.t === 'толчок') {           // встряска: выбить из застоя
        for (const u of this.узлы) u.v += (Math.random() - .5) * .6;
      }
    };
  }

  сеть(узлы, шинаЗнач, p) {
    const базовая = 20 * Math.pow(2, p.частота * 9);          // 20 Гц … 10 кГц
    const связь = растяни(p.связь, .42) * 3.2;                 // критическая точка ≈ .42
    const гист = .1 + p.гистерезис * .8;
    let сумма = 0, ток_шины = 0;
    for (let i = 0; i < узлы.length; i++) {
      const u = узлы[i];
      const расстройка = Math.pow(2, (i - узлы.length / 2) * p.разброс * .9);
      // кросс-связь: соседи подмешиваются в ток заряда
      const a = узлы[(i + 1) % узлы.length].вых;
      const b = узлы[(i + узлы.length - 1) % узлы.length].сгл;
      const мод = 1 + связь * (a * .6 + b * .8) + this.fb * p.обратная * 2;
      const ток = базовая * расстройка * Math.max(.02, мод) * шинаЗнач;
      const сдвиг = связь * .22 * (b * .7 + this.fb * p.обратная);
      u.шаг(ток, сдвиг, гист, (p.качели - .5) * .85);
      ток_шины += Math.abs(u.q - u.v) * .5;
      сумма += u.сгл;
    }
    return { сумма, ток_шины };
  }

  process(inputs, outputs) {
    const oL = outputs[0][0], oR = outputs[0][1], n = oL.length;
    const p = this.p;
    // просадка питания: чем больше узлы дёргают ток, тем ниже напряжение,
    // и тем ниже частоты у всех разом — из этого рождается общая «дышащая»
    // нестабильность, которой нет у независимых осцилляторов
    const глубина = p.питание * .55;

    for (let s = 0; s < n; s++) {
      const r = this.сеть(this.узлы, this.шина, p);
      this.шина += ((1 - глубина * clamp(r.ток_шины / this.N, 0, 2)) - this.шина) * .002;

      const t = this.сеть(this.тень, this.тень_шина, p);
      this.тень_шина += ((1 - глубина * clamp(t.ток_шины / this.N, 0, 2)) - this.тень_шина) * .002;

      // логическое смешение: XOR прямоугольников даёт негармонические
      // разностные тона — то самое металлическое рычание КМОП-схем
      let лог = 0;
      for (let i = 0; i < this.N; i += 2) {
        const a = this.узлы[i].вых > 0, b = this.узлы[(i + 1) % this.N].вых > 0;
        лог += (a !== b) ? 1 : -1;
      }
      лог /= this.N / 2;

      let x = r.сумма / this.N * (1 - p.логика) + лог * p.логика * .7;

      // фильтр с резонансом: state-variable, срез и добротность на клавишах
      const fc = 30 * Math.pow(2, p.фильтр * 9);
      const k = clamp(2 * Math.sin(Math.PI * Math.min(fc, SR * .45) / SR), .001, 1.4);
      const q = 1.4 - p.резонанс * 1.35;
      this.lp += k * this.bp;
      const hp = x - this.lp - q * this.bp;
      this.bp += k * hp;
      x = this.lp;

      // ---- медленная часть: пульс из захвата ------------------------------
      // Те же релаксационные генераторы, только на долях герца. Связанные,
      // они САМИ захватываются в целые отношения — отсюда доли, тройки и
      // полиритмия. Никакого счётчика шагов: ритм есть следствие связи.
      const связьМедл = растяни(p.связь, .42) * 3.2;
      let медлТок = 0, пульсСумма = 0;
      for (let i = 0; i < this.М; i++) {
        const u = this.медл[i];
        const рас = Math.pow(2, i * (p.делёж * 2.2));
        const мод = 1 + связьМедл * .8 * this.узлы[i % this.N].сгл;
        const ток = (.25 + p.пульс * 11) * рас * Math.max(.05, мод);
        u.шаг(ток, связьМедл * .12 * this.узлы[(i + 2) % this.N].сгл,
              .35, (p.качели - .5) * .85);
        медлТок += Math.abs(u.q - u.v) * .5;
        пульсСумма += u.сгл;
      }
      // Ворота — это просадка питания медленными узлами, а не огибающая по
      // расписанию: они тянут ток, шина падает, быстрые узлы тускнеют.
      const пульс = clamp(.5 + пульсСумма / this.М * .8, 0, 1.6);
      const воротаФиз = 1 - p.просадка + p.просадка * пульс;
      x *= воротаФиз;

      // ---- резонатор Дуффинга вместо подмешанного баса --------------------
      // Нелинейная пружина: ẍ + δẋ + αx + βx³ = F. При мягкой характеристике
      // (β<0) частота падает с амплитудой, и при затухании высота сама ползёт
      // вверх — тот самый ход 808, только не нарисованный, а физический.
      if (p.струна > .01) {
        const w = 2 * Math.PI * (24 + p.натяг * 90) / SR;
        const α = w * w;
        // Мягкость не должна превышать единицу: при большей полная жёсткость
        // (α+β) на больших амплитудах уходит в минус, пружина выворачивается
        // и резонатор упирается в ограничитель. Потолок .9 оставляет запас,
        // и высота при раскачке падает примерно втрое — ровно ход 808.
        const β = -α * clamp(p.мягкость, 0, 1) * .9;
        // Демпфирование — доля от собственной частоты (2ζω), а не абсолютная
        // величина: сначала я домножил его на частоту дискретизации, и
        // резонатор разлетался в бесконечность за доли секунды.
        const δ = w * ((1 - p.затух) * .06 + .0015);
        // Возбуждают только МЕДЛЕННЫЕ узлы. Быстрые щёлкают на звуковых
        // частотах — от них это не удары, а непрерывная накачка, и резонатор
        // за секунду упирается в ограничитель и залипает там намертво.
        let удар = 0;
        for (const u of this.медл) if (u.щелчок) удар += u.щелчок;
        // Мягкая пружина (β<0) в чистом виде расходится: при большой
        // амплитуде возвращающая сила меняет знак и систему уносит. Делим
        // кубический член на (1+x²) — при малых отклонениях он тот же, при
        // больших выходит на насыщение, как у реальной струны.
        const x2 = this.rx * this.rx;
        const a = -α * this.rx - β * this.rx * x2 / (1 + x2) - δ * this.rv
                  // Масштаб удара: приращение скорости Δv даёт амплитуду
                  // Δv/w, поэтому множитель порядка w — иначе резонатор
                  // с первого же щелчка уходит в ограничитель и залипает.
                  + удар * w * .45;
        this.rv += a;
        this.rx += this.rv;
        if (this.rx > 4) { this.rx = 4; this.rv *= -.5; }
        else if (this.rx < -4) { this.rx = -4; this.rv *= -.5; }
        // не отдельный голос: он и модулирует сеть, и подмешан через общий тракт
        const рез = clamp(this.rx, -1.5, 1.5);
        x = x * (1 + рез * .3) + рез * p.струна * .55;
      }

      // Асимметрия перед насыщением рождает ЧЁТНЫЕ гармоники — то, что ухо
      // слышит как тепло. Симметричный tanh даёт только нечётные, жёсткие.
      const смещение = (p.асимметрия - .5) * .6;
      const drive = 1 + p.грязь * 14;
      x = Math.tanh((x + смещение) * drive) - Math.tanh(смещение * drive);
      x *= (1 - p.грязь * .35);
      // Сворачивание: в отличие от насыщения спектр не ограничивается,
      // а взрывается складками — это и есть рычащий рейдж-тембр.
      if (p.сворачивание > .01) {
        const св = 1 + p.сворачивание * 7;
        x = x * (1 - p.сворачивание) + Math.sin(x * св * 1.6) * p.сворачивание;
      }
      this.fb = x;

      this.dcy = x - this.dcx + .9995 * this.dcy; this.dcx = x;
      let y = clamp(this.dcy * .8, -1, 1);

      // интервалы между щелчками первого узла — основа меры беспорядка
      this.сЩелчка++;
      if (this.узлы[0].щелчок > 0) {
        if (this.сЩелчка > 4 && this.сЩелчка < SR) {
          this.инт[this.интИ = (this.интИ + 1) % this.инт.length] = this.сЩелчка;
          if (this.интN < this.инт.length) this.интN++;
        }
        this.сЩелчка = 0;
      }

      // расхождение копий → показатель Ляпунова
      let d2 = 0;
      for (let i = 0; i < this.N; i++) { const dv = this.узлы[i].v - this.тень[i].v; d2 += dv * dv; }
      const d = Math.sqrt(d2) + 1e-12;
      this.ляп += Math.log(d / this.разошлось);
      // перенормировка: тень возвращается близко, иначе она просто убегает
      const g = this.разошлось / d;
      for (let i = 0; i < this.N; i++)
        this.тень[i].v = this.узлы[i].v + (this.тень[i].v - this.узлы[i].v) * g;

      // число вращения: считаем переходы через ноль у двух узлов
      for (let i = 0; i < 2; i++) {
        const з = this.узлы[i].сгл > 0;
        if (з !== this.прошлое[i]) { this.переходы[i]++; this.прошлое[i] = з; }
      }
      if (++this.окно >= SR * .25) {
        this.вращение = this.переходы[1] > 0 ? this.переходы[0] / this.переходы[1] : 0;
        this.переходы[0] = this.переходы[1] = 0; this.окно = 0;
        this.ляп_сгл = this.ляп / (SR * .25);
        this.ляп = 0;
        // коэффициент вариации интервалов: 0 — идеально ровно, >.5 — распад
        if (this.интN > 6) {
          let сум = 0;
          for (let i = 0; i < this.интN; i++) сум += this.инт[i];
          const ср = сум / this.интN;
          let д = 0;
          for (let i = 0; i < this.интN; i++) { const q2 = this.инт[i] - ср; д += q2 * q2; }
          this.разбр = ср > 1 ? Math.sqrt(д / this.интN) / ср : 0;
        }
      }

      // Страж: хаотическая система может улететь в бесконечность от одной
      // неудачной комбинации ручек. Без этого один NaN отравляет всё
      // навсегда — звук пропадает до перезагрузки страницы.
      if (!(y === y) || y === Infinity || y === -Infinity) {
        y = 0;
        this.rx = 0; this.rv = 0; this.lp = 0; this.bp = 0; this.fb = 0;
        this.шина = 1; this.тень_шина = 1;
        for (let i = 0; i < this.N; i++) {
          if (!(this.узлы[i].v === this.узлы[i].v)) { this.узлы[i].v = 0; this.узлы[i].q = 1; }
          if (!(this.тень[i].v === this.тень[i].v)) { this.тень[i].v = 0; this.тень[i].q = 1; }
        }
        for (const u of this.медл) if (!(u.v === u.v)) { u.v = 0; u.q = 1; }
        this.срывы = (this.срывы || 0) + 1;
      }
      const a = y < 0 ? -y : y;
      if (a > this.пик) this.пик = a;
      this.rms += (y * y - this.rms) * .0005;

      // лёгкое расхождение каналов: моно из такой сети звучит плоско
      const yR = this.dcy * .8 * .93 + this.узлы[this.N - 1].сгл * .07;
      oL[s] = y;
      oR[s] = (yR === yR) ? clamp(yR, -1, 1) : 0;

      this.осц[this.осцИ = (this.осцИ + 1) & 255] = y;
    }

    // отчёт наверх — для индикаторов и рисунка
    this.отчёт += n;
    if (this.отчёт >= SR / 30) {
      this.отчёт = 0;
      this.port.postMessage({
        пик: this.пик, rms: Math.sqrt(this.rms),
        ляп: this.ляп_сгл, разброс: this.разбр, вращение: this.вращение,
        шина: this.шина,
        осц: this.осц.slice(),
        узлы: this.узлы.map(u => u.сгл),
        медл: this.медл.map(u => u.сгл), струна: this.rx, срывы: this.срывы || 0
      });
      this.пик *= .6;
    }
    return true;
  }
}
