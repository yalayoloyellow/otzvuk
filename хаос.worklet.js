// ============================================================================
//  ХАОС — ядро инструмента.
//
//  Устройство списано с шумовых синтезаторов на КМОП-логике (40106): шесть
//  генераторов на триггерах Шмитта, связанных перекрёстно и сидящих на общей
//  просаженной шине питания. Характер там рождается не в генераторах, а в их
//  взаимном влиянии: каждый импульс сажает питание, от этого плывут все
//  остальные. Развязки нет НАМЕРЕННО — она бы убила всю живость.
//
//  Математически это сеть связанных нелинейных осцилляторов. Её поведение
//  описывает отображение окружности: сила связи ведёт от захвата в жёсткие
//  ритмические отношения (языки Арнольда) через квазипериодичность к хаосу,
//  а расстройка выбирает, какое именно отношение. Поэтому две ручки дают
//  осмысленную карту, а не лотерею.
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// Шкала, растянутая возле критической точки. Без неё край хаоса — щель
// шириной в пару процентов хода, и ручка работает как выключатель:
// только что был ровный ритм, и сразу каша, а интересное проскочило.
function растяни(x, крит) {
  const t = clamp(x, 0, 1) - крит;
  return крит + Math.sign(t) * Math.pow(Math.abs(t) / Math.max(крит, 1 - крит), 1.8)
         * Math.max(крит, 1 - крит);
}

// ---- УЗЕЛ: релаксационный генератор ----------------------------------------
// Всё, что здесь есть, проверено счётом (см. РАЗБОР.md, раздел ПРОВЕРКА):
//
//  · Постоянная времени берётся как 1/(ln4·f), а НЕ 1/(1.2·f). Константа 1.2
//    из даташита относится к реальным порогам конкретного чипа, а у нас
//    идеальные ⅓ и ⅔, для которых период равен RC·ln4. Прежняя константа
//    занижала частоту ровно на 13.4% — измерено −13.5…−14.0%.
//
//  · Момент пересечения порога считается ВНУТРИ шага аналитически. Без этого
//    период всегда целое число отсчётов, и частота липнет к сетке SR/n:
//    заданные 9000 Гц звучали как 6000, ошибка до трети.
//
//  · Защитные диоды ограничивают напряжение на АБСОЛЮТНЫЕ 0.6 В за шины.
//    Это единственная величина в схеме, не пропорциональная питанию, и
//    именно она делает частоту зависимой от просадки: без неё питание
//    сокращается во всех формулах и не слышно вовсе (проверено — ровный ноль).
class Узел {
  constructor(i, семя){
    this.i = i;
    const r = Math.sin(семя * 12.9898 + i * 78.233) * 43758.5453;
    this.разброс = 1 + ((r - Math.floor(r)) - .5) * .06;   // допуск деталей ±3%
    this.v = .3 + (i * .137) % .4;
    this.q = i & 1 ? 1 : 0;          // однополярная логика, как в железе
    this.вых = 0;
    this.сгл = 0;
    this.щелчок = 0;
  }
  // Vdd — текущее напряжение шины: оно живое и проседает под нагрузкой.
  // ток — 1/RC в герцах; сосед и связь — диффузионная связь через резистор.
  // разрешение — второй вход элемента 2И-НЕ. Когда он в нуле, выход залипает
  // в единице и генерация ОСТАНАВЛИВАЕТСЯ. Это и есть механизм ритма в таких
  // схемах: медленный генератор гейтит быстрый, получается тон-пауза-тон.
  // Плавные связи такого дать не могут — они меняют характер, но не режут.
  шаг(частота, Vdd, сосед, связь, гист, асим, шум, разрешение){
    if (разрешение !== undefined && разрешение < .5){
      // элемент заперт: конденсатор подтягивается к шине, выход стоит
      this.v += (Vdd - this.v) * .002;
      this.вых = Vdd; this.щелчок = 0; this.заперт = 1;
      this.сгл += ((this.v - Vdd * .5) - this.сгл) * .25;
      this.ток = .02;
      return this.сгл;
    }
    this.заперт = 0;
    const порогВерх = Vdd * (.5 + гист * .28);
    const порогНиз  = Vdd * (.5 - гист * .28);
    const цель = this.q ? Vdd : 0;
    const RC = 1 / (Math.log(4) * Math.max(1, частота) * this.разброс);
    const dt = 1 / SR;
    // асимметрия цепей заряда и разряда — физическая причина свинга
    const τ = RC / (this.q ? (1 + асим) : (1 - асим));
    const было = this.v;
    this.v += (цель - this.v) * (1 - Math.exp(-dt / τ));
    if (связь > 0) this.v += (сосед - this.v) * связь * (dt / τ);

    // диоды: абсолютные 0.6 В за шины, не доля питания
    if (this.v < -.6) this.v = -.6;
    else if (this.v > Vdd + .6) this.v = Vdd + .6;

    // СБРОС ФАЗЫ. Если сосед дёрнул сильно, узел перезапускает свой цикл не
    // дожидаясь порога — волна врезается в волну. В схеме это происходит,
    // когда чужой импульс через конденсатор перебрасывает вход разом за оба
    // порога. Тот самый эффект «одна волна вторгается в другую».
    if (связь > 0 && сосед !== undefined){
      const рывок = (сосед - this.v) * связь;
      if (Math.abs(рывок) > Vdd * .55){
        this.v = рывок > 0 ? Vdd * .1 : Vdd * .9;
        this.q = рывок > 0 ? 1 : 0;
        this.сброс = 1;
      } else this.сброс = 0;
    }

    this.щелчок = 0;
    // Тепловой шум сэмплируется триггером в момент решения. Он сдвигает
    // порог тем сильнее, чем ПОЛОЖЕ кривая заряда в этой точке: возле
    // асимптоты небольшая помеха переносит момент переключения далеко.
    // Отсюда физический факт — медленные генераторы дрожат заметнее быстрых.
    let порог = this.q ? порогВерх : порогНиз;
    if (шум > .001){
      // Наклон в знаменателе — но с ограничением: у самой асимптоты он почти
      // ноль, и без предела сдвиг улетал за пороги, а генераторы глохли
      // (проверено: громкость падала впятеро).
      const наклон = Math.max(.12, Math.abs(цель - this.v));
      const сдвиг = (Math.random() - .5) * шум * .05 / наклон * Vdd;
      порог += clamp(сдвиг, -Vdd * .14, Vdd * .14);
    }
    const пересёк = this.q ? (this.v > порог) : (this.v < порог);
    if (пересёк){
      // доля шага до настоящего пересечения — из точного решения экспоненты
      const d0 = было - цель, d1 = порог - цель;
      let доля = (d0 !== 0 && d1 / d0 > 0) ? -Math.log(d1 / d0) * τ / dt : .5;
      доля = доля < 0 ? 0 : доля > 1 ? 1 : доля;
      this.q ^= 1;
      this.щелчок = this.q ? 1 : -1;
      this.доля = доля;
      // выход усредняется по шагу: ступенька встаёт в правильную точку,
      // а не на границу отсчёта — это и снимает квантование частоты
      this.вых = Vdd * ((this.q ? 1 : 0) * (1 - доля) + (this.q ? 0 : 1) * доля);
    } else {
      this.вых = this.q ? Vdd : 0;
    }
    // ток потребления: заряд конденсатора плюс бросок при переключении
    this.ток = Math.abs(цель - this.v) / (τ * SR) + (this.щелчок ? .35 : 0);
    this.сгл += ((this.v - Vdd * .5) - this.сгл) * .25;
    return this.сгл;
  }
}

// ---- РИТМ-СЕКЦИЯ ----------------------------------------------------------
// То, без чего ритма в таких приборах не бывает и чего у меня не было.
//
// ДЕЛИТЕЛИ. Триггер делит частоту пополам; каскад даёт ÷2, ÷4, ÷8, ÷16.
// В советских схемах это К561ИЕ. Комбинируя выходы логикой, получаешь
// ритмический рисунок — не «характер волны», а именно рисунок.
//
// РЕГИСТР СДВИГА С ОБРАТНОЙ СВЯЗЬЮ. Классика самодельных синтезаторов:
// биты сдвигаются, обратная связь через сумму по модулю два. Даёт длинную
// непериодическую на слух последовательность — рваный несимметричный рисунок.
class Ритм {
  constructor(){
    this.дел = new Uint8Array(6);        // состояния делителей
    this.рег = 0x2ACE1 & 0xfffff;        // регистр сдвига, 20 бит
    this.прошлый = 0;
    this.выход = 0; this.бит = 0;
    this.сх = 0;                          // выборка-хранение
  }
  // тик приходит с фронта медленного генератора
  тик(){
    for (let i = 0; i < this.дел.length; i++){
      this.дел[i] ^= 1;                   // каждый делит предыдущий пополам
      if (this.дел[i]) break;             // перенос только при переходе в единицу
    }
    // сумма по модулю два двух отводов — максимальная длина последовательности
    const б = ((this.рег >> 19) ^ (this.рег >> 16)) & 1;
    this.рег = ((this.рег << 1) | б) & 0xfffff;
    this.бит = б;
    return true;
  }
  // рисунок: какие делители участвуют и как складываются
  узор(глубина, вид, шум){
    const д = this.дел;
    let r;
    if (вид < .33){                        // ровные доли: один делитель
      const k = Math.min(5, Math.floor(глубина * 5.99));
      r = д[k];
    } else if (вид < .66){                 // логическая комбинация — синкопы
      const a = д[1], b = д[2], c = д[3];
      r = ((a ^ b) & 1) | (глубина > .5 ? (c & 1) : 0);
    } else {                                // регистр сдвига — рваный рисунок
      r = this.бит;
    }
    return r ? 1 : (шум > .5 ? 1 : 0);
  }
}

// ---- ПРИБОР: одна законченная схема ---------------------------------------
// Раньше голоса складывались параллельно и почти не влияли друг на друга —
// отсюда «слишком управляемо, не похоже на каскад из двух приборов». У Срапы
// второй прибор не подмешивается к первому, а СИДИТ У НЕГО НА ВЫХОДЕ: сигнал
// первого лезет второму в питание, в цепи заряда и в пороги. Тогда низкое
// качает среднее, и ритмический рисунок рождается вместе с тембром.
class Прибор {
  constructor(семя, узлов){
    this.N = узлов;
    this.узлы = [];
    for (let i = 0; i < узлов; i++) this.узлы.push(new Узел(i, семя));
    this.М = 2;
    this.медл = [];
    for (let i = 0; i < this.М; i++) this.медл.push(new Узел(i + 11, семя + 7));
    this.Vdd = 1; this.ток = 0;
    this.rx = 0; this.rv = 0;
    this.lp = 0; this.bp = 0; this.вLp = 0; this.свПрош = 0;
    this.вых = 0; this.пульс = 0;
    this.сЩелчка = 0; this.инт = new Float32Array(48); this.интИ = 0; this.интN = 0;
    this.разбр = 0; this.гц = 0;
    this.ритм = new Ритм();
    this.сх = 0;                      // выборка-хранение: ступенчатая модуляция
    this.кольцо = 0; this.кПраг = 0; this.кольцоС = 0;  // кольцевой генератор
  }

  // вх — то, что пришло от предыдущего прибора в цепи; точки подключения
  // разные и слышны по-разному, это и есть «переставить педали».
  шаг(p, вх, гл){
    // ИНЖЕКЦИЯ. Чужой сигнал идёт током ПРЯМО В КОНДЕНСАТОРЫ, а не правит
    // параметры. Разница принципиальная: параметрическая модуляция меняет
    // характер, а инжекция вызывает ЗАХВАТ — генератор бросает свой ход и
    // начинает делить частоту входа на 2, 3, 5. Проверено: при силе 0.25
    // своя 90 Гц садится на ÷5, 140 на ÷3, 210 на ÷2, выше — на ÷1.
    // Крутишь частоту — перебираешь деления, то есть выбираешь частоту
    // искажения. На границах захвата генератор мечется между делениями, и
    // это медленное биение слышно как раскачка.
    const инж       = вх * гл.инжекция;
    const вПитание  = вх * гл.питание;
    const вЗаряд    = вх * гл.заряд;
    const вПорог    = вх * гл.порог;

    // питание: чужой сигнал буквально сажает или поднимает шину
    const жёсткость = .0004 + (1 - p.питание) * .01;
    const цельШины = 1 - clamp(this.ток * 60, 0, 1) * p.питание * .85 - вПитание * .7;
    this.Vdd += (цельШины - this.Vdd) * жёсткость;
    if (this.Vdd < .15) this.Vdd = .15;
    let токСум = 0;

    // медленные: пульс
    const свМедл = растяни(p.связь, .42) * .9;
    for (let i = 0; i < this.М; i++){
      const u = this.медл[i];
      const f = (.15 + p.пульс * 7) * Math.pow(2, i * p.делёж * 2.4) * (1 + вЗаряд * 2);
      u.шаг(Math.max(.02, f), this.Vdd, this.медл[(i+1)%this.М].v + вПорог,
            свМедл, .5, (p.качели - .5) * .8, p.шум);
      токСум += u.ток;
    }
    this.пульс = this.медл[0].сгл;
    // фронт медленного гонит делители и регистр сдвига
    if (this.медл[0].щелчок > 0){
      this.ритм.тик();
      // выборка-хранение: держим значение второго медленного до следующего
      // фронта — модуляция становится ступенчатой, а не текучей
      this.сх = this.медл[1].сгл / Math.max(.2, this.Vdd);
    }
    const узор = this.ритм.узор(p.рисунок, p.видРисунка, 0);

    // низ: резонатор от ударов пульса
    let низ = 0;
    if (p.струна > .003){
      const w = 2*Math.PI*(26 + p.натяг*78)*(1 + вЗаряд*.8)/SR;
      const α = w*w, β = -α*clamp(p.мягкость,0,1)*.9;
      const δ = w*((1-p.затух)*.05 + .0012);
      let удар = 0;
      for (const u of this.медл) if (u.щелчок > 0) удар += 1;
      const x2 = this.rx*this.rx;
      this.rv += -α*this.rx - β*this.rx*x2/(1+x2) - δ*this.rv + удар*w*.5;
      this.rx += this.rv;
      if (this.rx > 3){ this.rx = 3; this.rv *= -.4; }
      else if (this.rx < -3){ this.rx = -3; this.rv *= -.4; }
      низ = Math.tanh(this.rx*1.6) * p.струна * 1.15;
    }

    // середина: связанная пара — здесь живёт хаос
    // Выборка-хранение: значение схвачено на фронте и держится до следующего.
    // Высота едет ступенями, а не плавно — характерная черта таких приборов,
    // где медленный генератор через ключ заряжает конденсатор и тот держит.
    const ступень = 1 + this.сх * p.холд * 1.6;
    const базовая = 30 * Math.pow(2, p.частота*7.5) * (1 + вЗаряд*3) * ступень;
    const св = растяни(p.связь, .42) * 1.6;
    const гист = .25 + p.гистерезис*.6;
    // ГЕЙТ: медленный генератор запирает середину. Глубина гейта — сколько
    // раз из скольких он вообще срабатывает; при нуле схема играет сплошняком,
    // при единице пауза ровно на полпериода пульса.
    // Порог открытия ведёт ручка: при нуле элемент открыт всегда (сплошняк),
    // при большом значении открывается лишь на вершине медленной волны —
    // короткие вспышки с паузами, то есть отчётливый ритм.
    // Гейт теперь ведёт РИСУНОК с делителей, а не просто уровень медленной
    // волны: отсюда доли, синкопы и рваные фигуры вместо ровного дыхания.
    const гейт1 = p.рисунок < .02
      ? ((this.медл[0].v / this.Vdd) > p.гейт * .92 ? 1 : 0)
      : (узор ? 1 : (p.гейт < .3 ? 1 : 0));
    let серед = 0;
    for (let i = 0; i < 2; i++){
      const u = this.узлы[i], сосед = this.узлы[1-i];
      const f = Math.max(2, базовая * (i ? Math.pow(2, p.разброс*1.6) : 1));
      серед += u.шаг(f, this.Vdd, сосед.v + вПорог + инж * 2.2, св + Math.abs(гл.инжекция) * .8,
                     гист, (p.качели-.5)*.5, p.шум, гейт1);
      токСум += u.ток;
    }
    // Ни tanh-«грязи», ни sin-«сворачивания» здесь больше нет: это была
    // математика поверх схемы, а не сама схема. Искажение теперь рождается
    // тем же способом, что в железе — сигнал упирается в шины питания.
    // Чем сильнее просажена батарейка, тем раньше он в них упрётся.
    серед *= 1.8 * (1 + p.накачка * 7);
    const предел = this.Vdd * .9;
    if (серед > предел) серед = предел + (серед - предел) * .04;
    else if (серед < -предел) серед = -предел + (серед + предел) * .04;

    // верх: логическое смешение
    let верх = 0;
    if (p.логика > .01 && this.N > 4){
      for (let i = 2; i < this.N; i++){
        const u = this.узлы[i];
        const f = Math.max(2, базовая * Math.pow(2, 1.4 + (i-2)*(.35 + p.разброс*.8)));
        // верх гейтится ВТОРЫМ медленным — рисунок получается сложнее, чем
        // у одного гейта: два независимых периода накладываются
        // верх идёт по ДРУГОМУ отводу делителя — два рисунка накладываются
        const гейт2 = p.рисунок < .02
          ? ((this.медл[1].v / this.Vdd) > p.гейт2 * .92 ? 1 : 0)
          : (this.ритм.дел[Math.min(5, 1 + Math.floor(p.гейт2 * 4))] ? 1 : 0);
        u.шаг(f, this.Vdd, this.узлы[(i+1)%this.N].v + вПорог + инж * 1.6,
              св*.5 + Math.abs(гл.инжекция) * .6, гист, 0, p.шум, гейт2);
        токСум += u.ток;
      }
      const пол = u => u.вых > this.Vdd*.5;
      const a = пол(this.узлы[2]), b = пол(this.узлы[3]), c = пол(this.узлы[4]);
      верх = (((a !== b) !== c) ? 1 : -1) * p.логика * .45;
      this.вLp += (верх - this.вLp)*.3;
      верх -= this.вLp;
    }
    this.ток += (токСум/(this.N + this.М) - this.ток)*.01;

    // Точка съёма: в приборе выход берут с конкретного места — с конденсатора
    // генератора, с выхода логики, с резонатора. Это не микшер, а провод,
    // припаянный туда или сюда, и звучит по-разному.
    const т = p.съём;
    let x;
    if (т < .33){
      const d = т/.33;
      x = this.узлы[0].сгл*2.2*(1-d) + серед*d;    // прямо с конденсатора
    } else if (т < .66){
      const d = (т-.33)/.33;
      x = серед*(1-d) + (серед*.5 + верх)*d;        // середина плюс логика
    } else {
      const d = (т-.66)/.34;
      x = (серед*.5 + верх)*(1-d) + (низ*2.2 + серед*.4)*d;   // с резонатора
    }
    x *= .45 + .55*clamp(this.Vdd, 0, 1);

    // Фильтр разносило на максимуме среза: у этой схемы предел устойчивости
    // k < 2 − q, а я разрешал k до 1.4 при q около 1.17 — за пределом она
    // взрывается, выдаёт громкий выброс и глохнет. Теперь предел соблюдён,
    // и добавлено мягкое ограничение внутри петли: даже при перегрузке
    // фильтр насыщается, а не улетает.
    // На выходе прибора — обычная RC-цепочка, как в железе (конденсатор на
    // излучатель). Резонансного фильтра с добротностью там нет и не было:
    // прежний цифровой SVF ещё и разносило на максимуме среза.
    this.сырой = x;                       // до фильтра — для перемычки обхода
    const a = 1 - Math.exp(-2*Math.PI*(40*Math.pow(2, p.фильтр*8.5))/SR);
    this.lp += (x - this.lp) * clamp(a, .0005, .9);
    x = this.lp;

    // мера беспорядка по интервалам щелчков пульса
    this.сЩелчка++;
    if (this.медл[0].щелчок !== 0){
      if (this.сЩелчка > 4 && this.сЩелчка < SR*4){
        this.инт[this.интИ = (this.интИ+1)%this.инт.length] = this.сЩелчка;
        if (this.интN < this.инт.length) this.интN++;
      }
      this.сЩелчка = 0;
    }
    this.низУр = низ; this.серУр = серед; this.верхУр = верх;
    this.вых = x;
    return x;
  }

  мера(){
    if (this.интN > 4){
      let сум = 0;
      for (let i = 0; i < this.интN; i++) сум += this.инт[i];
      const ср = сум/this.интN;
      let д = 0;
      for (let i = 0; i < this.интN; i++){ const t = this.инт[i]-ср; д += t*t; }
      this.разбр = ср > 1 ? Math.sqrt(д/this.интN)/ср : 0;
      this.гц = SR/ср;
    }
  }

  сброс(){
    this.rx = 0; this.rv = 0; this.lp = 0; this.bp = 0;
    this.Vdd = 1; this.ток = 0; this.вых = 0;
    for (const u of this.узлы) if (!(u.v === u.v)){ u.v = .3; u.q = 1; }
    for (const u of this.медл) if (!(u.v === u.v)){ u.v = .3; u.q = 1; }
  }
}

class Хаос extends AudioWorkletProcessor {
  constructor(){
    super();
    // ДВА ПРИБОРА В ЦЕПИ. Первый — «ведущий», обычно медленный и грязный;
    // второй сидит у него на выходе. Между ними три точки подключения, и
    // они звучат совершенно по-разному — это и есть «переставить педали».
    this.А = new Прибор(1, 6);
    this.Б = new Прибор(31, 6);

    this.p = {
      частота:.35, разброс:.5, связь:.3, питание:.25, гистерезис:.5,
      логика:.3, фильтр:.6, накачка:.2, шум:.25,
      гейт:.6,          // глубина запирания
      гейт2:.4,         // рисунок для верха
      рисунок:.4,       // какой отвод делителей ведёт ритм
      видРисунка:.3,    // доли / синкопы / рваный регистр сдвига
      холд:.3,          // выборка-хранение: ступенчатая модуляция
      кольцо:0,         // кольцевой генератор: высокий писк поверх
      батарея:.15,      // за сколько садится: медленный дрейф питания
      пульс:.4, делёж:.35, качели:.5,
      струна:.3, натяг:.35, мягкость:.45, затух:.5,
      // ---- каскад ----
      каскад:.35,       // общая глубина связи А→Б
      куда:.5,          // характер связи: 0 — всё в питание, 1 — всё в заряд
      вПорог:.35,       // в пороги (самое чувствительное — там рождается хаос)
      назад:.15,        // обратная связь Б→А: цепь замыкается в кольцо
      съём:.4,          // откуда снят провод: конденсатор, логика, резонатор
      вес:.6,           // чей голос громче в общей нагрузке
      нагрузка:.35,     // насколько жёстко приборы встречаются на общем выходе
      расстройка:.35    // насколько второй прибор отличается по частотам
    };

    // ПЛОЩАДКИ. Не пресеты и не переключатели: каждая замыкает свой участок
    // схемы через живое сопротивление. Прохождения тока через тело в цифре
    // не будет, поэтому переосмысляем — палец шунтирует цепь, и схема
    // отзывается искажением, а не аккуратной прибавкой.
    this.пл = new Float32Array(9);
    this.батТик = 0; this.батЗаряд = 1; this.общТок = 0; this.наводка = 0;
    this.дс = 0; this.дх = 0; this.дy = 0;
    this.пик = 0; this.отчёт = 0;
    this.осц = new Float32Array(256); this.осцИ = 0;
    this.срывы = 0; this.окно = 0;

    this.port.onmessage = e => {
      const d = e.data;
      if (d.t === 'p'){ for (const k in d.v) if (k in this.p) this.p[k] = clamp(d.v[k], 0, 1); }
      else if (d.t === 'площадки'){ for (let i = 0; i < 9; i++) this.пл[i] = d.v[i] || 0; }
      else if (d.t === 'толчок'){
        for (const u of this.А.узлы) u.v += (Math.random()-.5)*.5;
        for (const u of this.Б.узлы) u.v += (Math.random()-.5)*.5;
      }
    };
  }

  process(inputs, outputs){
    const oL = outputs[0][0], oR = outputs[0][1], n = oL.length;
    const p = this.p;

    // Второй прибор — не копия: у реальных двух коробок разные номиналы.
    const pБ = Object.assign({}, p, {
      частота: clamp(p.частота + (p.расстройка - .5) * .5, 0, 1),
      пульс:   clamp(p.пульс   + (p.расстройка - .5) * .4, 0, 1),
      разброс: clamp(p.разброс + (p.расстройка - .5) * .3, 0, 1)
    });
    const гл = {
      инжекция: p.каскад * .5,          // главный путь: ток в конденсаторы
      питание:  p.каскад * (1 - p.куда) * .5,
      заряд:    p.каскад * p.куда * .35,
      порог:    p.каскад * p.вПорог * .3
    };
    const глНазад = { инжекция: p.назад * .3, питание: p.назад * .35,
                      заряд: p.назад * .2, порог: p.назад * .18 };

    // ---- ПЛОЩАДКИ ---------------------------------------------------------
    // Палец не замыкает цепь накоротко — он подключает СОПРОТИВЛЕНИЕ в сотни
    // килоом, и эффект зависит от того, как прижал: больше площадь контакта —
    // меньше сопротивление — сильнее уход. Все площадки делают ОДНОРОДНУЮ
    // вещь, как на приборе: подключают свой номинал к частотозадающей цепи.
    // Поэтому касание предсказуемо: знаешь, куда поедет тон.
    //   1 2 3 — параллельно резистору: ток заряда растёт, тон ВВЕРХ
    //           (слабый, средний, сильный номиналы)
    //   4 5   — добавляют ёмкость: заряд медленнее, тон ВНИЗ
    //   6 7   — между генераторами: они стягиваются друг к другу
    //   8     — на выходе: сажает сигнал и подмешивает наводку от руки
    const пл = this.пл;
    const пВверх = пл[1]*.35 + пл[2]*.9 + пл[3]*2.2;
    const пВниз  = пл[4]*.3 + пл[5]*.62;
    const пСтяг  = пл[6]*.5 + пл[7]*1.3;
    const пВыход = пл[8];
    // уход в полутонах, а не в долях параметра: диапазон частоты семь октав,
    // и одинаковая добавка на низах и верхах ощущалась бы совсем по-разному
    const сдвигЧ = Math.log2((1 + пВверх) / (1 + пВниз)) / 7.5;
    const тронуто = пВверх + пВниз + пСтяг > .005;
    const pА = тронуто ? Object.assign({}, p, {
          частота: clamp(p.частота + сдвигЧ, 0, 1),
          разброс: p.разброс * (1 - clamp(пСтяг, 0, .95)),
          делёж:   p.делёж   * (1 - clamp(пСтяг * .7, 0, .9))
        }) : p;
    const pБ2 = тронуто ? Object.assign({}, pБ, {
          частота: clamp(pБ.частота + сдвигЧ * .55, 0, 1),   // до Б палец дальше
          разброс: pБ.разброс * (1 - clamp(пСтяг * .7, 0, .9)),
          делёж:   pБ.делёж   * (1 - clamp(пСтяг * .5, 0, .9))
        }) : pБ;

    // Батарея садится: медленный дрейф за минуты, с провалами под нагрузкой.
    this.батТик += n;
    if (p.батарея > .01 && this.батТик > SR * .5){
      this.батТик = 0;
      this.батЗаряд = Math.max(.45, this.батЗаряд - p.батарея * .0009);
    } else if (p.батарея <= .01) this.батЗаряд = 1;
    const бат = this.батЗаряд;

    for (let s = 0; s < n; s++){
      const а = this.А.шаг(pА, this.Б.вых * глНазад.питание, глНазад);
      let б = this.Б.шаг(pБ2, а, гл);

      // 8: рука на выходе — сажает сигнал и подмешивает наводку, как ладонь
      // на неэкранированном проводе
      if (пВыход > .01){
        this.наводка = this.наводка * .9994 + (Math.random() - .5) * пВыход * .004;
        б = б * (1 - пВыход * .55) + this.наводка;
      }

      // ОБЩАЯ НАГРУЗКА. Оба прибора сидят на одном транзисторе и одном
      // излучателе, без развязки: складываются ДО предела, и нелинейность
      // рождает суммы и РАЗНОСТИ частот — разность двух средних тонов падает
      // в бас, которого в самих генераторах нет.
      //
      // Предел РАЗНЫЙ сверху и снизу, как у однотактного каскада. Это не
      // мелочь: симметричное ограничение даёт только нечётные продукты, и
      // разностный тон в них подавлен (проверено — −85 дБ, неслышим).
      // С асимметрией он поднимается до −18 дБ.
      const общ = (а * (1 - p.вес) + б * p.вес) * (1 + p.нагрузка * 5);
      const лимВ = 1 - p.нагрузка * .58, лимН = 1 - p.нагрузка * .22;
      let x = общ > лимВ ? лимВ + (общ - лимВ) * .05
            : общ < -лимН ? -лимН + (общ + лимН) * .12 : общ;

      // ток общей нагрузки сажает питание ОБОИХ приборов: они мешают друг
      // другу, как на одной батарейке
      this.общТок += (Math.abs(x) - this.общТок) * .002;
      const провал = 1 - this.общТок * p.нагрузка * .6;
      this.А.Vdd = Math.min(this.А.Vdd, бат * провал);
      this.Б.Vdd = Math.min(this.Б.Vdd, бат * провал);

      this.дy = x - this.дх + .9995 * this.дy; this.дх = x;
      let y = clamp(this.дy * .5, -1, 1);
      if (!(y === y)){
        y = 0; this.А.сброс(); this.Б.сброс();
        this.дх = 0; this.дy = 0; this.общТок = 0; this.срывы++;
      }

      if (++this.окно >= SR * .25){ this.окно = 0; this.А.мера(); this.Б.мера(); }

      const a2 = y < 0 ? -y : y;
      if (a2 > this.пик) this.пик = a2;
      oL[s] = y;
      const yR = this.дy * .5 * .93 + this.Б.узлы[1].сгл * .07;
      oR[s] = (yR === yR) ? clamp(yR, -1, 1) : 0;
      this.осц[this.осцИ = (this.осцИ + 1) & 255] = y;
    }

    this.отчёт += n;
    if (this.отчёт >= SR/30){
      this.отчёт = 0;
      this.port.postMessage({
        пик: this.пик, разброс: this.А.разбр, разбросБ: this.Б.разбр,
        гц: this.А.гц || 0, гцБ: this.Б.гц || 0,
        шина: this.А.Vdd, шинаБ: this.Б.Vdd, срывы: this.срывы,
        батарея: this.батЗаряд, узор: Array.from(this.А.ритм.дел),
        осц: this.осц.slice(),
        низ: Math.abs(this.А.низУр || 0) + Math.abs(this.Б.низУр || 0),
        серед: Math.abs(this.Б.серУр || 0), верх: Math.abs(this.Б.верхУр || 0),
        медл: [this.А.пульс, this.Б.пульс], струна: this.Б.rx,
        пл: Array.from(this.пл)
      });
      this.пик *= .6;
    }
    return true;
  }
}
registerProcessor('хаос', Хаос);
