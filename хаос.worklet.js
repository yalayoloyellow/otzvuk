// ============================================================================
//  ХАОС — ядро инструмента.
//
//  Собран вокруг КАЧЕЛЕЙ. Это два релаксационных генератора на разных
//  временных шкалах: один в звуке, второй медленный, и медленный ведёт
//  ТОКОМ заряд звукового. Звуковой от этого ездит по четырём-шести октавам:
//  внизу проваливается в 25–45 Гц, где прямоугольник слышен отдельными
//  импульсами, наверху уходит за килогерц. Ухо читает это как ритмический
//  рисунок — «трррр-виииии-трррр-виииии», — а не как модуляцию.
//
//  Тот же управляющий ток перекашивает скважность: внизу импульс узкий и
//  грязный, наверху ровный. Высота и грязь связаны ОДНОЙ величиной, потому
//  что в железе это один резистор, и разделить их нельзя.
//
//  Три первые ручки — это сам прибор. Три вторые — добавки из той же схемы:
//  второй генератор на подгармонике, ещё более медленный генератор поверх
//  первого, и просадка питания под током импульсов.
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// Пороги реального триггера — 0.32 и 0.68 от питания, а не идеальные ⅓ и ⅔.
// Период тогда равен RC·ln(0.68/0.32) = 1.508·RC.
const ПЕР = 1.508;

// ---- ГЕНЕРАТОР -------------------------------------------------------------
// Один элемент с триггером Шмитта и RC в обратной связи. Всё, что он умеет:
// заряжаться к питанию, разряжаться к нулю и переключаться на порогах.
class Генератор {
  constructor(сдвиг, допуск){
    this.v = .32 + сдвиг * .3;
    this.q = 1;
    this.вых = -1;
    this.доп = допуск;              // разброс номиналов этого экземпляра
    this.тзар = 0; this.тразр = 0;
    this.f = 0; this.скв = .5; this.щелчок = 0; this.ток = 0;
  }
  // f  — частота при нулевом управляющем токе
  // см — управляющий ток, в долях питания. Он подгоняет заряд и одновременно
  //      тормозит разряд; если подтянет точку покоя выше нижнего порога,
  //      генератор запрётся, потому и ограничен здесь же.
  // Vdd — живое питание: оно проседает под током импульсов.
  шаг(f, см, Vdd){
    const порогВ = Vdd * .68, порогН = Vdd * .32;
    const смО = clamp(см, 0, .30) * Vdd;
    const цель = (this.q ? Vdd : 0) + смО;
    const RC = 1 / (ПЕР * Math.max(.02, f) * this.доп);
    const прошл = this.v;
    this.v += (цель - this.v) * (1 - Math.exp(-1 / (SR * RC)));
    // Защитные диоды ограничивают напряжение на АБСОЛЮТНЫЕ 0.6 В за шины.
    // Это единственная величина в схеме, не пропорциональная питанию, и
    // только благодаря ей просадка вообще слышна: без диодов Vdd сокращается
    // во всех формулах и на частоту не влияет (проверено — ровный ноль).
    if (this.v < -.6) this.v = -.6;
    else if (this.v > Vdd + .6) this.v = Vdd + .6;

    let вых = this.q ? 1 : -1;
    this.щелчок = 0;
    if (this.q ? this.v > порогВ : this.v < порогН){
      // Момент пересечения считается ВНУТРИ шага. Без этого период всегда
      // целое число отсчётов, частота липнет к сетке SR/n, и наверху качелей
      // вместо визга получается ступенчатый мусор.
      const порог = this.q ? порогВ : порогН;
      const зн = this.v - прошл;
      const доля = зн !== 0 ? clamp((порог - прошл) / зн, 0, 1) : .5;
      const стар = вых;
      this.q ^= 1;
      вых = стар * доля + (this.q ? 1 : -1) * (1 - доля);
      this.щелчок = this.q ? 1 : -1;
      if (this.q){
        const T = this.тзар + this.тразр;
        if (T > 1){ this.f = SR / T; this.скв = this.тзар / T; }
        this.тзар = 0; this.тразр = 0;
      }
    }
    if (this.q) this.тзар++; else this.тразр++;
    this.вых = вых;
    this.ток = Math.abs(цель - this.v) / (RC * SR) + (this.щелчок ? .35 : 0);
    return вых;
  }
  // напряжение на конденсаторе, приведённое к 0…1 — управляющая величина
  упр(Vdd){ return clamp((this.v / Math.max(.15, Vdd) - .32) / .36, 0, 1); }
}

// ---- ПРИБОР ----------------------------------------------------------------
class Прибор {
  constructor(семя){
    const r = k => { const x = Math.sin(семя * 12.9898 + k * 78.233) * 43758.5453;
                     return x - Math.floor(x); };
    // Номиналы деталей этого экземпляра. Для исполнителя они выглядят
    // случайностью, хотя физически детерминированы: случайность здесь — это
    // ровно то, к чему нет доступа, но что звучит.
    this.медл = new Генератор(r(3), 1 + (r(4) - .5) * .10);
    this.гул  = new Генератор(r(5), 1 + (r(6) - .5) * .14);
    this.осн  = new Генератор(r(1), 1 + (r(2) - .5) * .05);
    this.вт   = new Генератор(r(7), 1 + (r(8) - .5) * .05);
    this.Vdd = 1; this.ток = 0;
    this.вч = 0; this.лп = 0; this.вых = 0;
    this.u = .5; this.g = .5;
    this.инт = new Float32Array(32); this.интИ = 0; this.интN = 0; this.сЩ = 0;
    this.разбр = 0; this.гц = 0;
  }

  шаг(p, пл){
    // ---- КАЧАНИЕ ---------------------------------------------------------
    // Ручка задаёт ПЕРИОД рисунка, поэтому шкала идёт вниз: слева десятки
    // герц — качание такое частое, что слышится тембром, а не рисунком;
    // справа доли герца — прибор дышит одним движением на несколько секунд.
    let Fк = 60 * Math.pow(2, -p.пульс * 7.7);

    // ---- ГУЛЯНИЕ ---------------------------------------------------------
    // Ещё один генератор, вдесятеро медленнее первого, качает ЕГО период.
    // Рисунок остаётся рисунком, но перестаёт повторяться в точности: то
    // растягивается, то поджимается. Это и есть управляемый хаос — не шум,
    // а уход самого ритма.
    if (p.гуляние > .002){
      this.гул.шаг(Math.max(.02, Fк * .09), 0, 1);
      this.g = this.гул.упр(1);
      Fк *= Math.pow(2, (this.g - .5) * p.гуляние * 3.4);
    } else this.g = .5;

    this.медл.шаг(Math.max(.03, Fк), 0, 1);
    this.u = this.медл.упр(1);

    // ---- КАЧЕЛИ ----------------------------------------------------------
    // Нижняя точка держится в области треска на всём ходу ХАРАКТЕРА — иначе
    // рисунок пропадает и остаётся вой. Верхняя уходит тем выше, чем правее
    // ручка. Качели раскрываются ОТ ЦЕНТРА, поэтому нулевой размах — это
    // ровный тон средней высоты, а не гул на самом низу.
    // Палец на площадке подключает сопротивление к частотозадающей цепи:
    // ток заряда растёт, но всего на проценты — тон остаётся на месте, а
    // фактура меняется. Заметно это прежде всего по перекосу импульса.
    const утечка = пл ? пл.утечка : 0;
    const хар = clamp(p.частота + утечка * .06, 0, 1);
    const низК  = 24  * Math.pow(2, хар * 1.2);
    const верхК = 300 * Math.pow(2, хар * 4.0);
    const центр = Math.sqrt(низК * верхК);
    const рзм = clamp(p.размах, 0, 1);
    const пол = центр * Math.pow(низК / центр, рзм);
    const пот = центр * Math.pow(верхК / центр, рзм);
    const f1 = пол * Math.pow(пот / пол, this.u);
    // Управляющий ток велик там, где качели внизу: он же и утаскивает их
    // туда, тормозя разряд. Одна величина — и высота, и перекос импульса.
    let см1 = (.12 + хар * .19) * рзм * (1 - this.u);
    // та же утечка подтягивает точку покоя — импульс перекашивается сильнее,
    // и звук грязнеет, не меняя высоты
    см1 = clamp(см1 + утечка * .05, 0, .30);

    let сумТок = 0;
    const a = this.осн.шаг(f1 * (1 + утечка * .12), см1, this.Vdd);
    сумТок += this.осн.ток;

    // ---- ВТОРОЙ ----------------------------------------------------------
    // Второй генератор сидит на ПОДГАРМОНИКЕ первого: ÷1 слева, ÷5 справа.
    // Он качается теми же качелями, но своим током, поэтому расходится с
    // первым по фазе — одна волна входит в другую. Их встреча на общей
    // нагрузке даёт разностный тон, которого нет ни в одном из них.
    let b = 0;
    if (p.второй > .004){
      const дел = 1 + p.второй * 4;
      b = this.вт.шаг(f1 * (1 + утечка * .07) / дел, см1 * .8, this.Vdd);
      сумТок += this.вт.ток;
    }

    // ---- ПРОСАДКА --------------------------------------------------------
    // Импульсы жрут ток, батарейка не идеальная, шина садится. Пороги
    // триггера едут вместе с ней, а диоды остаются на своих абсолютных
    // 0.6 В — отсюда уход частоты и качание громкости под собственным
    // ритмом прибора. Развязки нет намеренно: она убила бы всю живость.
    this.ток += (сумТок / 2 - this.ток) * .01;
    // Чем дряхлее батарейка, тем выше её внутреннее сопротивление и тем
    // ЖИВЕЕ шина ходит за током. Скорость была записана наоборот — на
    // максимуме ручки шина почти стояла, и просадки не было слышно вовсе.
    const цельШины = 1 - clamp(this.ток * 60, 0, 1) * p.просад * .9;
    this.Vdd += (цельШины - this.Vdd) * (.0015 + p.просад * .05);
    if (this.Vdd < .2) this.Vdd = .2;

    // ---- ОБЩАЯ НАГРУЗКА --------------------------------------------------
    // Оба генератора сидят на одном транзисторе и одном излучателе, без
    // развязки. Предел РАЗНЫЙ сверху и снизу, как у однотактного каскада:
    // симметричное ограничение даёт только нечётные продукты, и разностный
    // тон в них подавлен на −85 дБ, то есть неслышим. С асимметрией он
    // поднимается до −18 дБ — вот откуда бас, которого нет в генераторах.
    // Перегруза «на всякий случай» здесь нет: он слышался сатурацией поверх
    // прибора, а не самим прибором. Ограничение только то, что даёт
    // однотактный каскад, и оно фиксированное.
    let x = (a + b * clamp(p.второй * 1.6, 0, 1)) * 1.15;
    const лимВ = .82, лимН = .95;
    x = x > лимВ ? лимВ + (x - лимВ) * .05
      : x < -лимН ? -лимН + (x + лимН) * .12 : x;
    x *= .45 + .55 * clamp(this.Vdd, 0, 1);

    // Выходной конденсатор на излучатель. Перекошенный импульс несёт большую
    // постоянную составляющую; без него качели катали бы всю дорожку
    // вверх-вниз вместо того, чтобы звучать.
    this.вч += (x - this.вч) * (12 * 2 * Math.PI / SR);
    x -= this.вч;
    // и обычная RC-цепочка следом. Резонансного фильтра в таких приборах
    // нет и не было.
    const α = 1 - Math.exp(-2 * Math.PI * (60 * Math.pow(2, p.фильтр * 7.5)) / SR);
    this.лп += (x - this.лп) * clamp(α, .0005, .95);
    x = this.лп * .55;

    // мера беспорядка: разброс интервалов между щелчками медленного узла
    this.сЩ++;
    if (this.медл.щелчок > 0){
      if (this.сЩ > 4 && this.сЩ < SR * 8){
        this.инт[this.интИ = (this.интИ + 1) % this.инт.length] = this.сЩ;
        if (this.интN < this.инт.length) this.интN++;
      }
      this.сЩ = 0;
    }
    this.вых = x;
    return x;
  }

  мера(){
    if (this.интN > 4){
      let сум = 0;
      for (let i = 0; i < this.интN; i++) сум += this.инт[i];
      const ср = сум / this.интN;
      let д = 0;
      for (let i = 0; i < this.интN; i++){ const t = this.инт[i] - ср; д += t * t; }
      this.разбр = ср > 1 ? Math.sqrt(д / this.интN) / ср : 0;
      this.гц = SR / ср;
    }
  }

  сброс(){
    this.Vdd = 1; this.ток = 0; this.вч = 0; this.лп = 0; this.вых = 0;
    for (const г of [this.медл, this.гул, this.осн, this.вт])
      if (!(г.v === г.v)){ г.v = .4; г.q = 1; }
  }
}

class Хаос extends AudioWorkletProcessor {
  constructor(){
    super();
    this.пр = new Прибор(1);
    this.p = {
      пульс:.45,      // КАЧАНИЕ  — период рисунка
      частота:.5,     // ХАРАКТЕР — высота верхней точки и перекос импульса
      размах:.75,     // РАЗМАХ   — глубина качелей, ноль даёт ровный тон
      второй:0,       // ВТОРОЙ   — генератор на подгармонике
      гуляние:0,      // ГУЛЯНИЕ  — период качелей сам гуляет
      просад:.12,     // ПРОСАДКА — шина садится под током импульсов
      фильтр:.75,     // RC на выходе
      батарея:.15     // за сколько садится батарейка
    };
    this.пл = new Float32Array(9);
    this.батТик = 0; this.батЗаряд = 1; this.наводка = 0;
    this.пик = 0; this.отчёт = 0; this.окно = 0; this.срывы = 0;
    this.осц = new Float32Array(256); this.осцИ = 0;
    this.след = new Float32Array(200); this.слИ = 0; this.проре = 0;

    this.port.onmessage = e => {
      const d = e.data;
      if (d.t === 'p'){ for (const k in d.v) if (k in this.p) this.p[k] = clamp(d.v[k], 0, 1); }
      else if (d.t === 'площадки'){ for (let i = 0; i < 9; i++) this.пл[i] = d.v[i] || 0; }
      else if (d.t === 'толчок'){
        this.пр.осн.v += (Math.random() - .5) * .4;
        this.пр.медл.v += (Math.random() - .5) * .3;
      }
    };
  }

  process(_, outputs){
    const oL = outputs[0][0], oR = outputs[0][1], n = oL.length, p = this.p;

    // ---- ПЛОЩАДКИ ---------------------------------------------------------
    // На приборе они все ОДИНАКОВЫЕ и делают одно: палец подключает своё
    // сопротивление к частотозадающей цепи. Ток заряда чуть подрастает, форма
    // чуть меняется — фактура становится другой, но тон никуда не улетает.
    // Разница между площадками только в номинале: от еле заметной к самой
    // ощутимой. Нажатые вместе — складываются, как параллельные резисторы.
    const пл = this.пл;
    let утечка = 0;
    for (let i = 1; i <= 8; i++) утечка += пл[i] * (.05 + i * .028);
    const пар = { утечка };

    this.батТик += n;
    if (p.батарея > .01 && this.батТик > SR * .5){
      this.батТик = 0;
      this.батЗаряд = Math.max(.5, this.батЗаряд - p.батарея * .0009);
    } else if (p.батарея <= .01) this.батЗаряд = 1;

    for (let s = 0; s < n; s++){
      let x = this.пр.шаг(p, пар);
      if (this.пр.Vdd > this.батЗаряд) this.пр.Vdd = this.батЗаряд;

      // наводка от руки на неэкранированной цепи — тем заметнее, чем больше
      // площадок прижато
      if (утечка > .01){
        this.наводка = this.наводка * .9994 + (Math.random() - .5) * утечка * .0025;
        x += this.наводка;
      }
      let y = clamp(x, -1, 1);
      if (!(y === y)){ y = 0; this.пр.сброс(); this.срывы++; }

      if (++this.окно >= SR * .25){ this.окно = 0; this.пр.мера(); }
      const a2 = y < 0 ? -y : y;
      if (a2 > this.пик) this.пик = a2;
      oL[s] = y;
      oR[s] = y;
      this.осц[this.осцИ = (this.осцИ + 1) & 255] = y;
      if (++this.проре >= SR / 100){ this.проре = 0;
        this.след[this.слИ] = this.пр.u; this.слИ = (this.слИ + 1) % 200; }
    }

    this.отчёт += n;
    if (this.отчёт >= SR / 30){
      this.отчёт = 0;
      const л = new Float32Array(200);
      for (let i = 0; i < 200; i++) л[i] = this.след[(this.слИ + i) % 200];
      this.port.postMessage({
        пик: this.пик, разброс: this.пр.разбр, гц: this.пр.гц || 0,
        высота: this.пр.осн.f || 0, скважность: this.пр.осн.скв,
        второйГц: this.пр.вт.f || 0,
        шина: this.пр.Vdd, срывы: this.срывы, батарея: this.батЗаряд,
        осц: this.осц.slice(), след: л,
        качели: this.пр.u, гуляние: this.пр.g,
        пл: Array.from(this.пл)
      });
      this.пик *= .6;
    }
    return true;
  }
}
registerProcessor('хаос', Хаос);
