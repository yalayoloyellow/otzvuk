// ============================================================================
//  ХАОС — ядро инструмента.
//
//  Устройство списано с шумовых синтезаторов на КМОП-логике (40106): шесть
//  генераторов на триггерах Шмитта, связанных перекрёстно и сидящих на общей
//  просаженной шине питания. Характер там рождается не в генераторах, а в их
//  взаимном влиянии: каждый импульс сажает питание, от этого плывут все
//  остальные. Развязки нет НАМЕРЕННО — она бы убила всю живость.
//
//  Математически это сеть связанных нелинейных осцилляторов. Её поведение
//  описывает отображение окружности: сила связи ведёт от захвата в жёсткие
//  ритмические отношения (языки Арнольда) через квазипериодичность к хаосу,
//  а расстройка выбирает, какое именно отношение. Поэтому две ручки дают
//  осмысленную карту, а не лотерею.
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// Шкала, растянутая возле критической точки. Без неё край хаоса — щель
// шириной в пару процентов хода, и ручка работает как выключатель:
// только что был ровный ритм, и сразу каша, а интересное проскочило.
function растяни(x, крит) {
  const t = clamp(x, 0, 1) - крит;
  return крит + Math.sign(t) * Math.pow(Math.abs(t) / Math.max(крит, 1 - крит), 1.8)
         * Math.max(крит, 1 - крит);
}

// ---- УЗЕЛ: релаксационный генератор ----------------------------------------
// Всё, что здесь есть, проверено счётом (см. РАЗБОР.md, раздел ПРОВЕРКА):
//
//  · Постоянная времени берётся как 1/(ln4·f), а НЕ 1/(1.2·f). Константа 1.2
//    из даташита относится к реальным порогам конкретного чипа, а у нас
//    идеальные ⅓ и ⅔, для которых период равен RC·ln4. Прежняя константа
//    занижала частоту ровно на 13.4% — измерено −13.5…−14.0%.
//
//  · Момент пересечения порога считается ВНУТРИ шага аналитически. Без этого
//    период всегда целое число отсчётов, и частота липнет к сетке SR/n:
//    заданные 9000 Гц звучали как 6000, ошибка до трети.
//
//  · Защитные диоды ограничивают напряжение на АБСОЛЮТНЫЕ 0.6 В за шины.
//    Это единственная величина в схеме, не пропорциональная питанию, и
//    именно она делает частоту зависимой от просадки: без неё питание
//    сокращается во всех формулах и не слышно вовсе (проверено — ровный ноль).
class Узел {
  constructor(i, семя){
    this.i = i;
    const r = Math.sin(семя * 12.9898 + i * 78.233) * 43758.5453;
    this.разброс = 1 + ((r - Math.floor(r)) - .5) * .06;   // допуск деталей ±3%
    this.v = .3 + (i * .137) % .4;
    this.q = i & 1 ? 1 : 0;          // однополярная логика, как в железе
    this.вых = 0;
    this.сгл = 0;
    this.щелчок = 0;
  }
  // Vdd — текущее напряжение шины: оно живое и проседает под нагрузкой.
  // ток — 1/RC в герцах; сосед и связь — диффузионная связь через резистор.
  шаг(частота, Vdd, сосед, связь, гист, асим, шум){
    const порогВерх = Vdd * (.5 + гист * .28);
    const порогНиз  = Vdd * (.5 - гист * .28);
    const цель = this.q ? Vdd : 0;
    const RC = 1 / (Math.log(4) * Math.max(1, частота) * this.разброс);
    const dt = 1 / SR;
    // асимметрия цепей заряда и разряда — физическая причина свинга
    const τ = RC / (this.q ? (1 + асим) : (1 - асим));
    const было = this.v;
    this.v += (цель - this.v) * (1 - Math.exp(-dt / τ));
    if (связь > 0) this.v += (сосед - this.v) * связь * (dt / τ);

    // диоды: абсолютные 0.6 В за шины, не доля питания
    if (this.v < -.6) this.v = -.6;
    else if (this.v > Vdd + .6) this.v = Vdd + .6;

    this.щелчок = 0;
    const порог = this.q ? порогВерх : порогНиз;
    const пересёк = this.q ? (this.v > порог) : (this.v < порог);
    if (пересёк){
      // доля шага до настоящего пересечения — из точного решения экспоненты
      const d0 = было - цель, d1 = порог - цель;
      let доля = (d0 !== 0 && d1 / d0 > 0) ? -Math.log(d1 / d0) * τ / dt : .5;
      доля = доля < 0 ? 0 : доля > 1 ? 1 : доля;
      this.q ^= 1;
      this.щелчок = this.q ? 1 : -1;
      this.доля = доля;
      // выход усредняется по шагу: ступенька встаёт в правильную точку,
      // а не на границу отсчёта — это и снимает квантование частоты
      this.вых = Vdd * ((this.q ? 1 : 0) * (1 - доля) + (this.q ? 0 : 1) * доля);
    } else {
      this.вых = this.q ? Vdd : 0;
    }
    // ток потребления: заряд конденсатора плюс бросок при переключении
    this.ток = Math.abs(цель - this.v) / (τ * SR) + (this.щелчок ? .35 : 0);
    this.сгл += ((this.v - Vdd * .5) - this.сгл) * .25;
    return this.сгл;
  }
}

class Хаос extends AudioWorkletProcessor {
  constructor() {
    super();
    this.N = 6;
    this.узлы = [];
    for (let i = 0; i < this.N; i++) this.узлы.push(new Узел(i, 1));

    // Параметры — то, что крутится с клавиатуры. Все в 0…1, наружу
    // разворачиваются нелинейно, чтобы интересное занимало весь ход.
    this.p = {
      частота: .35,     // общая высота
      разброс: .5,      // расстройка узлов друг относительно друга
      связь: .3,        // сила кросс-модуляции: главная ручка хаоса
      питание: .25,     // насколько сильно узлы сажают общую шину
      гистерезис: .5,   // ширина петли триггера
      логика: .3,       // доля логического смешения против аналогового
      фильтр: .6,       // срез выходного фильтра
      резонанс: .2,
      обратная: .15,    // возврат выхода на вход сети
      шум: .25,         // тепловой шум на порогах: живое дрожание момента
      грязь: .3,        // насыщение и перегруз
      // ---- медленная часть: пульс рождается захватом, а не счётчиком ----
      пульс: .4,        // частота медленных узлов, доли герца … единицы
      делёж: .35,       // расстройка медленных: во что они захватятся (2:1, 3:1…)
      качели: .5,       // асимметрия RC — физическая причина свинга
      // ---- резонатор вместо подмешанного баса ----
      струна: .3,       // сколько его в звуке
      натяг: .35,       // частота покоя
      мягкость: .45,    // нелинейность Дуффинга: высота едет с амплитудой
      затух: .5,        // добротность
      // ---- нелинейности тракта ----
      сворачивание: 0,  // диодный фолдер: спектр не режется, а складывается
      асимметрия: .5    // смещение перед насыщением: чётные гармоники, тепло
    };
    // медленные узлы: те же триггеры Шмитта, но на инфранизких частотах
    this.М = 3;
    this.медл = [];
    for (let i = 0; i < this.М; i++) this.медл.push(new Узел(i + 11, 2));
    // резонатор Дуффинга: нелинейная пружина. Мягкая характеристика —
    // чем сильнее раскачана, тем ниже частота; при затухании высота сама
    // ползёт вверх. Это физическая причина того, что в 808 рисуют экспонентой.
    this.rx = 0; this.rv = 0;

    this.шина = 1;      // напряжение общей шины
    this.бросок = 0;    // импульсный ток потребления
    this.вLp = 0;
    this.уНиз = 0; this.уСер = 0; this.уВерх = 0; this.гц = 0;
    this.lp = 0; this.bp = 0;
    this.fb = 0;
    this.dcx = 0; this.dcy = 0;

    // Питание: конденсатор развязки, который проседает под током и
    // восстанавливается. Именно через него генераторы влияют друг на друга —
    // развязки нет НАМЕРЕННО, это и есть «дышит вместе».
    this.Vdd = 1; this.токШины = 0; this.свПрош = 0;
    // Мера беспорядка — по РАЗБРОСУ ИНТЕРВАЛОВ между щелчками пульса.
    // Показатель Ляпунова по непрерывной траектории у релаксационных схем
    // врёт: между переключениями система всегда сжимается, и он показывает
    // порядок при любой связи. Слышно же именно ровность щелчков.
    this.инт = new Float32Array(48); this.интИ = 0; this.интN = 0;
    this.сЩелчка = 0; this.разбр = 0; this.окно = 0;
    // Число вращения: отношение частот двух первых узлов. Рациональное —
    // значит захват в ритмическую фигуру, иррациональное — плывёт.
    this.переходы = [0, 0];
    this.прошлое = [0, 0];
    this.окно = 0;
    this.вращение = 0;

    this.пик = 0; this.rms = 0;
    this.отчёт = 0;
    this.осц = new Float32Array(256);
    this.осцИ = 0;
    this.спектр = new Float32Array(24);
    this.гон = 0;

    this.port.onmessage = e => {
      const d = e.data;
      if (d.t === 'p') { for (const k in d.v) if (k in this.p) this.p[k] = clamp(d.v[k], 0, 1); }
      else if (d.t === 'толчок') {           // встряска: выбить из застоя
        for (const u of this.узлы) u.v += (Math.random() - .5) * .6;
      }
    };
  }

  process(inputs, outputs) {
    const oL = outputs[0][0], oR = outputs[0][1], n = oL.length;
    const p = this.p;

    for (let s = 0; s < n; s++) {
      // ---- питание: живая шина ------------------------------------------
      // Ток тянут все узлы разом; ёмкость развязки сглаживает, но не спасает.
      // Просадка слышна потому, что диоды в узлах имеют АБСОЛЮТНОЕ падение —
      // без них питание сокращалось бы во всех формулах и не влияло ни на что
      // (проверено: ровный ноль по всем метрикам).
      const жёсткость = .0004 + (1 - p.питание) * .01;
      // Множитель 60: сырой ток заряда даёт около двух тысячных, и просадка
      // была неразличима — ручка не делала ничего (проверено, ровный ноль).
      // Приводим к масштабу, где полностью открытая ручка реально сажает шину.
      this.Vdd += ((1 - clamp(this.токШины * 60, 0, 1) * p.питание * .85) - this.Vdd) * жёсткость;
      if (this.Vdd < .15) this.Vdd = .15;
      let токСумма = 0;

      // ---- медленные: пульс из захвата ----------------------------------
      const свМедл = растяни(p.связь, .42) * .9;
      for (let i = 0; i < this.М; i++) {
        const u = this.медл[i];
        const f = (.15 + p.пульс * 7) * Math.pow(2, i * p.делёж * 2.4);
        u.шаг(f, this.Vdd, this.медл[(i + 1) % this.М].v, свМедл,
              .5, (p.качели - .5) * .8, p.шум);
        токСумма += u.ток;
      }
      const пульс = (this.медл[0].сгл + this.медл[1].сгл * .6) / this.Vdd;

      // ---- НИЗ: резонатор от ударов пульса --------------------------------
      let низ = 0;
      if (p.струна > .003) {
        const w = 2 * Math.PI * (26 + p.натяг * 78) / SR;
        const α = w * w, β = -α * clamp(p.мягкость, 0, 1) * .9;
        const δ = w * ((1 - p.затух) * .05 + .0012);
        let удар = 0;
        for (const u of this.медл) if (u.щелчок > 0) удар += 1;
        const x2 = this.rx * this.rx;
        this.rv += -α * this.rx - β * this.rx * x2 / (1 + x2) - δ * this.rv + удар * w * .5;
        this.rx += this.rv;
        if (this.rx > 3) { this.rx = 3; this.rv *= -.4; }
        else if (this.rx < -3) { this.rx = -3; this.rv *= -.4; }
        низ = Math.tanh(this.rx * 1.6) * p.струна * 1.15;
      }

      // ---- СЕРЕДИНА: связанная пара, здесь живёт хаос ---------------------
      const базовая = 30 * Math.pow(2, p.частота * 7.5);
      const св = растяни(p.связь, .42) * 1.6;
      const гист = .25 + p.гистерезис * .6;
      let серед = 0;
      for (let i = 0; i < 2; i++) {
        const u = this.узлы[i], сосед = this.узлы[1 - i];
        const f = базовая * (i ? Math.pow(2, p.разброс * 1.6) : 1);
        серед += u.шаг(f, this.Vdd, сосед.v, св, гист, (p.качели - .5) * .5, p.шум);
        токСумма += u.ток;
      }
      серед *= .9;
      if (p.грязь > .01) {
        const см = (p.асимметрия - .5) * .5, dr = 1 + p.грязь * 12;
        серед = Math.tanh((серед + см) * dr) - Math.tanh(см * dr);
      }
      // Сворачивание — единственное место, где алиасинг реально силён
      // (до 51% на высоких частотах, проверено). Поэтому считаем его на
      // учетверённой частоте с усреднением: дешёвый, но действенный приём.
      if (p.сворачивание > .01) {
        const g = 1 + p.сворачивание * 6;
        let сум = 0;
        for (let k = 0; k < 4; k++) {
          const t = серед + (this.свПрош - серед) * (3 - k) / 4;
          сум += Math.sin(t * g * 1.7);
        }
        this.свПрош = серед;
        серед = серед * (1 - p.сворачивание) + (сум / 4) * p.сворачивание;
      }

      // ---- ВЕРХ: логическое смешение --------------------------------------
      let верх = 0;
      if (p.логика > .01) {
        for (let i = 2; i < this.N; i++) {
          const u = this.узлы[i];
          const f = базовая * Math.pow(2, 1.4 + (i - 2) * (.35 + p.разброс * .8));
          u.шаг(f, this.Vdd, this.узлы[(i + 1) % this.N].v, св * .5, гист, 0, p.шум);
          токСумма += u.ток;
        }
        const пол = u => u.вых > this.Vdd * .5;
        const a = пол(this.узлы[2]), b = пол(this.узлы[3]), c = пол(this.узлы[4]);
        верх = (((a !== b) !== c) ? 1 : -1) * p.логика * .45;
        this.вLp += (верх - this.вLp) * .3;
        верх -= this.вLp;
      }
      this.токШины += (токСумма / (this.N + this.М) - this.токШины) * .01;

      // ---- сборка ---------------------------------------------------------
      let x = низ + серед * (1 - p.струна * .3) + верх;
      // Отдельной ручки «просадка» больше нет: она дублировала «питание» —
      // оба параметра управляли одним механизмом, и вторая была неслышна.
      // Лучше меньше ручек, но каждая делает своё.
      x *= .45 + .55 * clamp(this.Vdd, 0, 1);

      const fc = 40 * Math.pow(2, p.фильтр * 8.5);
      const k = clamp(2 * Math.sin(Math.PI * Math.min(fc, SR * .45) / SR), .001, 1.4);
      const q = 1.45 - p.резонанс * 1.4;
      this.lp += k * this.bp;
      const hp = x - this.lp - q * this.bp;
      this.bp += k * hp;
      x = this.lp + this.bp * p.резонанс * .6;

      this.fb = x;
      this.dcy = x - this.dcx + .9995 * this.dcy; this.dcx = x;
      let y = clamp(this.dcy * .55, -1, 1);

      if (!(y === y)) {
        y = 0; this.rx = 0; this.rv = 0; this.lp = 0; this.bp = 0;
        this.fb = 0; this.dcx = 0; this.dcy = 0; this.Vdd = 1; this.токШины = 0;
        for (const u of this.узлы) if (!(u.v === u.v)) { u.v = .3; u.q = 1; }
        for (const u of this.медл) if (!(u.v === u.v)) { u.v = .3; u.q = 1; }
        this.срывы = (this.срывы || 0) + 1;
      }

      this.сЩелчка++;
      if (this.медл[0].щелчок !== 0) {
        if (this.сЩелчка > 4 && this.сЩелчка < SR * 4) {
          this.инт[this.интИ = (this.интИ + 1) % this.инт.length] = this.сЩелчка;
          if (this.интN < this.инт.length) this.интN++;
        }
        this.сЩелчка = 0;
      }
      if (++this.окно >= SR * .25) {
        this.окно = 0;
        if (this.интN > 4) {
          let сум = 0;
          for (let i = 0; i < this.интN; i++) сум += this.инт[i];
          const ср = сум / this.интN;
          let д = 0;
          for (let i = 0; i < this.интN; i++) { const t = this.инт[i] - ср; д += t * t; }
          this.разбр = ср > 1 ? Math.sqrt(д / this.интN) / ср : 0;
          this.гц = SR / ср;
        }
      }

      const a2 = y < 0 ? -y : y;
      if (a2 > this.пик) this.пик = a2;
      this.уНиз += (Math.abs(низ) - this.уНиз) * .001;
      this.уСер += (Math.abs(серед) - this.уСер) * .001;
      this.уВерх += (Math.abs(верх) - this.уВерх) * .001;

      oL[s] = y;
      const yR = this.dcy * .55 * .94 + this.узлы[1].сгл * .06;
      oR[s] = (yR === yR) ? clamp(yR, -1, 1) : 0;
      this.осц[this.осцИ = (this.осцИ + 1) & 255] = y;
    }

    this.отчёт += n;
    if (this.отчёт >= SR / 30) {
      this.отчёт = 0;
      this.port.postMessage({
        пик: this.пик, разброс: this.разбр, гц: this.гц || 0,
        шина: this.Vdd, срывы: this.срывы || 0,
        осц: this.осц.slice(),
        низ: this.уНиз, серед: this.уСер, верх: this.уВерх,
        медл: this.медл.map(u => u.сгл), струна: this.rx
      });
      this.пик *= .6;
    }
    return true;
  }
}
registerProcessor('хаос', Хаос);
