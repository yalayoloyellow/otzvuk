// ============================================================================
//  ХАОС — ядро инструмента.
//
//  Модель собрана ПО ЦЕПИ настоящего прибора, узел за узлом. Каждый класс —
//  это деталь на плате, а не приём обработки звука:
//
//      Сборка      номиналы этого экземпляра, вынутые из семени
//      Качели      медленный генератор (и ещё более медленный над ним)
//      Генератор   релаксационный узел на триггере Шмитта — источник звука
//      Шина        батарейка и питание, живое и проседающее
//      Рука        пальцы на контактных площадках
//      Излучатель  динамик: масса на подвесе, стоит В РАЗРЫВЕ цепи
//      Прибор      соединяет всё это проводами
//
//  Главный механизм — КАЧЕЛИ: медленный узел ведёт ТОКОМ заряд звукового.
//  Звуковой ездит по четырём-шести октавам, внизу проваливается в 25–45 Гц,
//  где прямоугольник слышен отдельными импульсами, наверху уходит за
//  килогерц. Ухо читает это как ритмический рисунок, а не как модуляцию.
//  Тот же ток перекашивает скважность: высота и грязь связаны ОДНОЙ
//  величиной, потому что в железе это один резистор.
//
//  Всё считается посэмплово: обратные связи не векторизуются в принципе.
// ============================================================================
const SR = sampleRate;
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

// ПЕРЕДИСКРЕТИЗАЦИЯ. Прямоугольник с резким фронтом честно занимает полосу
// далеко за слышимой; на частоте выхода его верхние гармоники заворачиваются
// вниз негармоничным звоном — это и есть «цифровое» звучание. Аналог тут ни
// при чём: в железе такой полосы просто нет ограничения. Поэтому вся цепь
// считается вчетверо чаще, а вниз сводится честным фильтром — тогда фронт
// может остаться острым, не покупая мягкость ценой глухоты.
const КРАТ = 4;
const ЧД = SR * КРАТ;

// Фильтр сведения: Баттерворт четвёртого порядка на 0.42 от исходной частоты
// дискретизации, два биквада каскадом.
class Свод {
  constructor(){
    this.з = [[0,0,0,0],[0,0,0,0]];
    const fc = SR * .42, K = Math.tan(Math.PI * fc / ЧД);
    this.b = [];
    for (const Q of [.5412, 1.3066]){
      const н = 1 / (1 + K/Q + K*K);
      this.b.push([K*K*н, 2*K*K*н, K*K*н, 2*(K*K-1)*н, (1 - K/Q + K*K)*н]);
    }
  }
  шаг(x){
    for (let i = 0; i < 2; i++){
      const [b0,b1,b2,a1,a2] = this.b[i], з = this.з[i];
      const y = b0*x + b1*з[0] + b2*з[1] - a1*з[2] - a2*з[3];
      з[1] = з[0]; з[0] = x; з[3] = з[2]; з[2] = y;
      x = y;
    }
    return x;
  }
}

// ---- СБОРКА ----------------------------------------------------------------
// Все номиналы этого экземпляра в одном месте. Для исполнителя они выглядят
// случайностью, хотя выведены из семени: случайность здесь — это ровно то,
// к чему у него НЕТ ДОСТУПА, но что звучит. Разброс широкий намеренно —
// приборы собирались из того, что было под рукой, и две коробки отличаются
// не на проценты.
class Сборка {
  constructor(семя){
    let x = (семя >>> 0) || 1;
    const r = () => { x = (Math.imul(x, 1664525) + 1013904223) >>> 0; return x / 4294967296; };
    const м = (a, b) => a + r() * (b - a);

    // Три генератора на плате: свои допуски и своё место в разводке.
    // Первый — ведущий, два других уходят от него тем дальше, чем сильнее
    // разведены подстроечники.
    this.доп = [м(.96, 1.04), м(.93, 1.07), м(.90, 1.10)];
    // Куда уходит каждый узел при разведении подстроечников. Второй держится
    // рядом и даёт биения, третий уходит далеко вверх: наверху качелей он
    // выскакивает за пять килогерц, и вместе с дребезгом это уже шипение,
    // а не тон. Так шум и получают в таких схемах.
    this.разв = [0, м(.35, .8), м(3.2, 6.5)];
    this.вес  = [1, м(.55, .9), м(.4, .8)];
    this.допОсн  = this.доп[0];       // допуск частотозадающей цепи
    this.допМедл = м(.90, 1.10);
    this.допГул  = м(.86, 1.14);
    this.петля   = м(.14, .24);       // полуширина петли триггера
    // Нагрузочная ёмкость монтажа задаёт скорость фронта, то есть мягкость.
    // Короткий монтаж — резкий и звонкий, длинный — тёплый и глухой.
    this.фронт   = м(.22, 1);
    this.fИзл    = м(58, 165);        // резонанс подвеса динамика
    this.затИзл  = м(.18, .55);       // насколько вялый подвес
    this.срез    = м(2200, 7000);     // RC на выходе: провода и корпус
    this.перекос = м(-.10, .10);      // общий перекос номиналов
    this.батарея = м(.55, 1);         // свежесть батарейки
    this.имя = ((семя >>> 0).toString(36) + '0000').slice(0, 4);
  }
}

// ---- ГЕНЕРАТОР -------------------------------------------------------------
// Элемент с триггером Шмитта и RC в обратной связи. Заряжается к питанию,
// разряжается к нулю, переключается на порогах. Это весь его репертуар.
class Генератор {
  constructor(сборка, допуск, фаза){
    this.сб = сборка;
    this.доп = допуск;
    this.v = .2 + фаза * .5;
    this.q = 1;
    this.вых = -1; this.сгл = -1;
    this.тзар = 0; this.тразр = 0;
    this.f = 0; this.скв = .5; this.щелчок = 0; this.ток = 0;
    this.фронт = 1;                    // 1 — мгновенный, меньше — мягче
  }

  // f   — частота при нулевом управляющем токе
  // см  — управляющий ток в долях питания: подгоняет заряд и тормозит разряд.
  //       Если подтянет точку покоя выше нижнего порога, генератор запрётся,
  //       потому и ограничен здесь же.
  // Vdd — живое питание
  // др  — тепловой шум в цепи заряда
  шаг(f, см, Vdd, др){
    const ш = this.сб.петля;
    const порогВ = Vdd * (.5 + ш), порогН = Vdd * (.5 - ш);
    const смО = clamp(см, 0, .5 - ш - .02) * Vdd;
    const цель = (this.q ? Vdd : 0) + смО;
    // Пороги не идеальные ⅓ и ⅔, поэтому и постоянная времени своя:
    // период равен RC · 2·ln((0.5+ш)/(0.5−ш)).
    const К = 2 * Math.log((.5 + ш) / (.5 - ш));
    const RC = 1 / (К * Math.max(.02, f) * this.доп);
    const прошл = this.v;
    this.v += (цель - this.v) * (1 - Math.exp(-1 / (ЧД * RC)));
    // Защитные диоды ограничивают напряжение на АБСОЛЮТНЫЕ 0.6 В за шины.
    // Это единственная величина в схеме, не пропорциональная питанию, и
    // только благодаря ей просадка вообще слышна: без диодов Vdd сокращается
    // во всех формулах и на частоту не влияет (проверено — ровный ноль).
    if (this.v < -.6) this.v = -.6;
    else if (this.v > Vdd + .6) this.v = Vdd + .6;

    // ТЕПЛОВОЙ ШУМ сидит в цепи заряда, а триггер сэмплирует его в момент
    // решения. Сдвиг тем больше, чем ПОЛОЖЕ кривая заряда в этой точке:
    // возле асимптоты малая помеха переносит переключение далеко. Отсюда
    // физический факт — низкие ноты хрипят заметнее высоких.
    let пВ = порогВ, пН = порогН;
    if (др > .001){
      const наклон = Math.max(.10, Math.abs(цель - this.v));
      const сдв = clamp((Math.random() - .5) * др * .06 / наклон * Vdd,
                        -Vdd * ш * .8, Vdd * ш * .8);
      пВ += сдв; пН += сдв;
    }

    let сырой = this.q ? 1 : -1;
    this.щелчок = 0;
    if (this.q ? this.v > пВ : this.v < пН){
      // Момент пересечения считается ВНУТРИ шага. Без этого период всегда
      // целое число отсчётов, частота липнет к сетке SR/n, и наверху качелей
      // вместо визга получается ступенчатый мусор.
      const порог = this.q ? пВ : пН;
      const зн = this.v - прошл;
      const доля = зн !== 0 ? clamp((порог - прошл) / зн, 0, 1) : .5;
      const стар = сырой;
      this.q ^= 1;
      сырой = стар * доля + (this.q ? 1 : -1) * (1 - доля);
      this.щелчок = this.q ? 1 : -1;
      if (this.q){
        const T = this.тзар + this.тразр;
        if (T > 1){ this.f = ЧД / T; this.скв = this.тзар / T; }
        this.тзар = 0; this.тразр = 0;
      }
    }
    if (this.q) this.тзар++; else this.тразр++;

    // СКОРОСТЬ ФРОНТА. Выходной ток элемента конечен, нагрузка ёмкостная —
    // ступенька не бывает мгновенной. Разрыв за один отсчёт даёт то самое
    // цифровое звучание: гармоники выше Найквиста заворачиваются вниз
    // негармоничным звоном. Ограничение тока — не фильтр поверх звука, а
    // ровно та причина, по которой в аналоге этого звона нет.
    const шг = this.фронт;
    if (сырой > this.сгл + шг) this.сгл += шг;
    else if (сырой < this.сгл - шг) this.сгл -= шг;
    else this.сгл = сырой;

    this.ток = Math.abs(цель - this.v) / (RC * ЧД) + (this.щелчок ? .35 : 0);
    this.вых = this.сгл;
    return this.вых;
  }

  // Паразитная связь через монтаж: сосед подтягивает конденсатор. Слабая,
  // но именно она собирает разведённые узлы обратно в захват.
  связь(чужое, k){ this.v += (чужое - this.v) * k; }

  // напряжение на конденсаторе, приведённое к 0…1 — управляющая величина
  упр(){ const ш = this.сб.петля; return clamp((this.v - (.5 - ш)) / (2 * ш), 0, 1); }
}

// ---- КАЧЕЛИ ----------------------------------------------------------------
// Медленный генератор, ведущий заряд звукового, и ещё более медленный над
// ним. Отдаёт одну величину u — положение качелей от нижней точки к верхней.
class Качели {
  constructor(сборка){
    this.сб = сборка;
    this.медл = new Генератор(сборка, сборка.допМедл, .31);
    this.гул  = new Генератор(сборка, сборка.допГул, .67);
    this.u = .5; this.g = .5; this.период = 0;
  }
  // качание — ПЕРИОД рисунка: слева десятки герц (сливается в тембр),
  //           справа доли герца (одно движение на несколько секунд)
  // гуляние — глубина, с которой верхний генератор качает период нижнего
  шаг(качание, гуляние){
    let F = 60 * Math.pow(2, -качание * 7.7);
    if (гуляние > .002){
      this.гул.шаг(Math.max(.02, F * .09), 0, 1, 0);
      this.g = this.гул.упр();
      F *= Math.pow(2, (this.g - .5) * гуляние * 3.4);
    } else this.g = .5;
    this.период = 1 / Math.max(.02, F);
    this.медл.шаг(Math.max(.03, F), 0, 1, 0);
    this.u = this.медл.упр();
    return this.u;
  }
}

// ---- ШИНА ------------------------------------------------------------------
// Батарейка и питание. Импульсы жрут ток, шина проседает, пороги едут за
// ней — а диоды остаются на своих абсолютных 0.6 В. Развязки нет намеренно:
// она убила бы всю живость. Органом управления это не было и на приборе,
// поэтому ручки здесь нет — только физика.
class Шина {
  constructor(сборка){ this.сб = сборка; this.V = 1; this.ток = 0; this.заряд = 1; this.тик = 0; }
  шаг(ток, утечка){
    this.ток += (ток - this.ток) * .01;
    const цель = this.заряд * (1 - clamp(this.ток * 60, 0, 1) * .28 - утечка * .10);
    this.V += (цель - this.V) * .012;
    if (this.V < .2) this.V = .2;
    return this.V;
  }
  // батарейка садится за минуты — медленный дрейф, который слышно на долгой игре
  минута(n){
    this.тик += n;
    if (this.тик > SR * .5){
      this.тик = 0;
      this.заряд = Math.max(.5, this.заряд - (1 - this.сб.батарея) * .0016);
    }
  }
}

// ---- РУКА ------------------------------------------------------------------
// Контактные площадки. На приборе они ВСЕ ОДИНАКОВЫЕ: палец подключает своё
// сопротивление к одной и той же точке цепи и отличаются они только номиналом.
// Поэтому здесь одна величина — утечка, — и она расходится по узлам сама.
// Главное, что она делает, слышно при любом положении качелей: подгружает
// выход, сажает шину и грязнит фронт. Уход частоты вторичен — иначе палец
// терялся бы на фоне качелей, которые ездят на четыре октавы.
class Рука {
  constructor(){ this.у = 0; this.наводка = 0; }
  шаг(пл){
    let у = 0;
    for (let i = 1; i <= 8; i++) у += пл[i] * (.10 + i * .055);
    this.у += (у - this.у) * .01;
    // ладонь на неэкранированной цепи ловит наводку
    this.наводка = this.наводка * .9993 + (Math.random() - .5) * this.у * .003;
    return this.у;
  }
}

// ---- ИЗЛУЧАТЕЛЬ ------------------------------------------------------------
// Динамик — не провод, а масса на подвесе. Он стоит В РАЗРЫВЕ цепи: наружу
// выходит только то, что он излучил. Ниже резонанса не отдаёт ничего, на
// резонансе подпирает — отсюда телесная середина вместо синтетического
// полного диапазона. Наружу идёт СКОРОСТЬ диффузора: микрофон слышит
// движение, а не положение.
class Излучатель {
  constructor(сборка){ this.сб = сборка; this.скорость = 0; this.ход = 0; }
  шаг(x, удар, утечка){
    const ω = 2 * Math.PI * this.сб.fИзл / ЧД;
    // палец на площадке подгружает выход — подвес отзывается вяло
    const зат = (this.сб.затИзл - удар * (this.сб.затИзл - .035)) * (1 + утечка * 1.6);
    // Подвес НЕЛИНЕЙНЫЙ: чем дальше ушёл диффузор, тем жёстче его тянет
    // назад. Это не защита от перегруза, а устройство настоящего динамика —
    // и именно оно даёт грязный низ и увод тона на громких ударах, само
    // ограничивая размах. Жёсткое обрезание хода, стоявшее здесь раньше,
    // и было той некрасивой резкостью.
    const жёстк = 1 + 2.5 * this.ход * this.ход;
    // УСКОРЕНИЕ диффузора, а не его скорость: звуковое давление пропорционально
    // именно ускорению. Выше резонанса ход и скорость малы, ускорение идёт
    // за сигналом один в один — отдача плоская и звук остаётся острым. На
    // резонансе подъём, ниже — спад 12 дБ на октаву. Скорость на выходе,
    // стоявшая здесь раньше, давала спад ВЫШЕ резонанса: отсюда глухота.
    const уск = x - this.ход * жёстк - this.скорость * зат;
    this.скорость += ω * уск;
    this.ход += ω * this.скорость;
    if (this.ход > 3) { this.ход = 3; this.скорость *= -.3; }
    else if (this.ход < -3) { this.ход = -3; this.скорость *= -.3; }
    // ЭЛЕКТРИЧЕСКОЕ ДЕМПФИРОВАНИЕ. Усилитель не идеальный источник
    // напряжения: у него есть выходное сопротивление, и ток, наведённый
    // движущейся катушкой, тормозит её тем сильнее, чем звонче подвес.
    // Поэтому звонкий динамик не выходит вшестеро громче вялого — он выходит
    // ОСТРЕЕ. Без этого прибор то шептал, то рвал дорожку.
    // Сила, которую катушка может развить, ограничена током, а ток —
    // напряжением батарейки. Поэтому и ускорение имеет потолок: на самых
    // резких ударах усилитель просто упирается в питание. Мягко, как
    // упирается настоящий транзисторный каскад.
    const пик = 1.5;
    let у = уск;
    if (у > пик) у = пик + (у - пик) * .12;
    else if (у < -пик) у = -пик + (у + пик) * .12;
    const норм = Math.sqrt(зат / this.сб.затИзл);
    return у * норм;
  }
}

// ---- ПРИБОР ----------------------------------------------------------------
// Соединяет узлы проводами. Здесь нет ни одной величины, которой не было бы
// у железа: только номиналы сборки и то, что стоит на ручках.
class Прибор {
  constructor(семя){
    this.сб = new Сборка(семя);
    this.качели = new Качели(this.сб);
    // ТРИ ГЕНЕРАТОРА. Один узел звучит бедно по определению: у него нет
    // ни с кем разницы частот, а весь характер таких приборов рождается
    // именно во встрече нескольких. Сведённые вместе они бьются и дают
    // музыкальные биения, разведённые — треск и шум, а на общей нагрузке
    // между ними рождаются разностные тоны, которых нет ни в одном.
    this.узлы = [];
    for (let i = 0; i < 3; i++){
      const г = new Генератор(this.сб, this.сб.доп[i], .07 + i * .29);
      г.фронт = this.сб.фронт;
      this.узлы.push(г);
    }
    this.осн = this.узлы[0];
    this.шина = new Шина(this.сб);
    this.излуч = new Излучатель(this.сб);
    this.вч = 0; this.лп = 0; this.вых = 0;
    this.инт = new Float32Array(32); this.интИ = 0; this.интN = 0; this.сЩ = 0;
    this.разбр = 0; this.гц = 0;
  }

  шаг(p, утечка, наводка){
    const u = this.качели.шаг(p.качание, p.гуляние);

    // Нижняя точка качелей держится в области треска на всём ходу ХАРАКТЕРА —
    // иначе рисунок пропадает и остаётся вой. Верхняя уходит тем выше, чем
    // правее ручка. Раскрываются они ОТ ЦЕНТРА, поэтому нулевой размах — это
    // ровный тон средней высоты, а не гул на самом низу.
    const хар = clamp(p.характер + this.сб.перекос * .35, 0, 1);
    const низ  = 24  * Math.pow(2, хар * 1.2);
    const верх = 300 * Math.pow(2, хар * 4.0);
    const центр = Math.sqrt(низ * верх);
    const рзм = clamp(p.размах, 0, 1);
    const пол = центр * Math.pow(низ / центр, рзм);
    const пот = центр * Math.pow(верх / центр, рзм);
    const f = пол * Math.pow(пот / пол, u) * (1 + утечка * .12);

    // Управляющий ток велик там, где качели внизу: он же и утаскивает их
    // туда, тормозя разряд. Ручка ИМПУЛЬС добавляет к нему постоянную часть
    // с подстроечного резистора смещения — это самый громкий орган в начале
    // цепи: симметричный прямоугольник делается узким и резким.
    const см = (.12 + хар * .19) * рзм * (1 - u) + p.импульс * .215 + утечка * .06;
    const V = this.шина.V;
    const др = p.дребезг + утечка * .18;
    // РАЗВОД подстроечников. При нуле все три сидят в унисоне и монтажная
    // связь держит их захваченными — слышен один голос с живыми биениями.
    // Дальше они расходятся: сперва в интервалы, потом в треск и шум.
    let x = 0, ток = 0, всего = 0;
    for (let i = 0; i < 3; i++){
      const г = this.узлы[i];
      const fi = f * (1 + p.развод * this.сб.разв[i]);
      // Монтажная ёмкость: развязки между узлами на плате нет и не было,
      // соседний узел подтягивает конденсатор через паразитную связь.
      const сосед = this.узлы[(i + 1) % 3];
      // Связь тем сильнее, чем дальше разведены подстроечники: у них падает
      // сопротивление, и узлы начинают тянуть друг друга через общий монтаж.
      // Разведённая пара с сильной связью не захватывается и не бьётся ровно,
      // а идёт вразнос — это и есть шум в таких схемах, а не подмешанный
      // генератор случайных чисел.
      г.связь(сосед.v, .002 + p.развод * .004);
      x += г.шаг(fi, см, V, др) * this.сб.вес[i];
      всего += this.сб.вес[i];
      ток += г.ток;
    }
    // Общая нагрузка: все сидят на одном транзисторе, складываются ДО
    // предела. Предел РАЗНЫЙ сверху и снизу, как у однотактного каскада —
    // при симметричном ограничении остаются только нечётные продукты, и
    // разностный тон в них подавлен на −85 дБ, то есть неслышим.
    // Делим на сумму весов, а не на глазок: иначе три узла давали размах в
    // два с лишним раза выше предела, каскад упирался в него постоянно и
    // срезал все фронты разом — отсюда глухая квадратная каша вместо трёх
    // разных голосов. Теперь предел ловит только настоящие пики.
    x /= всего;
    const лимВ = .82, лимН = .95;
    if (x > лимВ) x = лимВ + (x - лимВ) * .05;
    else if (x < -лимН) x = -лимН + (x + лимН) * .12;
    this.шина.шаг(ток / 3, утечка);
    x *= .45 + .55 * clamp(V, 0, 1);

    // Разделительный конденсатор. Перекошенный импульс несёт большую
    // постоянную составляющую; без него качели катали бы всю дорожку
    // вверх-вниз вместо того, чтобы звучать.
    this.вч += (x - this.вч) * (12 * 2 * Math.PI / ЧД);
    x = (x - this.вч) + наводка;

    x = this.излуч.шаг(x, p.удар, утечка);

    // RC монтажа: провода и корпус. Это номинал сборки, а не орган.
    const α = 1 - Math.exp(-2 * Math.PI * this.сб.срез / ЧД);
    this.лп += (x - this.лп) * clamp(α, .0005, .95);

    // мера беспорядка: разброс интервалов между щелчками медленного узла
    this.сЩ++;
    if (this.качели.медл.щелчок > 0){
      if (this.сЩ > 4 && this.сЩ < ЧД * 8){
        this.инт[this.интИ = (this.интИ + 1) % this.инт.length] = this.сЩ;
        if (this.интN < this.инт.length) this.интN++;
      }
      this.сЩ = 0;
    }
    // Уровень выставлен так, чтобы прибор НИ В КАКОМ положении ручек не
    // упирался в потолок дорожки. До этого он клиппил всегда, на любых
    // настройках, и весь характер срезался об единицу — это слышалось как
    // грязная бедность и «одна волна».
    this.вых = this.лп * .34;
    return this.вых;
  }

  мера(){
    if (this.интN > 4){
      let сум = 0;
      for (let i = 0; i < this.интN; i++) сум += this.инт[i];
      const ср = сум / this.интN;
      let д = 0;
      for (let i = 0; i < this.интN; i++){ const t = this.инт[i] - ср; д += t * t; }
      this.разбр = ср > 1 ? Math.sqrt(д / this.интN) / ср : 0;
      this.гц = ЧД / ср;
    }
  }

  живой(){
    for (const г of [...this.узлы, this.качели.медл, this.качели.гул])
      if (!(г.v === г.v)){ г.v = .4; г.q = 1; г.сгл = 0; }
    if (!(this.лп === this.лп)) this.лп = 0;
    if (!(this.излуч.ход === this.излуч.ход)){ this.излуч.ход = 0; this.излуч.скорость = 0; }
    this.шина.V = clamp(this.шина.V, .2, 1);
  }
}

// ---- ПРОЦЕССОР -------------------------------------------------------------
class Хаос extends AudioWorkletProcessor {
  constructor(){
    super();
    this.пр = new Прибор(1);
    this.рука = new Рука();
    // Ровно семь величин, и каждая — орган на панели. Ничего служебного:
    // всё остальное живёт в сборке, потому что на приборе оно впаяно.
    this.p = { качание:.55, характер:.5, размах:.75,
               импульс:.2, дребезг:.15, удар:.35,
               развод:.15, гуляние:0 };
    this.пл = new Float32Array(9);
    this.свод = new Свод();
    this.пик = 0; this.отчёт = 0; this.окно = 0; this.срывы = 0;
    // Осциллограмма пишется не подряд, а с шагом под текущую высоту: в
    // кадре всегда около двух периодов волны. Иначе на низах в буфер
    // попадала пятая часть периода, и фазовый портрет вырождался в отрезок.
    this.осц = new Float32Array(256); this.осцИ = 0; this.осцШ = 0;
    this.след = new Float32Array(200); this.слИ = 0; this.проре = 0;

    this.port.onmessage = e => {
      const d = e.data;
      if (d.t === 'p'){ for (const k in d.v) if (k in this.p) this.p[k] = clamp(d.v[k], 0, 1); }
      else if (d.t === 'площадки'){ for (let i = 0; i < 9; i++) this.пл[i] = d.v[i] || 0; }
      else if (d.t === 'семя'){ this.пр = new Прибор(d.v); this.свод = new Свод(); }
      else if (d.t === 'толчок'){
        for (const г of this.пр.узлы) г.v += (Math.random() - .5) * .4;
      }
    };
  }

  process(_, outputs){
    const oL = outputs[0][0], oR = outputs[0][1], n = oL.length, p = this.p;
    const утечка = this.рука.шаг(this.пл);
    this.пр.шина.минута(n);

    for (let s = 0; s < n; s++){
      // цепь идёт вчетверо чаще, наружу выходит сведённое
      let y = 0;
      for (let k = 0; k < КРАТ; k++) y = this.свод.шаг(this.пр.шаг(p, утечка, this.рука.наводка));
      if (!(y === y)){ y = 0; this.пр.живой(); this.свод = new Свод(); this.срывы++; }
      y = clamp(y, -1, 1);
      if (++this.окно >= SR * .25){ this.окно = 0; this.пр.мера(); }
      const a = y < 0 ? -y : y;
      if (a > this.пик) this.пик = a;
      oL[s] = y; oR[s] = y;
      const шагО = clamp(Math.round(SR / (Math.max(20, this.пр.осн.f) * 128)), 1, 64);
      if (++this.осцШ >= шагО){ this.осцШ = 0;
        this.осц[this.осцИ = (this.осцИ + 1) & 255] = y; }
      if (++this.проре >= SR / 100){ this.проре = 0;
        this.след[this.слИ] = this.пр.качели.u; this.слИ = (this.слИ + 1) % 200; }
    }

    this.отчёт += n;
    if (this.отчёт >= SR / 30){
      this.отчёт = 0;
      const л = new Float32Array(200);
      for (let i = 0; i < 200; i++) л[i] = this.след[(this.слИ + i) % 200];
      const сб = this.пр.сб;
      this.port.postMessage({
        пик: this.пик, разброс: this.пр.разбр, гц: this.пр.гц || 0,
        период: this.пр.качели.период,
        высота: this.пр.осн.f || 0, скважность: this.пр.осн.скв,
        шина: this.пр.шина.V, срывы: this.срывы, батарея: this.пр.шина.заряд,
        осц: this.осц.slice(), след: л,
        качели: this.пр.качели.u, гуляние: this.пр.качели.g,
        сборка: { имя: сб.имя, излучатель: сб.fИзл, фронт: сб.фронт,
                  петля: сб.петля, срез: сб.срез },
        пл: Array.from(this.пл), утечка
      });
      this.пик *= .6;
    }
    return true;
  }
}
registerProcessor('хаос', Хаос);
