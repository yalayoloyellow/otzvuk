// Разыгрывание кармана из семени: жанр — рамки, семя — точка внутри.
// rnd — посевной генератор (mul32), чтобы карман был свойством пресета.
export function pickGroove(profile,rnd){
  const G=GROOVE[profile]; if(!G) return null;
  const fam=G.fam[(rnd()*G.fam.length)|0];
  const R=v=>Array.isArray(v)?v[0]+rnd()*(v[1]-v[0]):v;
  return {
    name:fam.name,
    swing:R(fam.swing),
    late:{kick:R(fam.late.kick), snare:R(fam.late.snare),
          hat:R(fam.late.hat),   clap:R(fam.late.clap)},
    jit:fam.jit, wander:fam.wander, human:fam.human,
    acc:G.acc
  };
}
