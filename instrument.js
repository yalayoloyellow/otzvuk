  // захвате 4:1 разброс вырос до 0.379, потому что период перескакивает
  // между соседними кратными, хотя фаза стоит. Разброс мерит период, захват
  // живёт в фазе.
  //
  // Молчит, пока на входе ничего не бьёт: числу неоткуда взяться, и лучше
  // пусто, чем висящее старое.
  const sc = report.scepka || 0;
  const сцеп = sc > .04
    // Сцепка — про саму схему, значит зелёная. Синим она принадлежала голосу
