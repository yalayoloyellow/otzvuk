  const r=report.razbros||0;
  // РЕЖИМ остаётся: это единственное, что говорит, где прибор находится по
  // хаосу — идёт ровно, дышит, гуляет или уже разваливается.
  // Под удержанием замер по фронтам стоит, и режим с темпом — последние
  // померенные, а не живые. Числу висеть можно (период и правда тот, где
  // замерли), но подписать надо честно.
  const rezhim = switches.derzhi ? 'держим'
    : r<.02?'ровно' : r<.10?'дышит' : r<.28?'гуляет' : r<.55?'край':'распад';
