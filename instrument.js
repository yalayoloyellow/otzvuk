// граница горящей части поплыла бы и шкала соврала бы про значение.
//
// У КРАСНОЙ И СИНЕЙ ШКАЛЫ ХВОСТ ЗЕЛЁНЫЙ — и это не уступка, а ровно то же
// правило, что в картине: слабый свет принадлежит прибору, цветом помечено
// только сильное. Правило «акцент не ниже третьей ступени» тут работает само
// и ничего не запирает; запирало оно, пока у шкалы не было спада — плоской
// шкале и правда некуда разложиться, кроме как в две ступени.
const SPAD=3, NIZ_HVOSTA=1;
// Гребень: сила в ступенях и ширина в знакоместах. Сила чуть меньше ступени —
// он поднимает знак ровно на одну, и только в самой середине.
// Сила больше двух ступеней и ширина меньше знакоместа: в каждый миг поднят
// РОВНО ОДИН знак, и поднят заметно. Так это читается искрой, бегущей по
// шкале, а не общим подрагиванием — соседи при этом стоят на месте.
const VOLNA_SILA=2.2, VOLNA_SHIR=.95;
// Свет по непрерывной ступени: между соседними подошвами линейно, выше
// верхней — с запасом.
function poStupeni(T, L){
  if(T>=4) return L[4]*(1+.5*(T-4));
  const t=T|0;
  return L[t]+(L[t+1]-L[t])*(T-t);
}
function ppole(){
  if(!PEKRAN || !GRANI[0]) return;
  // Подошвы ступеней по возрастанию; нулевая — та же граница отрисовки, что
  // и у фигуры.
  // ЛЕСТНИЦА ПАНЕЛИ НЕ ИМЕЕТ ПРАВА СХЛОПНУТЬСЯ В СТУПЕНЬКУ.
  //
  // Ступени считаются ПО РАНГУ от картины: доли 10, 20, 30, 38 и 46 процентов
  // от числа горящих знакомест. Пока их тысячи, всё честно. Но стоит прибору
  // притихнуть — мастер в нуле, питание снято, — и горят единицы: все пять
  // целей округляются в единицу, первая же непустая корзина удовлетворяет их
  // разом, и пять подошв получают ОДНО значение.
  //
  // Картине это безразлично, там и смотреть не на что. А панель от этого
  // загоралась целиком: дорожка шкалы считается между двумя нижними подошвами,
  // и когда они равны верхней, каждое знакоместо оказывается выше верхней
  // ступени. Ровно это он и увидел — нулевая громкость, а всё горит.
  //
  // Чиним ЗДЕСЬ, а не в общем счёте ступеней: там ранговая лестница и правда
  // узкая, и подменять её ровной сеткой значит потерять глубину картины.
  // Панели же нужна просто различимая лестница, и если пришедшая выродилась —
  // строим свою от нижней подошвы.
  // У ПАНЕЛИ СВОЯ ЛЕСТНИЦА, ПОСТОЯННАЯ. Прежде она бралась от картины — от
  // ранговых границ её гистограммы, — и потому ходила под ногами каждый
  // отчёт. Значение знакоместа задаётся ступенью лестницы, порог рисования
  // задаётся ею же, и когда она дышит, знаки перекладываются между слоями
  // при полностью неподвижном значении ручки. Замер это и показал: сильнее
  // всех дрожали самые ДЛИННЫЕ шкалы — MASTER, SWING, DEPTH, RATE, — причём
  // у MASTER значение вообще не двигается.
  //
  // Картине ранговая лестница нужна: там сотни знакомест и живая
  // гистограмма. Панели нужна просто различимая пятиступенчатая рампа, и
  // держать её надо неподвижной — тогда шкала стоит, пока не двинется само
  // значение.
  const L0=POROG_GOR;
  let L=[L0, L0*1.7, L0*2.9, L0*4.9, L0*8.4];
  // ПЕРЕКЛЮЧЕНИЕ ЛЕСТНИЦЫ — С ГИСТЕРЕЗИСОМ. Прежде порог был один: стоило
  // картине задышать у самой черты, и панель перекладывалась с пришедшей
  // лестницы на свою и обратно КАЖДЫЙ отчёт. А лестница задаёт значение
  // каждому знакоместу разом — то есть вся панель разом меняла ступени.
  // Замер: до двух с половиной тысяч знакомест за кадр, и это читалось как
  // поломанное мерцание. Входим в свою лестницу ниже трёх, выходим выше
  // четырёх — между ними держим то, что уже стоит.

  const gdor=(L[1]+L[0])*.5;
  // PU ШАГАЕТ ОДНИМИ ЧАСАМИ — в kartina, на отчёт. Здесь стояла его копия, а
  // эта функция зовётся на КАДР: одна переменная шагала девяносто раз в
  // секунду на шестидесяти герцах и полтораста на ста двадцати, постоянная
  // сглаживания выходила 185 мс против 111, и через PU это уезжало и в форму
  // существа, и в дыхание шкал — прибор выглядел по-разному на разных
  // мониторах. Ровно эту болезнь проект уже лечил у послесвечения.
  const u=PU;
  const shina=clamp(report.shina??1,0,1);
  // Дыхание считается В СТУПЕНЯХ, а не в разах: качели ведут весь спад на
  // полступени вверх-вниз, просадка шины подсаживает его целиком.
  const dyh=(u-.5)*.7-(1-shina)*1.4;
  // ХОД ФАЗЫ — ПО ЧАСАМ, А НЕ ПО КАДРАМ. Кадры на разных мониторах идут с
  // разной частотой, и привязка к ним делала бы волну быстрее на сто
  // двадцати герцах. Один проход по шкале за один оборот медленного
  // генератора: период берётся живой, из отчёта.
  const сейчас=performance.now();
  const шаг=volnaBylo ? Math.min(.1,(сейчас-volnaBylo)/1000) : 0;
  volnaBylo=сейчас;
  // Проход — за два оборота генератора, и не быстрее полусекунды: на быстрых
  // сборках период падает до полутора десятых, и искра превратилась бы в
  // строб. Медленнее восьми секунд тоже незачем — движение перестаёт читаться.
  volnaFaza=(volnaFaza+шаг/clamp((report.period||.5)*2,.5,8))%1;
  for(let c=0;c<PPOLE.length;c++) PPOLE[c].fill(0);
  for(const s of SHKALY){
    if(s.x===undefined || s.y>=PV) continue;
    const p=PPOLE[s.zona], baz=s.y*PSH+s.x;
    // Гребень входит слева и уходит вправо за край: путь длиннее шкалы на
    // две ширины колокола с каждой стороны, иначе он рождался и умирал
    // прямо на знаке.
    const put=s.sh+VOLNA_SHIR*4;
    const grebenj=((volnaFaza+s.y*.13)%1)*put-VOLNA_SHIR*2;
    for(let i=0;i<s.sh;i++){
      const j=baz+i;
      if(j<0||j>=p.length) continue;
      // Погасшая часть — дорожка, и она ЦВЕТОМ СВОЕЙ ЗОНЫ. Зелёной она была,
      // пока панель жила по правилу картины; на панели зона красная целиком.
      // РУЧКА В НУЛЕ ВСЁ РАВНО ГДЕ-ТО СТОИТ. При нулевом значении не горело
      // ни одного знака — вся шкала была ровной дорожкой, и по ней нельзя
      // было отличить «ручка в нуле» от «шкалы тут нет вовсе». Ставим
      // указатель на первом знакоместе: он тусклее острия, но ярче дорожки.
      if(i>=s.n){ p[j] = (s.n===0 && i===0) ? poStupeni(2,L) : gdor; continue; }
      // Остриё держит верхнюю ступень всегда: им отмечено значение, и мигать
      // ему нельзя. Дышит и дрожит хвост — сменой знака, а не длиной.
      const d=s.n-1-i;
      let T=4.4;
      if(d){
        // Дрожь идёт ВОЛНОЙ вдоль шкалы. Шаг фазы на знакоместо был 1.9 рад:
        // соседние оказывались почти в противофазе, и спад рассыпался в рябь
        // 2-3-2-3-4 — рядом стоящие знаки прыгали через ступень. При 0.55 рад
        // волна укладывается в длину шкалы примерно за период, и ряд читается
        // ровно: 1-1-1-2-2-2-3-3-4.
        // Волна замедлена вчетверо: при ugol*9 она пробегала шкалу за
        // секунду, и это читалось не как дыхание, а как рябь.
        // ГРЕБЕНЬ, А НЕ РЯБЬ. Прежняя волна была синусом по всем знакам разом:
        // соседи оказывались в разных фазах и скакали вразнобой. Теперь по
        // шкале идёт ОДИН узкий гребень — колоколом в полтора знакоместа, —
        // и в каждый миг подсвечен один-два знака. Он движется медленно и
        // предсказуемо, поэтому читается как движение, а не как мерцание.
        const рас = i - grebenj;
        T=4-d/SPAD+dyh+VOLNA_SILA*Math.exp(-рас*рас/(2*VOLNA_SHIR*VOLNA_SHIR));
        T=T>4?4:T<NIZ_HVOSTA?NIZ_HVOSTA:T;
      }
      // Остриё (d===0) держит верхнюю ступень и памяти не требует.
      if(d){
        const был=PSTUP[j];
        if(был<0 || T>был+.5+GIST_STUP || T<был-.5-GIST_STUP)
          PSTUP[j]=Math.round(T);
        p[j]=poStupeni(PSTUP[j],L);
      } else p[j]=poStupeni(T,L);
    }
  }
  // Рисуем по ТОЙ ЖЕ лестнице, по какой считали свет, иначе ступени разойдутся.
  PEKRAN.risuy(PPOLE, [L[4],L[3],L[2],L[1],L[0]]);
}

// ЛЕГЕНДА СОБИРАЕТСЯ ИЗ ТАБЛИЦ, а не пишется руками. Написанная руками она
// расходится с прибором на первой же перекладке клавиш — и разошлась: в ней
// висели буквы, давно отданные под ручки. Теперь расходиться ей не с чем.
function klavisha(kod){
  return IMYAKL[kod] || {Tab:'tab', Space:'пробел', Enter:'⏎', Escape:'esc'}[kod]
      || kod.replace('Key','').toLowerCase();
}
function legenda(){
  // ЛЕГЕНДА ПЕРЕЧИСЛЯЕТ ТОЛЬКО ТО, ЧЕГО НЕТ НА ПАНЕЛИ. У каждой ручки и
  // каждого тумблера клавиша написана рядом с ним же — повторять их внизу
  // значит заполнять экран тем, что и так видно. Остаются команды: у них
  // своей строки нет и быть не может, потому что они не величины.
  // Клавиша без подписи примыкает к предыдущей: ↑ и ↓ делают одно дело в две
  // стороны, и «↑ листать · ↓ листать» было бы враньём про два разных дела.
  const kom=[];
  for(const k of KOMANDY){
    // ПОМЕЧЕННОЕ НА ПАНЕЛИ В ЛЕГЕНДУ НЕ ИДЁТ. Семь клавиш стояли дважды:
    // метроном подписан у CHOP, фраза у PHRASE, дорожка у TRACK, микрофон и
    // система в строке INPUT, сохранение и удаление у сборки. Легенда
    // объявляет, что перечисляет только то, чего на панели нет, — теперь она
    // это и делает, а признак стоит у самой команды, а не списком в стороне.
    if(k.naPaneli) continue;
    const kl=`${k.ctrl?'\u2303':''}${k.alt?'\u2325':''}${k.shift?'\u21e7':''}${klavisha(k.kl)}`;
    if(!k.imya && kom.length) kom[kom.length-1]=kom[kom.length-1].replace(' ', ' '+kl+' ');
    else kom.push(`${kl} ${k.imya}`);
  }
  kom.push('1\u20130 - = площадки', '\u2423 ладонь', '\u2318 втрое', '\u21e7 вдесятеро');
  // ЦВЕТ ОБЪЯСНЯЕТ СЕБЯ САМ. Строка «красное — работа поста, синее — голос»
  // стояла тут потому, что зон не было; теперь зелёные, синие и красные
  // ручки лежат отдельными блоками, и подпись под картиной повторяет то,
  // что и так видно сверху.
  return `<span class="z1">${kom.join(' \u00b7 ')}</span>`;
}

